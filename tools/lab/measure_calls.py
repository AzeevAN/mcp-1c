"""Разведочный замер: во что обойдётся индекс вызовов («где используется»).

Разведка 2026-08-18 сняла сигнатуры, поиск и формы. Вызовы не мерил никто, а
искать вхождения имени по 260 МБ текста на каждый запрос — секунды, значит
индекс придётся строить заранее и хранить. Сколько он весит — и решает,
влезаем ли мы в память вообще.

Меряется на отобранном коде тома (`data/modules/<Конфигурация>`), а не на
развёрнутом архиве: провайдер будет читать именно его.

Сборка и подъём — **разные процессы**, как в `measure_resident.py`. Пик разбора
и резидентная цена — разные величины: после чтения 260 МБ текста RSS обратно не
опускается, и замер «собрал и посмотрел RSS» меряет аллокатор, а не индекс.

Варианты отбора вызовов:

    квалифицированные  только `Модуль.Метод(` — дёшево и точно, но слепо к
                       вызовам внутри своего модуля
    известные          любой `Метод(`, чьё имя объявлено где-то в корпусе
    экспортные         то же, но цель обязана быть экспортной

Формы хранения при подъёме: `компактная` (таблица модулей + `array('i')`
плоскими парами) и `наивная` (список кортежей). Разница между ними — это и
есть разница между «влезаем» и «не влезаем».

Запуск:

    python3 tools/lab/measure_calls.py КОРЕНЬ известные собрать ФАЙЛ
    python3 tools/lab/measure_calls.py КОРЕНЬ известные поднять ФАЙЛ компактная
    python3 tools/lab/measure_calls.py КОРЕНЬ известные поднять ФАЙЛ наивная
    python3 tools/lab/measure_calls.py КОРЕНЬ - налету        # сколько стоит без индекса
    python3 tools/lab/measure_calls.py КОРЕНЬ - оглавление    # базовая линия
"""
import array
import gc
import marshal
import os
import random
import re
import subprocess
import sys
import time
from pathlib import Path

КОРЕНЬ = Path(sys.argv[1])
ВАРИАНТ = sys.argv[2] if len(sys.argv) > 2 else "известные"
ЭТАП = sys.argv[3] if len(sys.argv) > 3 else "собрать"
ФАЙЛ = Path(sys.argv[4]) if len(sys.argv) > 4 else Path("data/lab/calls.marshal")
ФОРМА = sys.argv[5] if len(sys.argv) > 5 else "компактная"

ОБЪЯВЛЕНИЕ = re.compile(
    r"^\s*(Процедура|Функция|Procedure|Function)\s+([А-Яа-яЁёA-Za-z_][\w]*)\s*\(([^)]*)\)\s*(Экспорт|Export)?",
    re.IGNORECASE | re.MULTILINE,
)

# Вызов: необязательный квалификатор перед точкой и имя перед скобкой.
ВЫЗОВ = re.compile(r"(?:([А-Яа-яЁёA-Za-z_]\w*)\s*\.\s*)?([А-Яа-яЁёA-Za-z_]\w*)\s*\(")

# Слова языка, за которыми скобка не означает вызова процедуры. Вариантам
# «известные»/«экспортные» фильтр по корпусу их снимает и так; список нужен
# «квалифицированным», где корпуса нет.
КЛЮЧЕВЫЕ = {
    "если", "иначеесли", "пока", "для", "возврат", "новый", "выполнить",
    "вычислить", "исключение", "тогда", "цикл", "и", "или", "не",
    "if", "elsif", "while", "for", "return", "new", "execute", "eval",
    "процедура", "функция", "procedure", "function",
}


def rss_мб() -> float:
    """Текущий RSS, а не пик: `ru_maxrss` пик обратно не отпускает."""
    вывод = subprocess.run(["ps", "-o", "rss=", "-p", str(os.getpid())],
                           capture_output=True, text=True).stdout.strip()
    return int(вывод) / 1024  # ps отдаёт КБ и на macOS, и на Linux


def файлы() -> list[Path]:
    return sorted(КОРЕНЬ.rglob("*.bsl")) or sorted(КОРЕНЬ.rglob("*.txt"))


def без_комментария(строка: str) -> str:
    """Хвост после `//` отбрасывается.

    Наивно: `//` внутри строкового литерала тоже срежет. Для замера объёма это
    даёт занижение единицами процентов; настоящему провайдеру так нельзя.
    """
    поз = строка.find("//")
    return строка if поз < 0 else строка[:поз]


def собрать_оглавление(пути: list[Path]) -> tuple[int, set, set]:
    """Имена объявленных процедур: все и экспортные."""
    все, экспортные = set(), set()
    объявлений = 0
    for путь in пути:
        текст = путь.read_text(encoding="utf-8-sig", errors="replace")
        for m in ОБЪЯВЛЕНИЕ.finditer(текст):
            имя = m.group(2).lower()
            все.add(имя)
            объявлений += 1
            if m.group(4):
                экспортные.add(имя)
    return объявлений, все, экспортные


def печать(заголовок: str, **числа) -> None:
    print(f"\n== {заголовок}")
    for ключ, значение in числа.items():
        подпись = ключ.replace("_", " ")
        if isinstance(значение, float):
            print(f"{подпись:<24}: {значение:,.1f}".replace(",", " "))
        elif isinstance(значение, int):
            print(f"{подпись:<24}: {значение:,}".replace(",", " "))
        else:
            print(f"{подпись:<24}: {значение}")


# --- подъём: отдельный процесс, честная резидентная цена ----------------------

if ЭТАП == "поднять":
    пустой = rss_мб()
    начало = time.monotonic()
    сырое = marshal.loads(ФАЙЛ.read_bytes())
    модули = сырое["модули"]
    if ФОРМА == "компактная":
        индекс = {}
        for ключ, байты in сырое["места"].items():
            массив = array.array("i")
            массив.frombytes(байты)
            индекс[ключ] = массив
    else:
        индекс = {}
        for ключ, байты in сырое["места"].items():
            массив = array.array("i")
            массив.frombytes(байты)
            индекс[ключ] = [(массив[i], массив[i + 1])
                            for i in range(0, len(массив), 2)]
    del сырое
    подъём = time.monotonic() - начало
    gc.collect()
    с_индексом = rss_мб()

    ключи = random.Random(20260820).sample(sorted(индекс), min(200, len(индекс)))
    начало = time.monotonic()
    мест = 0
    for ключ in ключи:
        места = индекс[ключ]
        мест += (len(места) // 2) if ФОРМА == "компактная" else len(места)
    латентность = (time.monotonic() - начало) / max(1, len(ключи)) * 1000

    печать(f"подъём индекса вызовов — {ВАРИАНТ}, форма {ФОРМА}",
           целей=len(индекс), модулей=len(модули),
           подъём_с=подъём,
           RSS_пустой_МБ=пустой, RSS_с_индексом_МБ=с_индексом,
           цена_индекса_МБ=с_индексом - пустой,
           латентность_мс=латентность, мест_в_выборке=мест)
    sys.exit(0)


пути = файлы()
print(f"корень            : {КОРЕНЬ}")
print(f"файлов кода       : {len(пути):,}".replace(",", " "))

# --- базовая линия -----------------------------------------------------------

if ЭТАП == "оглавление" or ВАРИАНТ == "оглавление":
    начало = time.monotonic()
    объявлений, все, экспортные = собрать_оглавление(пути)
    печать("оглавление",
           объявлений=объявлений, уникальных_имён=len(все),
           экспортных_имён=len(экспортные),
           сборка_с=time.monotonic() - начало)
    sys.exit(0)

# --- сколько стоит вопрос без индекса ----------------------------------------

if ЭТАП == "налету" or ВАРИАНТ == "налету":
    объявлений, все, экспортные = собрать_оглавление(пути)
    цели = random.Random(20260820).sample(sorted(экспортные), 5)
    времена = []
    for цель in цели:
        игла = re.compile(r"\b" + re.escape(цель) + r"\s*\(", re.IGNORECASE)
        начало = time.monotonic()
        найдено = 0
        for путь in пути:
            найдено += len(игла.findall(
                путь.read_text(encoding="utf-8-sig", errors="replace")))
        времена.append(time.monotonic() - начало)
        print(f"  {цель:<44} вхождений {найдено:>6}  {времена[-1]:.2f} с")
    печать("поиск без индекса",
           запросов=len(времена),
           медиана_с=sorted(времена)[len(времена) // 2],
           худший_с=max(времена))
    sys.exit(0)

# --- сборка ------------------------------------------------------------------

фильтр_целей: set[str] = set()
if ВАРИАНТ in ("известные", "экспортные"):
    начало = time.monotonic()
    объявлений, все, экспортные = собрать_оглавление(пути)
    фильтр_целей = экспортные if ВАРИАНТ == "экспортные" else все
    print(f"оглавление        : {объявлений:,} объявлений, "
          f"целей в фильтре {len(фильтр_целей):,}, "
          f"{time.monotonic() - начало:.1f} с".replace(",", " "))

места: dict[str, array.array] = {}
модули: list[str] = []
рёбер = 0

начало = time.monotonic()
for индекс_модуля, путь in enumerate(пути):
    модули.append(str(путь.relative_to(КОРЕНЬ)))
    текст = путь.read_text(encoding="utf-8-sig", errors="replace")
    for номер, строка in enumerate(текст.splitlines(), 1):
        строка = без_комментария(строка)
        if "(" not in строка:
            continue
        for m in ВЫЗОВ.finditer(строка):
            квалификатор, имя = m.group(1), m.group(2)
            низкое = имя.lower()
            if ВАРИАНТ == "квалифицированные":
                if not квалификатор or низкое in КЛЮЧЕВЫЕ:
                    continue
                ключ = f"{квалификатор.lower()}.{низкое}"
            else:
                if низкое not in фильтр_целей:
                    continue
                ключ = низкое
            запись = места.get(ключ)
            if запись is None:
                запись = места[ключ] = array.array("i")
            запись.append(индекс_модуля)
            запись.append(номер)
            рёбер += 1
    del текст

сборка = time.monotonic() - начало

ФАЙЛ.parent.mkdir(parents=True, exist_ok=True)
ФАЙЛ.write_bytes(marshal.dumps({
    "модули": модули,
    "места": {ключ: массив.tobytes() for ключ, массив in места.items()},
}))

печать(f"сборка индекса вызовов — {ВАРИАНТ}",
       рёбер=рёбер,
       уникальных_целей=len(места),
       мест_на_цель=рёбер / max(1, len(места)),
       сборка_с=сборка,
       на_диске_МБ=ФАЙЛ.stat().st_size / 1024 / 1024,
       пик_процесса_МБ=rss_мб())
