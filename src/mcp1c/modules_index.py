@dataclass(slots=True)
class Форма:
    """Одна форма, собранная по запросу из массивов `Формы`.

    `битая` нужна в публичном состоянии формы: без поля тест «битый Form.xml не роняет
    разбор» нечем было бы проверить снаружи, а прятать признак битости
    только во флаге индекса значило бы отдавать наружу пустую форму,
    неотличимую от настоящей пустой.

    `события` — `dict[str, tuple[str, ...]]`, не одиночная строка.
    На живой выгрузке 12 процедур из 23 210 привязок
    объявлены обработчиком ДВУХ разных событий (например,
    `BeforeLoadDataFromSettingsAtServer` и `OnLoadDataFromSettingsAtServer`
    — обе на одну процедуру), и `dict[str, str]` в исходной версии кода
    отдавал только последнюю привязку по порядку обхода XML — причём
    `состав` и `обработчик` расходились между собой (словарь оставлял
    последнюю пару, `обработчик` возвращал первую по раннему `return`):
    один и тот же вопрос имел два разных ответа в одном и том же индексе.
    Кортеж хранит все РАЗЛИЧНЫЕ события процедуры в порядке первого
    появления в XML — без дублей: одна и та же процедура нередко висит на
    одном и том же событии сразу у нескольких элементов (общий обработчик
    `ПриИзменении` на десяти полях), и повторение одного и того же имени
    события в кортеже не добавляет агенту знания, только дублирует его.
    Точные владельцы этих событий не теряются: новый массив привязок хранит
    элемент отдельно, а прежнее поле остаётся совместимым кратким видом.
    """

    реквизиты: list[str]
    элементы: list[str]
    события: dict[str, tuple[str, ...]]
    битая: bool
    структура_доступна: bool = True
    структура_частична: bool = False
    маркер: int | None = None
    состояние_xml: str = "missing"
    идентификатор: str | None = None
    имя: str | None = None
    синоним: str | None = None
    тип: str | None = None


