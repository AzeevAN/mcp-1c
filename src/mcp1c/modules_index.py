"""Оглавление процедур корпуса: сборка с диска, хранение, подъём.

Первая настоящая структура провайдера `modules` (design doc, раздел 4): на
ней держатся поиск процедур, «кто вызывает» и выдача тела. Строится проходом
по выгрузке — `bsl_lex.разобрать` даёт границы и `Экспорт`, `module_address.
адрес_модуля` переводит путь файла в адрес на языке метаданных.

**Хранение — параллельные массивы, а не список объектов на процедуру.**
Замерено на живой конфигурации (137 116 процедур): кортежи с текстом
сигнатуры — 128 МБ, параллельные массивы без сигнатуры — 62 МБ. Разница не
в форме массива, а в том, что каждая процедура кортежами заводит отдельный
Python-объект (кортеж + строки внутри), а `array('i')` хранит числа плотно,
без объектной обвязки на каждый элемент.

**Сигнатура принципиально не хранится.** Она лежит на диске в строке
объявления (поле `строка`), и чтение оттуда стоит 0,1 мс на модуль — держать
её в памяти постоянно значило бы платить +66 МБ за то, что достаётся
мгновенно по первому запросу.

**Ключ процедуры — пара «модуль + имя», а не одно имя.** `ПриСозданииНаСервере`
объявлена в 3 003 модулях живой конфигурации; `Запись`, отданная по одному
только имени, была бы неполной и выглядела бы как полный ответ.

**Вид (процедура или функция) — бит в тех же флагах, не отдельный массив.**
Design doc (раздел 4) перечисляет `вид[i]` в одном ряду со `строка`/`конец`/
`флаги` — в интерфейсе этой задачи поле сначала не завели, это пробел брифа,
закрытый по ревью. Отдельный `array('i')` стоил бы ещё +0,5 МБ на живом
корпусе ради одного бита на запись; вместо этого — пятый бит в `_флаги`
(`ФУНКЦИЯ`), цена которого ноль: тот же массив, тот же файл на диске. Нужен
не для полноты — у функции есть возвращаемое значение, у процедуры нет, и
агент, составляющий вызов, обязан различать это до чтения сигнатуры с диска;
не отдавать вид значило бы вынуждать потребителя гадать по имени процедуры
(«ПолучитьСумму» — наверное, функция?), а такая догадка не гарантирована
ничем и на живом корпусе будет ошибаться.

Подъём с диска (`прочитать`) обязан идти через `array.frombytes()` без
промежуточных списков: первая версия строила `list(marshal.loads(...))` и
только потом `array('i', список)` — на этом пути измерение показало 97 МБ
вместо 62. Причина — мусор аллокатора: список из миллиона `int` держит
миллион отдельных объектов, пусть и временно, и аллокатор память под них не
возвращает ОС сразу же после того, как список отброшен.
"""
from __future__ import annotations

import marshal
import re
import sys
import xml.etree.ElementTree as ET
from array import array
from dataclasses import dataclass
from pathlib import Path

from . import index_cache
from .bsl_lex import прочитать_модуль, разобрать
