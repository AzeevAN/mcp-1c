def test_лишний_сегмент_с_шаблоном_не_совпадает(tmp_path):
    ответ = get_syntax(_реестр(tmp_path), "Справочники.Номенклатура.Вложенный.ПустаяСсылка")

    assert "Шаблон справки для" not in ответ


def test_нет_шаблона_прежний_ответ(tmp_path):
    ответ = get_syntax(_реестр(tmp_path), "Справочники.Номенклатура.НетТакого")

    assert "Шаблон справки для" not in ответ
    assert "Точного совпадения нет" in ответ or "нет элемента" in ответ
