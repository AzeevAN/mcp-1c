"""Подсказки «нет такого объекта»: близкие имена того же вида, потом полнотекстовый поиск."""

from __future__ import annotations

import re

from mcp1c import tools
from mcp1c.model import Configuration, MetadataObject
from mcp1c.registry import Registry, RegistryError

from conftest import write_export

ДОКУМЕНТ = "Документ.РеализацияТоваровУслуг"


def _объект(вид: str, имя: str) -> MetadataObject:
    return MetadataObject(f"{вид}.{имя}", вид, имя)


def _конфигурация(имя: str, объекты: list[tuple[str, str]]) -> Configuration:
    конфигурация = Configuration(name=имя)
    конфигурация.objects = {
        f"{вид}.{название}": _объект(вид, название) for вид, название in объекты
    }
    return конфигурация


def _реестр(tmp_path, конфигурации: dict[str, list[tuple[str, str]]]) -> Registry:
    реестр = Registry(tmp_path / "data")
    for имя, объекты in конфигурации.items():
        папка = tmp_path / f"выгрузка-{имя}"
        папка.mkdir()
        реестр.add_configuration(write_export(папка, _конфигурация(имя, объекты)))
    return реестр


ОСНОВНЫЕ = [
    ("Документ", "РеализацияТоваровУслуг"),
    ("Документ", "ПоступлениеТоваров"),
    ("Справочник", "РеализацияТоваровУслугСклад"),
    # Другой вид с почти тем же именем: полнотекстовый поиск ставит его первым.
    ("Справочник", "РеализацияТоваровУслу"),
]


def _ответ(вызов) -> str:
    """Текст ответа «нет объекта»: строка ответа или текст RegistryError."""
    try:
        return вызов()
    except RegistryError as ошибка:
        return str(ошибка)


def _подсказки(ответ: str) -> list[str]:
    return re.findall(r"^- `([^`]+)`$", ответ, re.M)


def test_опечатка_в_имени_документа(tmp_path):
    реестр = _реестр(tmp_path, {"Пример": ОСНОВНЫЕ})
    ответ = _ответ(lambda: tools.get_object(реестр, "Документ.РеализацияТоваровУслу", config="Пример"))
    assert "Возможно, имелось в виду" in ответ
    assert _подсказки(ответ)[0] == ДОКУМЕНТ


def test_нет_такого_подсказывает_только_тот_же_вид(tmp_path):
    объекты = [("Документ", f"НетТакое{суффикс}") for суффикс in
               ("Один", "Два", "Три", "Четыре", "Пять", "Шесть")]
    объекты += [("Справочник", "НетТакого"), ("Справочник", "НетТакогоСклад")]
    реестр = _реестр(tmp_path, {"Пример": объекты})
    ответ = _ответ(lambda: tools.get_object(реестр, "Документ.НетТакого", config="Пример"))
    подсказки = _подсказки(ответ)
    assert подсказки
    assert all(строка.startswith("Документ.") for строка in подсказки), подсказки


def test_get_related_подсказывает_похожие(tmp_path):
    реестр = _реестр(tmp_path, {"Пример": ОСНОВНЫЕ})
    ответ = _ответ(lambda: tools.get_related(реестр, "Документ.РеализацияТоваровУслу", config="Пример"))
    assert "Возможно, имелось в виду" in ответ
    assert ДОКУМЕНТ in _подсказки(ответ)


def test_compare_подсказывает_похожие(tmp_path):
    реестр = _реестр(tmp_path, {
        "Первая": [("Документ", "РеализацияТоваровУслуг")],
        "Вторая": [("Документ", "РеализацияТоваров"), ("Справочник", "РеализацияТоваровУслугСклад")],
    })
    ответ = tools.compare_configurations(реестр, ДОКУМЕНТ, ["Первая", "Вторая"])
    assert "**Вторая** — объекта нет" in ответ
    assert "Похожие: `Документ.РеализацияТоваров`" in ответ
    похожие = ответ.split("Похожие:", 1)[1].split("\n", 1)[0]
    assert "Справочник." not in похожие


def test_similar_objects_сначала_тот_же_вид_затем_полнотекстовый_поиск(tmp_path):
    from mcp1c.tools_code import similar_objects

    реестр = _реестр(tmp_path, {"Пример": ОСНОВНЫЕ})
    конфигурация = реестр.resolve("Пример").configuration
    найденные = similar_objects(конфигурация, "Документ.РеализацияТоваровУслу", limit=5)
    assert найденные[0] == ДОКУМЕНТ
    assert len(найденные) <= 5
    assert len(set(найденные)) == len(найденные)
    assert "Документ.РеализацияТоваровУслу" not in найденные
    assert similar_objects(конфигурация, "Документ.РеализацияТоваровУслу", limit=1) == [ДОКУМЕНТ]


def test_similar_objects_пусто_для_пустой_конфигурации(tmp_path):
    from mcp1c.tools_code import similar_objects

    реестр = _реестр(tmp_path, {"Пример": []})
    assert similar_objects(реестр.resolve("Пример").configuration, "Документ.Нет") == []


def test_существующий_объект_без_подсказок_страж(tmp_path):
    """Страж: найденный объект отвечает карточкой, а не подсказками."""
    реестр = _реестр(tmp_path, {"Пример": ОСНОВНЫЕ})
    ответ = tools.get_object(реестр, ДОКУМЕНТ, config="Пример")
    assert "нет объекта" not in ответ
    assert "Возможно, имелось в виду" not in ответ


def test_подсказки_get_object_не_содержат_запрошенное_имя(tmp_path):
    """Страж: запрошенное несуществующее имя само в подсказки не попадает."""
    реестр = _реестр(tmp_path, {"Пример": ОСНОВНЫЕ})
    ответ = _ответ(lambda: tools.get_object(реестр, "Документ.РеализацияТоваровУслу", config="Пример"))
    assert "Документ.РеализацияТоваровУслу" not in _подсказки(ответ)
