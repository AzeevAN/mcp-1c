@dataclass(slots=True)
class KeyCoverage:
    """Сколько ключей нашло свой элемент, а сколько повисло."""

    total: int = 0
    attached: int = 0
    lost: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.lost

    def as_warning(self) -> str:
        """Строка для `Source.warnings`. Пусто, когда всё привязалось."""
        if self.ok:
            return ""
        примеры = ", ".join(sorted(self.lost)[:5])
        хвост = " и ещё…" if len(self.lost) > 5 else ""
        return (
            f"поисковых ключей {self.total}, привязано {self.attached}, "
            f"потеряно {len(self.lost)}: {примеры}{хвост}. Набор страниц справки "
            "не совпал с тем, под который ключи писались — поиск по языку "
            "запросов работает хуже заявленного."
        )


def coverage(item_ids: object) -> KeyCoverage:
    """Сверить таблицу ключей с тем, что реально разобралось.

    Привязка идёт по идентификатору страницы, а он приходит из имени файла в
    `.hbk`. Справка другой платформы может дать другой набор страниц, и тогда
    часть ключей молча повиснет: поиск просядет до состояния «как без ключей»,
    но никакой ошибки не будет. Ровно тот класс дефекта, что уже ловили на
    пустом имени платформы и на скрытом по версии, выданном за ненайденное, —
    поэтому расхождение обязано быть видно при загрузке.
    """
    известные = set(item_ids)  # type: ignore[arg-type]
    lost = [key for key in SEARCH_KEYS if key not in известные]
    return KeyCoverage(
        total=len(SEARCH_KEYS),
        attached=len(SEARCH_KEYS) - len(lost),
        lost=lost,
    )


def keys_text(item_id: str) -> str:
    """Ключи элемента одной строкой для поля индекса. Пусто — ключей нет."""
    return "\n".join(SEARCH_KEYS.get(item_id, ()))
