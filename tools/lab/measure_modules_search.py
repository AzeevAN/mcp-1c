"""Разведочный замер: цена `SearchIndex` по экспортным процедурам — с шапкой
и без (задача 8, `modules-provider-design.md`, раздел 4 и 14).

`measure_search.py` снял 156 МБ на двух полях (имя, модуль) и без шапки —
раздел 14 спеки прямо называет эту цифру незамеренной для документа с
комментарием-шапкой. Здесь три варианта одного и того же документа меряются
одним и тем же кодом, чтобы разница была ценой именно шапки, а не отличием
в устройстве замера:

    без_шапки       — имя и модуль, как в исходном замере (контроль)
    шапка           — имя, модуль и комментарий-шапка целиком
    первая_строка   — имя, модуль и только первая строка шапки

Строится настоящим `Оглавление.построить` + `bsl_lex.разобрать`, не
регуляркой: шапка — многострочный комментарий с правилами накопления,
которые `bsl_lex` уже реализует (задача 3 отдельно чинила случай, когда
шапка цеплялась от чужой процедуры через пустую строку) — переизобретать их
здесь ради замера значило бы рисковать той же ошибкой заново.

Файлы без единой экспортной процедуры не читаются вовсе — то же решение,
что и в производственном `modules_index.построить_поиск`.

Каждый вариант — отдельный процесс (обычный запуск скрипта из шелла): RSS
после `gc.collect()` не заражён тем, что уже было в интерпретаторе от
предыдущего варианта.

Запуск:

    python3 tools/lab/measure_modules_search.py КОРЕНЬ без_шапки
    python3 tools/lab/measure_modules_search.py КОРЕНЬ шапка
    python3 tools/lab/measure_modules_search.py КОРЕНЬ первая_строка
"""
import gc
import os
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, "src")
from mcp1c.bsl_lex import прочитать_модуль, разобрать
from mcp1c.module_address import адрес_модуля
from mcp1c.modules_index import Оглавление
from mcp1c.search import Doc, SearchIndex


def rss_мб() -> float:
    вывод = subprocess.run(["ps", "-o", "rss=", "-p", str(os.getpid())],
                           capture_output=True, text=True).stdout.strip()
    return int(вывод) / 1024  # ps отдаёт КБ и на macOS, и на Linux


КОРЕНЬ = Path(sys.argv[1])
ВАРИАНТ = sys.argv[2] if len(sys.argv) > 2 else "шапка"
assert ВАРИАНТ in ("без_шапки", "шапка", "первая_строка"), ВАРИАНТ

начало = time.monotonic()
о = Оглавление.построить(КОРЕНЬ)
построение_оглавления = time.monotonic() - начало
gc.collect()
пустой = rss_мб()

начало = time.monotonic()
индекс = SearchIndex(field_weights={"name": 1.0, "module": 0.4, "header": 0.6})
экспортных = 0
пропущено_файлов = 0
for файл in sorted(КОРЕНЬ.rglob("*.bsl")):
    адрес = адрес_модуля(файл.relative_to(КОРЕНЬ).as_posix())
    if not any(з.экспорт for з in о.модуля(адрес)):
        пропущено_файлов += 1
        continue
    for процедура in разобрать(прочитать_модуль(файл)):
        if not процедура.экспорт:
            continue
        экспортных += 1
        поля = {"name": процедура.имя, "module": адрес}
        if ВАРИАНТ == "шапка":
            поля["header"] = процедура.шапка
        elif ВАРИАНТ == "первая_строка":
            поля["header"] = процедура.шапка.split("\n", 1)[0]
        индекс.add(Doc(id=f"{адрес}::{процедура.имя}", fields=поля,
                        payload=(адрес, процедура.имя)))
сборка = time.monotonic() - начало
del о
gc.collect()
после_сборки = rss_мб()

# Прогрев: `_finalize` замораживает постинги в массивы numpy при первом запросе.
индекс.search("проверить остатки", limit=5)
gc.collect()
после_постингов = rss_мб()

запросы = [
    "проверить остатки на складе",
    "записать движения документа",
    "заполнить по контрагенту",
]
замеры = []
for q in запросы:
    t = time.monotonic()
    hits = индекс.search(q, limit=10)
    замеры.append((time.monotonic() - t) * 1000)
    первый = hits[0].doc.id if hits else "—"
    print(f"  «{q}» -> {len(hits)} шт, первый {первый[:70]}")

print()
print(f"вариант             : {ВАРИАНТ}")
print(f"файлов пропущено    : {пропущено_файлов:,} (без единой экспортной)".replace(",", " "))
print(f"экспортных процедур : {экспортных:,}".replace(",", " "))
print(f"оглавление          : {построение_оглавления:.1f} с")
print(f"сборка индекса      : {сборка:.1f} с")
print(f"RSS пустой          : {пустой:.0f} МБ")
print(f"RSS после сборки    : {после_сборки:.0f} МБ  (+{после_сборки - пустой:.0f})")
print(f"RSS с постингами    : {после_постингов:.0f} МБ  (+{после_постингов - после_сборки:.0f})")
print(f"цена индекса всего  : {после_постингов - пустой:.0f} МБ")
print(f"латентность запроса : медиана {sorted(замеры)[len(замеры)//2]:.2f} мс, "
      f"худшая {max(замеры):.2f} мс")
