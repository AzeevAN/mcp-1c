"""`get_syntax`: конкретное имя сопоставляется с шаблоном справки.

В справке адреса записаны шаблонами: `СправочникМенеджер.<Имя справочника>.
ПустаяСсылка`. Агент спрашивает конкретным именем (`Справочники.Номенклатура.
ПустаяСсылка`) и получал «Точного совпадения нет». Первый сегмент запроса
заменяется кандидатами (сам, `+Менеджер`, `+Ссылка`, `+Объект`; множественное
число менеджера сводится к единственному по `KIND_TO_MANAGER`), а сегмент
шаблона `<…>` совпадает с любым одним сегментом.
"""

from __future__ import annotations

from mcp1c.syntax_model import SyntaxItem
from mcp1c.tools import get_syntax

from conftest import build_syntax_registry

ПЛАТФОРМА = "8.3.27.2130"


def _метод(родитель: str, имя: str, описание: str) -> SyntaxItem:
    return SyntaxItem(
        id=f"objects/{родитель}/methods/{имя}",
        kind="method",
        name_ru=имя,
        parent_ru=родитель,
        description=описание,
    )


def _реестр(tmp_path):
    return build_syntax_registry(
        tmp_path,
        [
            _метод("СправочникМенеджер.<Имя справочника>", "ПустаяСсылка", "Пустая ссылка справочника."),
            _метод("СправочникСсылка.<Имя справочника>", "Пустая", "Признак пустой ссылки справочника."),
            _метод("ДокументМенеджер.<Имя документа>", "ПустаяСсылка", "Пустая ссылка документа."),
        ],
        ПЛАТФОРМА,
    )


def test_справочники_пустая_ссылка(tmp_path):
    ответ = get_syntax(_реестр(tmp_path), "Справочники.Номенклатура.ПустаяСсылка")

    assert "СправочникМенеджер.<Имя справочника>.ПустаяСсылка" in ответ
    assert "Пустая ссылка справочника." in ответ
    assert "Шаблон справки для `Справочники.Номенклатура.ПустаяСсылка`" in ответ
    assert "Точного совпадения нет" not in ответ
    assert "ДокументМенеджер" not in ответ


def test_справочник_ед_число_пустая_ссылка(tmp_path):
    ответ = get_syntax(_реестр(tmp_path), "Справочник.Номенклатура.ПустаяСсылка")

    assert "СправочникМенеджер.<Имя справочника>.ПустаяСсылка" in ответ
    assert "Шаблон справки для `Справочник.Номенклатура.ПустаяСсылка`" in ответ
    assert "Точного совпадения нет" not in ответ


def test_документы_пустая_ссылка(tmp_path):
    ответ = get_syntax(_реестр(tmp_path), "Документы.Реализация.ПустаяСсылка")

    assert "ДокументМенеджер.<Имя документа>.ПустаяСсылка" in ответ
