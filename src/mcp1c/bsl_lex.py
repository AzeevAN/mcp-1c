"""Лексер BSL: границы процедур, сигнатура с переносом строк, `Экспорт`.

Фундамент провайдера `modules` (`docs/modules-provider-design.md`, раздел 3):
оглавление процедур, индекс вызовов и три инструмента MCP читают код через
этот модуль. Разведочный прототип лежит в `tools/lab/bsl_lex.py`; переносить
его как есть нельзя. Разбор только строки объявления терял `Экспорт` у
2 074 процедур из 49 182 — именно у самых длинных сигнатур, где перенос строк
случается чаще всего. Параметры теперь добираются до баланса скобок, и только
после закрывающей ищется `Экспорт`, даже если он оказался на другой строке.

Состояние «внутри незакрытого литерала» теперь ведётся между строками
(`_код_строки`), а не гаснет на границе строки
файла. Без этого комментарий внутри незакрытого текста запроса и директивы
правки расширения `#Вставка`/`#Удаление` теряют состояние молча — на живом
коде это стоило 184 объявлений в одном файле (design doc, раздел 3).

Поля `директива`, `перекрытие`, `шапка`, `вызовы` заполняются тем же проходом.
Имя цели перекрытия в `&ИзменениеИКонтроль("Х")` лежит строковым литералом,
а маска к моменту разбора уже
стёрла содержимое литералов пробелами. Разбор по маске давал пустое имя у
185 перекрытий из 185 на живом расширении — молчаливый отказ, при котором
счётчик перекрытий выглядит правдоподобно. Строка, начинающаяся с `&`,
заведомо не продолжение многострочного литерала (см. правила `_код_строки`
выше), поэтому аннотация читается по ИСХОДНОЙ строке, а не по маске. Вызовы,
наоборот, разбираются по маске — иначе кандидат внутри комментария или
текста запроса (19 160 и 4 437 таких на «Рознице») читался бы как вызов.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

# Границы объявления. Русские и английские написания — оба встречаются в
# живых конфигурациях.
_НАЧАЛО = {
    "процедура": "процедура",
    "функция": "функция",
    "procedure": "процедура",
    "function": "функция",
}
_КОНЕЦ = {"конецпроцедуры", "конецфункции", "endprocedure", "endfunction"}
_ЭКСПОРТ = {"экспорт", "export"}

_ИМЯ = r"[А-Яа-яЁёA-Za-z_][А-Яа-яЁёA-Za-z_0-9]*"
_СЛОВО = re.compile(_ИМЯ)
# `Асинх` (8.3.18+) стоит ПЕРЕД видом («Асинх Процедура Имя() Экспорт»), а не
# первым словом строки в обычном смысле — без сдвига на это слово терялось
# 207 процедур (design doc, раздел 3). Он необязателен и не сохраняется:
# полей под него в датаклассе нет, только вид и имя нужны для оглавления.
#
# Без `^`: разбор возобновляется и с произвольного столбца, не только с
# начала строки (см. `разобрать` — хвост после `Экспорт`/`КонецПроцедуры` на
# той же физической строке). `^` без re.MULTILINE привязан к абсолютному
# началу строки-аргумента и с `pos>0` в `.match()` не совпал бы никогда;
# `.match(код, столбец)` и без `^` уже пытается совпасть ровно с этой позиции,
# так что якорь был лишним даже при столбец=0.
_ОБЪЯВЛЕНИЕ = re.compile(
    rf"\s*(?:(?:асинх|async)\s+)?({_ИМЯ})\s+({_ИМЯ})\s*\(",
    re.IGNORECASE,
)
# Тело — почти все строки корпуса (3,9 млн из ~4 млн), поэтому поиск конца
# внутри тела обязан быть одним re.search на строку, а не циклом по словам:
# `А = 1; КонецПроцедуры` в одной строке — валидный BSL, и КонецПроцедуры там
# не первое слово. Построена из _КОНЕЦ, чтобы не держать список ключевых слов
# в двух местах.
_ЗАКРЫТИЕ = re.compile(rf"\b(?:{'|'.join(_КОНЕЦ)})\b", re.IGNORECASE)

# Аннотации перекрытия (расширение меняет поведение типовой процедуры) и их
# английские написания — оба встречаются в живых расширениях. Значение —
# каноническая форма для `Процедура.перекрытие`, а не то, что попало в файл
# буква в букву: `&around(...)` и `&Around(...)` — одна и та же аннотация.
_ПЕРЕКРЫТИЯ = {
    "вместо": "Вместо", "после": "После", "перед": "Перед",
    "изменениеиконтроль": "ИзменениеИКонтроль",
    "around": "Around", "after": "After", "before": "Before",
    "changeandvalidate": "ChangeAndValidate",
}
# `\s*` в начале — как у `_ОБЪЯВЛЕНИЕ`: разбор возобновляется с произвольного
# столбца (аннотация может стоять не только в начале строки после того, как
# курсор сдвинулся дальше по ней). Цель перекрытия — необязательный
# единственный строковый аргумент; аннотации без аргументов (`&НаКлиенте`) и
# с аргументами другой формы (`&Вместо(Второй, "Х")`) в группу цели не
# попадают — это директивы компиляции либо перекрытие без разобранной цели.
_АННОТАЦИЯ = re.compile(
    rf'\s*&\s*({_ИМЯ})\s*(?:\(\s*"([^"]*)"\s*\))?', re.IGNORECASE
)

# Вызов — `Идентификатор(` или `Квалификатор.Идентификатор(`. Ищется по
# МАСКЕ (в отличие от `_АННОТАЦИЯ` выше): кандидат внутри комментария или
# текста запроса — не вызов, а маскировка уже стёрла его содержимое, сохранив
# позиции (design doc, раздел 3: 19 160 и 4 437 таких кандидатов на
# «Рознице» — их обязана не увидеть именно эта проверка).
#
# Не регулярка. Первая реализация была ей (`(?:({_ИМЯ})\s*\.\s*)?({_ИМЯ})\s*\(`
# через `finditer`), и A/B на «Рознице» показал просадку почти вдвое — 11,3 с
# базы против 22,0 с медианы. Диагностика (`код.find` как сторож
# без regex — 11,9 с, тот же `finditer`, но с отброшенным результатом —
# 21,7 с) показала, что дорог не отбор кандидатов и не сборка `Процедура.
# вызовы`, а сам проход регулярки по остатку строки: без литерального
# префикса `_ИМЯ` заставляет движок пробовать совпадение на каждой позиции
# строки, а тело — почти все 3,9 млн строк корпуса. Скобок в отрезке кода
# на порядок меньше, чем позиций символов, поэтому `код.find("(", …)`
# (быстрый посимвольный поиск в C) находит каждую скобку, а идентификатор
# перед ней снимается коротким обратным проходом (`_вызов_перед_скобкой`) —
# без построения и прогона регулярки вообще. Сверено на «Рознице» дословно
# с версией на регулярке: 1 009 478 вызовов, 0 расхождений по 137 116
# процедурам. Медиана после замены — 14,1 с (было 22,0 на регулярке).
_ИМЯ_СИМВОЛЫ = frozenset(
    "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯабвгдеёжзийклмнопрстуфхцчшщъыьэюя"
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_"
)
# Первый символ идентификатора цифрой быть не может — без цифр.
_ИМЯ_ПЕРВЫЕ = frozenset(
    "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯабвгдеёжзийклмнопрстуфхцчшщъыьэюя"
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz_"
)


def _вызов_перед_скобкой(код: str, p: int, нижняя: int) -> tuple[str, str] | None:
    """Идентификатор (и, через точку, квалификатор) сразу перед позицией `p`
    открывающей скобки. `None` — перед скобкой не идентификатор (`Если (`,
    арифметическая группировка) — не вызов, значит нечего и отбраковывать по
    `_НЕ_ВЫЗОВ` дальше. `нижняя` — левая граница отрезка тела, за неё обратный
    проход не уходит (текст до неё — соседняя конструкция, не эта строка).
    """
    i = p
    while i > нижняя and код[i - 1] in " \t":
        i -= 1
    конец = i
    while i > нижняя and код[i - 1] in _ИМЯ_СИМВОЛЫ:
        i -= 1
    if i == конец or код[i] not in _ИМЯ_ПЕРВЫЕ:
        return None
    имя = код[i:конец]
    j = i
    while j > нижняя and код[j - 1] in " \t":
        j -= 1
    if j > нижняя and код[j - 1] == ".":
        j -= 1
        while j > нижняя and код[j - 1] in " \t":
            j -= 1
        конец_кв = j
        while j > нижняя and код[j - 1] in _ИМЯ_СИМВОЛЫ:
            j -= 1
        if j < конец_кв and код[j] in _ИМЯ_ПЕРВЫЕ:
            return код[j:конец_кв], имя
    return "", имя


# Слово языка перед скобкой — не вызов процедуры: `Если (А) Тогда`,
# `Новый("Массив")`. Список из разведочного прототипа
# (`tools/lab/bsl_lex.py`), русские и английские написания.
_НЕ_ВЫЗОВ = frozenset({
    "если", "иначеесли", "пока", "для", "возврат", "новый", "и", "или", "не",
    "тогда", "цикл", "по", "из", "выполнить", "вычислить",
    "if", "elsif", "while", "for", "return", "new", "and", "or", "not",
    "then", "do", "to", "in", "execute", "eval",
    "процедура", "функция", "procedure", "function",
})


@dataclass(slots=True)
class Процедура:
    """Одно объявление `Процедура…КонецПроцедуры` / `Функция…КонецФункции`."""

    имя: str
    вид: str                       # "процедура" | "функция"
    параметры: str
    экспорт: bool
    строка: int
    конец: int = 0                  # 0 — КонецПроцедуры/КонецФункции не найден
    директива: str = ""
    перекрытие: tuple[str, str] | tuple[()] = ()
    шапка: str = ""
    частичный: bool = False
    вызовы: list[tuple[str, str, int]] = field(default_factory=list)
    # Точные позиции нужны только ответу, который дочитывает тело с диска.
    # В кэш оглавления они не попадают: при запросе модуль всё равно один раз
    # разбирается заново ради директивы и вида аннотации расширения.
    начало_столбец: int = 0
    конец_столбец: int = 0
    конец_сигнатуры_строка: int = 0
    конец_сигнатуры_столбец: int = 0


def нормализовать(текст: str) -> str:
    """Переводы строк к `\\n`; одиночный `CR` без пары `\\n` — не граница строки.

    `str.splitlines()` не применяется нигде в проекте: он режет ещё и по
    `\\v`, `\\f`, `\\x1c`–`\\x1e`, `\\x85`, `U+2028`, которых для 1С не
    существует. Но и наивная замена `\\r` → `\\n` не годится: в корпусе 50
    одиночных `CR` в 6 файлах — случайные байты, а не старый маковский
    перевод строки, и превращать их в `\\n` значит молча сдвигать номера
    строк ровно там, где эта функция обязана их не сдвигать. Одиночный `\\r`
    заменяется пробелом: строку не рвёт и соседние токены не склеивает.
    """
    return текст.replace("\r\n", "\n").replace("\r", " ")


def прочитать_модуль(путь: Path) -> str:
    """Читает файл модуля и нормализует переводы строк для `разобрать`.

    НЕ `Path.read_text()`. Тот открывает файл в текстовом режиме с
    универсальным переводом строк (`newline=None` по умолчанию) и молча
    превращает одиночный `\r` в `\n` ещё до того, как текст дойдёт до
    `нормализовать()` — а `нормализовать` обязана отличать одиночный `CR`
    (не перевод строки — 50 случайных байт в 6 файлах корпуса,
    design doc раздел 3) от настоящего `CRLF`. Прочитанный через
    `Path.read_text()` файл даёт другую разбивку на строки и, значит, другие
    номера строк, чем тот же файл через эту функцию — ровно в тех файлах,
    где такой символ есть, разойдясь с тем, что видит человек в
    конфигураторе.

    Читает байтами (`bytes.decode()` универсальные переводы строк не
    делает — это особенность текстового режима `io`, а не `decode`) и
    декодирует `utf-8-sig` (снимает BOM, если он есть) с `errors="replace"`,
    как и остальной код проекта читает выгрузку.
    """
    сырые = путь.read_bytes()
    return нормализовать(сырые.decode("utf-8-sig", errors="replace"))


def _код_строки(строка: str, в_строке: bool, мёртвая_ветка: bool) -> tuple[str, bool]:
    """Строка без литералов и комментария плюс новое состояние.

    Содержимое литерала заменяется пробелами, а не выбрасывается: позиции
    остальных символов обязаны сохраниться, иначе номера колонок поедут — на
    них опирается `_сигнатура`.

    Три правила, найденные на живом коде (design doc, раздел 3):

    * внутри незакрытого литерала строка, начинающаяся с `//`, — комментарий,
      а не содержимое и не конец. Разработчик комментирует куски текста
      запроса вместе с тем, что выглядит как закрывающая кавычка; лексер,
      считающий эту кавычку закрывающей, теряет состояние до конца файла —
      одна такая строка съела 184 объявления;
    * внутри `#Удаление … #КонецУдаления` текст мёртв и на состояние не
      влияет: удаляемая и вставляемая ветки несут каждая свою закрывающую
      кавычку, и состояние обязано вестись только по ветке `#Вставка`
      (`мёртвая_ветка` переключает вызывающий код `разобрать`, здесь только
      применяется — при мёртвой ветке состояние на входе возвращается как
      есть, что бы в тексте ни было);
    * удвоенная кавычка `""` внутри литерала — часть текста, а не закрытие
      плюс новое открытие.
    """
    if мёртвая_ветка:
        return " " * len(строка), в_строке
    if в_строке and строка.lstrip().startswith("//"):
        return " " * len(строка), True

    маска = list(строка)
    i, n = 0, len(строка)
    if в_строке:
        # Продолжение литерала, открытого на предыдущей строке: ищем
        # закрывающую кавычку с самого начала, а не заново решаем, что тут
        # литерал — это уже решено состоянием на входе.
        начало = i
        закрыт = False
        while i < n:
            if строка[i] == '"':
                if i + 1 < n and строка[i + 1] == '"':
                    i += 2               # удвоенная кавычка — часть текста
                    continue
                i += 1
                закрыт = True
                break
            i += 1
        for j in range(начало, i):
            маска[j] = " "
        if not закрыт:
            return "".join(маска), True
        в_строке = False
        # Литерал закрылся посреди строки — остаток разбираем как код.

    while i < n:
        if строка[i] == '"':
            начало = i
            i += 1
            закрыт = False
            while i < n:
                if строка[i] == '"':
                    if i + 1 < n and строка[i + 1] == '"':
                        i += 2           # удвоенная кавычка — часть текста
                        continue
                    i += 1
                    закрыт = True
                    break
                i += 1
            for j in range(начало, i):
                маска[j] = " "
            if not закрыт:
                # Не закрылась до конца строки — продолжится на следующей
                # через `|`, состояние уходит в следующий вызов.
                return "".join(маска), True
            continue
        if строка[i] == "/" and i + 1 < n and строка[i + 1] == "/":
            for j in range(i, n):
                маска[j] = " "
            break
        i += 1
    return "".join(маска), False


def _сигнатура(маски: list[str], начало: int, столбец: int) -> tuple[str, int, int]:
    """Текст параметров до баланса скобок и место сразу за закрывающей.

    Читать одну строку нельзя: у 2 074 процедур из 49 182 сигнатура
    перенесена, и `Экспорт` стоит на последней строке (design doc, раздел 3).
    Строки уже без литералов и комментариев (`маски`) — скобка внутри
    строкового умолчания параметра в баланс не идёт. Столбец на выходе — не
    параметр, а точка, откуда вызывающий код ищет `Экспорт` и следом
    `КонецПроцедуры`: `Процедура П() КонецПроцедуры` — обычная запись в одну
    строку, без этого столбца её было бы негде искать.
    """
    глубина, куски, номер = 0, [], начало
    while номер < len(маски):
        строка = маски[номер]
        начиная_с = столбец if номер == начало else 0
        for позиция in range(начиная_с, len(строка)):
            символ = строка[позиция]
            if символ == "(":
                глубина += 1
                if глубина == 1:
                    continue
            elif символ == ")":
                глубина -= 1
                if глубина == 0:
                    return "".join(куски).strip(), номер, позиция + 1
            if глубина >= 1:
                куски.append(символ)
        куски.append(" ")
        номер += 1
    # Скобка не закрылась до конца текста — модуль оборван внутри сигнатуры.
    return "".join(куски).strip(), начало, столбец


def _слово_с(строка: str, столбец: int) -> tuple[str, int]:
    """Первое слово строки от `столбец` и позиция сразу за ним.

    Пустое слово и тот же столбец — там нет идентификатора (конец строки,
    знак препинания и т. п.).
    """
    хвост = строка[столбец:]
    голый = хвост.lstrip()
    слово = _СЛОВО.match(голый)
    if not слово:
        return "", столбец
    начало_слова = столбец + (len(хвост) - len(голый))
    return слово.group(0), начало_слова + len(слово.group(0))


def _вызовы_в_отрезке(
    код: str, от: int, до: int, номер_строки: int, приёмник: list[tuple[str, str, int]]
) -> None:
    """Дописывает в `приёмник` вызовы из отрезка [от, до) строки без литералов.

    Вызывается раз на объявление (окно между концом сигнатуры и местом,
    где остановилась проверка на `Экспорт`/`КонецПроцедуры`), а не на
    строку — горячий путь тела инлайнен прямо в `разобрать` тем же приёмом
    (`код.find` + `_вызов_перед_скобкой`), см. комментарий у `_ИМЯ_СИМВОЛЫ`.
    """
    p = код.find("(", от, до)
    while p != -1:
        рез = _вызов_перед_скобкой(код, p, от)
        if рез is not None:
            квалификатор, имя = рез
            if имя.lower() not in _НЕ_ВЫЗОВ:
                приёмник.append((квалификатор, имя, номер_строки))
        p = код.find("(", p + 1, до)


def разобрать(текст: str) -> list[Процедура]:
    """Процедуры и функции модуля: границы, сигнатура с переносом, `Экспорт`.

    Проход ведёт курсор (строка, столбец), а не только строка: закрыв
    сигнатуру и проверив `Экспорт`/`КонецПроцедуры`, разбор возвращается на ТУ
    ЖЕ физическую строку с позиции сразу после найденного слова, а не
    перескакивает через её остаток. Без этого второе объявление на одной
    физической строке — «Процедура П1() КонецПроцедуры Процедура П2() …» —
    пропадало молча: обычное следствие того, что `нормализовать` схлопывает
    одиночный `CR` в пробел, а не в перевод строки, и может слить две
    исходные строки в одну.

    Внутри тела (`текущая is not None`) та же логика, но не по слову за раз —
    `КонецПроцедуры` ищется `re.search`-ом по всей оставшейся строке сразу:
    `А = 1; КонецПроцедуры` в одну строку — валидный BSL, и без этого поиска
    (только по первому слову) граница уезжала на первый попавшийся
    `КонецПроцедуры` дальше по файлу, а всё, что должно было открыться между
    ними, терялось. Тело — почти весь корпус построчно, поэтому один поиск на
    строку допустим, а разбор строки по словам в цикле — нет.

    Аннотации (`&Вместо`, `&НаКлиенте`, …) копятся в `ожидает_директива`/
    `ожидает_перекрытие` до ближайшего объявления — синтаксис BSL допускает
    аннотацию только непосредственно перед `Процедура`/`Функция`, поэтому
    ничего дольше одного объявления ждать не может. Комментарий-шапка копится
    в `буфер_шапки` из подряд идущих строк-комментариев над объявлением и
    сбрасывается, как только между шапкой и объявлением встретится строка
    настоящего кода (аннотация в разрыв не считается — в живых конфигурациях
    шапка почти всегда стоит НАД аннотацией, а не над самим объявлением).
    """
    строки = нормализовать(текст).split("\n")
    маски: list[str] = []
    в_строке = False
    мёртвая_ветка = False
    for строка in строки:
        # Директивы правки расширения всегда занимают строку целиком (это
        # формат выгрузки, не догадка) — проверяются по исходному тексту, а
        # не по маске, и раньше вызова `_код_строки`: `#Удаление` может
        # встретиться посреди ещё не закрытого литерала (design doc,
        # раздел 3, пример с `АналитикаХозяйственныхОпераций`), и на решение
        # «мёртвая ветка или нет» это не влияет.
        #
        # `"#" in строка` — дешёвый сторож перед `strip().lower()`: на
        # «Рознице» директив правки нет вовсе (0 файлов), а строка выполнялась
        # безусловно на всех 3,9 млн строк корпуса — 0,67 с из 12–13 против
        # 0,15 с со сторожем (независимый замер A/B).
        if "#" in строка:
            голая = строка.strip().lower()
            if голая == "#удаление":
                мёртвая_ветка = True
            elif голая == "#конецудаления":
                мёртвая_ветка = False
        код, в_строке = _код_строки(строка, в_строке, мёртвая_ветка)
        маски.append(код)

    процедуры: list[Процедура] = []
    текущая: Процедура | None = None
    ожидает_директива = ""
    ожидает_перекрытие: tuple[str, str] | tuple[()] = ()
    буфер_шапки: list[str] = []
    номер, столбец = 0, 0
    while номер < len(строки):
        код = маски[номер]
        голая = код[столбец:].strip()
        if not голая:
            if текущая is None and столбец == 0:
                # Маска красит целую строку-комментарий в пробелы точно так
                # же, как пустую строку — по маске они неразличимы. Шапка
                # нужна дословно (в BSL типов в сигнатуре нет, шапка —
                # единственный источник), поэтому здесь снова смотрим в
                # исходный текст, как и для аннотации.
                #
                # Пустая строка (`исходная == ""`) рвёт цепочку так же, как
                # и настоящий код: `else`, а не `elif исходная` — прежняя
                # версия проверяла только «не комментарий и не пусто»,
                # а по-настоящему пустая строка не подходила ни под одно из
                # двух условий и буфер выживал молча.
                # На живом корпусе это цепляло к процедуре заголовок раздела
                # файла или шапку соседней, никак не связанной процедуры —
                # около 2 396 случаев, и это хуже отсутствия шапки: агенту
                # приходит правдоподобный, но чужой текст.
                исходная = строки[номер].strip()
                if исходная.startswith("//"):
                    буфер_шапки.append(исходная)
                else:
                    буфер_шапки = []
            номер += 1
            столбец = 0
            continue

        if текущая is None:
            if голая[0] == "&":
                # Имя цели перекрытия — строковый литерал, и маска его уже
                # стёрла. Разбор по ИСХОДНОЙ строке: строка, начинающаяся с
                # `&`, заведомо не продолжение многострочного литерала.
                м_анн = _АННОТАЦИЯ.match(строки[номер], столбец)
                if not м_анн:
                    номер += 1
                    столбец = 0
                    continue
                слово_анн = м_анн.group(1)
                канон = _ПЕРЕКРЫТИЯ.get(слово_анн.lower())
                if канон:
                    ожидает_перекрытие = (канон, м_анн.group(2) or "")
                else:
                    ожидает_директива = слово_анн
                # Аннотация может стоять в одной строке с объявлением
                # (`&НаКлиенте Процедура …`) — остаток строки досматривается,
                # а не перепрыгивается.
                столбец = м_анн.end()
                continue

            м = _ОБЪЯВЛЕНИЕ.match(код, столбец)
            вид_слово = м.group(1).lower() if м else ""
            if м and вид_слово in _НАЧАЛО:
                хвост_до_объявления = код[столбец:]
                начало_декларации = столбец + (
                    len(хвост_до_объявления)
                    - len(хвост_до_объявления.lstrip())
                )
                открывающая = м.end() - 1      # позиция "("
                параметры, конец_строки, после_скобки = _сигнатура(маски, номер, открывающая)
                маска_конца = маски[конец_строки]
                слово, после_слова = _слово_с(маска_конца, после_скобки)
                экспорт = слово.lower() in _ЭКСПОРТ
                конец_сигнатуры = после_слова if экспорт else после_скобки
                if экспорт:
                    слово, после_слова = _слово_с(маска_конца, после_слова)

                текущая = Процедура(
                    имя=м.group(2), вид=_НАЧАЛО[вид_слово],
                    параметры=параметры, экспорт=экспорт, строка=номер + 1,
                    директива=ожидает_директива, перекрытие=ожидает_перекрытие,
                    шапка="\n".join(буфер_шапки),
                    начало_столбец=начало_декларации,
                    конец_сигнатуры_строка=конец_строки + 1,
                    конец_сигнатуры_столбец=конец_сигнатуры,
                )
                ожидает_директива, ожидает_перекрытие = "", ()
                буфер_шапки = []
                # Между концом сигнатуры и КонецПроцедуры/следующей строкой
                # может стоять тело в одну строку с объявлением —
                # «Процедура П() Рассчитать(1); КонецПроцедуры». Граница окна
                # ищется тем же `_ЗАКРЫТИЕ`, что и в ветке тела ниже, а не
                # позицией снятого выше `слово`: та отмечает конец ОДНОГО
                # идентификатора, а не открывающую скобку вызова следом за
                # ним — окно `[после_скобки, после_слова)` эту скобку не
                # захватывает, и вызов первым токеном тела терялся бы молча.
                граница_декл = _ЗАКРЫТИЕ.search(маска_конца, после_скобки)
                конец_окна_вызовов = граница_декл.start() if граница_декл else len(маска_конца)
                _вызовы_в_отрезке(
                    маска_конца, после_скобки, конец_окна_вызовов,
                    конец_строки + 1, текущая.вызовы,
                )
                if слово.lower() in _КОНЕЦ:
                    # Объявление и конец в одной строке уже разобраны целиком.
                    текущая.конец = конец_строки + 1
                    текущая.конец_столбец = после_слова
                    процедуры.append(текущая)
                    текущая = None
                # Не перескакиваем через остаток строки — на ней может стоять
                # ещё одно объявление (закрытый случай) или просто хвост,
                # который следующая проверка обязана увидеть, а не потерять.
                # Курсор — `max(после_слова, конец_окна_вызовов)`, а не
                # голое `после_слова`: окно вызовов уже
                # просмотрено целиком до `конец_окна_вызовов`, и обычная
                # ветка тела ниже начала бы с `после_слова` заново —
                # `Процедура П() Рассчитать(1); Другой(2); КонецПроцедуры`
                # находило бы «Другой» дважды. Когда процедура закрылась на
                # этой же строке, `после_слова` (конец «КонецПроцедуры»)
                # всегда правее границы окна вызовов (та — его НАЧАЛО), и
                # `max` выбирает его без изменения прежнего поведения.
                номер, столбец = конец_строки, max(после_слова, конец_окна_вызовов)
                continue

            # Голая строка — не аннотация и не объявление: настоящий код вне
            # тела (`#Область`, `Перем …;` и подобное). Шапка держится, только
            # если стоит прямо над объявлением (сквозь аннотации) — цепочка
            # рвётся.
            буфер_шапки = []
        else:
            м = _ЗАКРЫТИЕ.search(код, столбец)
            граница = м.start() if м else len(код)
            # Инлайн вместо вызова `_вызовы_в_отрезке`: тело — почти все
            # 3,9 млн строк корпуса, и на этой ветке чистый вызов функции
            # (аргументы, кадр, возврат) заметно дороже самого поиска —
            # первый A/B (ещё с `_ВЫЗОВ.finditer` внутри, не инлайна ради)
            # показал почти двукратную просадку (11,3 → 22,0 с медианы);
            # после замены регулярки на `код.find` + `_вызов_перед_скобкой`
            # и инлайна — 14,1 с (комментарий у `_ИМЯ_СИМВОЛЫ` разбирает обе
            # находки подробно).
            p = код.find("(", столбец, граница)
            while p != -1:
                рез = _вызов_перед_скобкой(код, p, столбец)
                if рез is not None:
                    квалификатор, имя = рез
                    if имя.lower() not in _НЕ_ВЫЗОВ:
                        текущая.вызовы.append((квалификатор, имя, номер + 1))
                p = код.find("(", p + 1, граница)
            if м:
                текущая.конец = номер + 1
                текущая.конец_столбец = м.end()
                процедуры.append(текущая)
                текущая = None
                # Тот же приём, что и для объявления: остаток строки после
                # найденного слова может держать следующую процедуру
                # («…КонецПроцедуры Процедура П2()…») — досканировать его, а
                # не перепрыгивать.
                столбец = м.end()
                continue

        номер += 1
        столбец = 0

    if текущая is not None:
        # Модуль оборвался раньше `КонецПроцедуры` — выгрузка обрезана или
        # файл битый; отдаём разобранное, а не молчим.
        текущая.частичный = True
        текущая.конец_столбец = len(строки[-1]) if строки else 0
        процедуры.append(текущая)
    return процедуры
