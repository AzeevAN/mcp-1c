def test_процедура_с_двумя_событиями_видна_в_обоих_методах(tmp_path):
    """Регресс, найденный ревью: до правки `состав(...).события[имя]` и
    `обработчик(адрес, имя)` расходились для процедуры с двумя разными
    событиями — словарь строился `{имя_процедуры: имя_события}` и
    оставлял последнюю пару по порядку обхода XML, а `обработчик` шёл по
    тем же парам и возвращал первую по раннему `return`: один вопрос имел
    два разных ответа в одном и том же индексе. На живой выгрузке так
    устроены 12 из 23 210 привязок (пример из ревью —
    `BeforeLoadDataFromSettingsAtServer`/`OnLoadDataFromSettingsAtServer`
    на одну процедуру `ПриЗагрузкеДанныхИзНастроекНаСервере`)."""
    ext = tmp_path / "Catalogs" / "Пример" / "Forms" / "ФормаЭлемента" / "Ext"
    (ext / "Form").mkdir(parents=True)
    (ext / "Form" / "Module.bsl").write_text(
        "&НаСервере\nПроцедура ЗагрузкаНастроек()\nКонецПроцедуры\n",
        encoding="utf-8",
    )
    (ext / "Form.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>'
        "<Form><Events>"
        '<Event name="BeforeLoadDataFromSettingsAtServer">ЗагрузкаНастроек</Event>'
        '<Event name="OnLoadDataFromSettingsAtServer">ЗагрузкаНастроек</Event>'
        "</Events></Form>",
        encoding="utf-8",
    )
    ф = Формы.построить(tmp_path)
    адрес = "Справочник.Пример.Форма.ФормаЭлемента"
    ожидание = ("BeforeLoadDataFromSettingsAtServer", "OnLoadDataFromSettingsAtServer")
    assert ф.состав(адрес).события["ЗагрузкаНастроек"] == ожидание
    assert ф.обработчик(адрес, "ЗагрузкаНастроек") == ожидание


