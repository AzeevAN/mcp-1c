"""Сверка таблицы версий языка запросов с двумя справками разных платформ.

Справка по языку запросов версий не содержит (проверено: ноль упоминаний
«8.3.x» на 129 страницах), поэтому версии живут в курируемой таблице
`query_versions.py`. Единственный способ увидеть в ней пропуск — сравнить две
справки: чего нет в старой и есть в новой, то появилось между ними, и у этого
обязана стоять версия.

Что печатает:

* появилось после старой версии — и сколько из этого покрыто таблицей;
* **ложные срабатывания** — элементы, которые были уже в старой справке, но
  получили версию. Это худший вид ошибки: такой элемент спрячется от
  конфигурации, где он на самом деле есть;
* исчезнувшее — язык запросов обычно только растёт, поэтому непустой список
  здесь означает либо удаление, либо перепутанные местами файлы.

Запуск::

    python3 tools/lab/compare_query_help.py <старая.hbk> <новая.hbk>

Прогон 2026-08-19 на 8.3.5.1570 против текущей: появилось 29, покрыто 29,
ложных 0, исчезло 0.
"""

import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, "src")
from mcp1c.query_parser import parse_hbk  # noqa: E402

СТАРАЯ = Path(sys.argv[1])
НОВАЯ = Path(sys.argv[2])

старая = parse_hbk(СТАРАЯ)
новая = parse_hbk(НОВАЯ)

было = {i.id for i in старая.items.values()}
стало = {i.id: i for i in новая.items.values()}

появились = [стало[ключ] for ключ in sorted(set(стало) - было)]
исчезли = sorted(было - set(стало))
без_версии = [i for i in появились if not i.since]
ложные = [i for i in новая.items.values() if i.since and i.id in было]

print(f"{СТАРАЯ.name:34} {len(старая.items):>4} страниц")
print(f"{НОВАЯ.name:34} {len(новая.items):>4} страниц")
print()
print(f"появилось после старой : {len(появились)}")
print(f"покрыто таблицей       : {len(появились) - len(без_версии)}")
print(f"НЕ покрыто             : {len(без_версии)}")
for i in без_версии:
    print(f"    {i.name_ru}  [{i.name_en}, {i.kind}]")
print(f"ЛОЖНЫХ срабатываний    : {len(ложные)}")
for i in ложные:
    print(f"    {i.name_ru} помечен {i.since}, но был уже в старой справке")
print(f"исчезло                : {len(исчезли)}")
for ключ in исчезли:
    print(f"    {ключ}")
print()
print("по релизам:", dict(Counter(i.since for i in новая.items.values() if i.since)))
