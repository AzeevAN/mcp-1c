"""Окрестность объекта для показа человеку: узлы, рёбра и их размещение.

Отдельно от `graph.py`, потому что отвечает на другой вопрос. Граф отвечает
«кто с кем связан» и живёт в памяти сервера; здесь — «как это показать», и
результат уходит в браузер, а не агенту.

**Почему для человека, а не для агента.** Список из тысячи имён на расстоянии
два бесполезен в любом виде: информацию несёт ребро, а не узел. Агенту нужна
цепочка «через что», и она отложена до живого случая (разбор — в «Отложено»).
Человеку же картинка отвечает сразу: он видит направление, подпись ребра и
плотность связей — и сам решает, куда смотреть дальше.

**Автоматического отсечения здесь нет, и это решение.** Первая мысль была
резать узлы с большой степенью как мусорные. Замер её опроверг: верхушка по
степени — `Справочник.Пользователи` (323 соседа), `Организации` (311),
`Номенклатура` (264), то есть самые осмысленные объекты конфигурации, а вовсе
не шум. А узел, который портил пути (`ДополнительныеРеквизитыИСведения`), имеет
скромные 34 соседа — он мешает не размером, а тем, что в него **входят** 33
объекта, и через него «связано» всё со всем.

Порогом это не отделить. Поэтому глубина всегда один шаг, а дальше человек
раскрывает узлы сам: он видит, что связь идёт в общий механизм, и не идёт
туда. Порога, который отличит `Пользователей` от `Дополнительных реквизитов`,
не существует — а глаз отличает мгновенно.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field

# Сколько соседей показываем по умолчанию. У половины объектов соседей нет
# вовсе (медиана 0–1), у 90% их не больше 5–8, и лимит не срабатывает никогда.
# Он для другого хвоста: у `Справочник.Пользователи` соседей 323.
#
# Число подобрано глазами по картинке, а не из головы: радиус кольца растёт
# вместе с числом узлов, и при шестидесяти вся схема ужимается в окно так,
# что подписи по 11 единиц превращаются в 3 пикселя. Тридцать читаются.
# Больше — по выбору человека прямо на странице.
DEFAULT_LIMIT = 30

# Сколько места занимает узел с подписью вдоль кольца, в единицах SVG. Отсюда
# считается радиус: подписи вроде `РеализацияТоваровУслуг` — это около сотни
# единиц, и если радиус задать константой, при тридцати узлах они наезжают
# друг на друга. Первая версия так и делала, увидели на первой же картинке.
NODE_SPACING = 105.0

# Меньше этого кольцо не сжимается: при двух соседях узлы не должны липнуть
# к центру.
MIN_RING = 190.0

# Ниже этого числа соседей кольцо одно. Выше — два, иначе радиус приходится
# задирать так, что картинка не помещается на экран целиком.
TWO_RING_FROM = 20

# Во сколько раз внешнее кольцо дальше внутреннего. Длина окружности растёт
# в ту же меру, поэтому в том же отношении делится и число узлов: иначе
# внутреннее кольцо тесное, а внешнее полупустое.
OUTER_FACTOR = 1.6


@dataclass(slots=True)
class Node:
    """Узел картинки. `distance` 0 — сам объект, 1 — прямой сосед."""

    name: str
    kind: str = ""
    distance: int = 1
    # Сколько всего связей у объекта в графе, а не на картинке. Показывает,
    # стоит ли его раскрывать: у объекта с тремя соседями сюрпризов нет.
    degree: int = 0
    x: float = 0.0
    y: float = 0.0

    @property
    def short(self) -> str:
        """Имя без вида: `Документ.ЧекККМ` -> `ЧекККМ`.

        Вид и так виден по цвету и по колонке в таблице под картинкой, а
        полное имя в подпись не влезает.
        """
        return self.name.split(".", 1)[1] if "." in self.name else self.name


@dataclass(slots=True)
class Link:
    """Ребро картинки. `outgoing` — из объекта наружу или в него."""

    source: str
    target: str
    title: str = ""
    outgoing: bool = True


@dataclass(slots=True)
class Neighbourhood:
    subject: Node
    nodes: list[Node] = field(default_factory=list)
    links: list[Link] = field(default_factory=list)
    # Сколько соседей есть на самом деле и сколько из них показано. Обрезка
    # обязана быть видна: молчаливое усечение читается как «связей больше
    # нет», и это ровно тот класс дефекта, что чинили в `get_related`.
    total: int = 0

    @property
    def shown(self) -> int:
        return len(self.nodes)

    @property
    def truncated(self) -> bool:
        return self.total > self.shown


def _kind_of(full_name: str) -> str:
    return full_name.split(".", 1)[0] if "." in full_name else ""


def neighbourhood(graph, full_name: str, limit: int = DEFAULT_LIMIT) -> Neighbourhood:
    """Прямые соседи объекта с подписями рёбер.

    Глубина ровно один шаг — см. причину в шапке модуля. Слабые рёбра не
    берутся: `ЗначениеДоступа` и подобные реквизиты перечисляют сотни типов и
    связывают почти всё со всем, в графе они уже помечены.
    """
    subject = Node(name=full_name, kind=_kind_of(full_name), distance=0)
    итог = Neighbourhood(subject=subject)

    рёбра: dict[str, Link] = {}
    for edge in graph.outgoing(full_name, include_weak=False):
        рёбра.setdefault(
            edge.target, Link(full_name, edge.target, edge.title, outgoing=True)
        )
    for edge in graph.incoming(full_name):
        # Встречное ребро не затирает исходящее: если объекты ссылаются друг на
        # друга, показываем ту сторону, которая нашлась первой, а не последнюю.
        рёбра.setdefault(
            edge.source, Link(edge.source, full_name, edge.title, outgoing=False)
        )
    рёбра.pop(full_name, None)

    итог.total = len(рёбра)

    # Порядок отбора решает, что попадёт в обрезку, поэтому он не случаен:
    # сначала связанные плотнее — у них выше шанс, что смотреть надо туда.
    имена = sorted(рёбра, key=lambda n: (-len(graph.neighbours(n)), n))[:limit]

    for имя in имена:
        итог.nodes.append(
            Node(
                name=имя,
                kind=_kind_of(имя),
                distance=1,
                degree=len(graph.neighbours(имя)),
            )
        )
        итог.links.append(рёбра[имя])

    subject.degree = итог.total
    layout(итог)
    return итог


def layout(область: Neighbourhood) -> None:
    """Расставить узлы кольцами вокруг объекта. Меняет узлы на месте.

    Раскладка своя, а не библиотечная: силовая укладка требует зависимости и
    итераций, а для одного шага она не нужна — все соседи равноудалены от
    центра по смыслу, и кольцо это выражает точнее, чем результат симуляции.
    """
    область.subject.x = 0.0
    область.subject.y = 0.0

    узлы = область.nodes
    if not узлы:
        return

    # Соседи одного вида идут подряд: так видно, что документ окружён
    # регистрами, а справочник — документами.
    порядок = sorted(range(len(узлы)), key=lambda i: (узлы[i].kind, узлы[i].name))

    if len(узлы) < TWO_RING_FROM:
        размеры = [len(узлы)]
    else:
        # Делим по длине окружностей: внешнее кольцо длиннее в OUTER_FACTOR раз,
        # столько же узлов оно и вмещает.
        внутри = max(1, round(len(узлы) / (1 + OUTER_FACTOR)))
        размеры = [внутри, len(узлы) - внутри]

    # Радиус — из числа узлов на кольце, а не константа: он обязан расти
    # вместе с плотностью, иначе подписи наезжают.
    базовый = max(MIN_RING, размеры[0] * NODE_SPACING / (2 * math.pi))

    место = 0
    for кольцо, сколько in enumerate(размеры):
        радиус = базовый * (OUTER_FACTOR**кольцо)
        # Внешнее кольцо повёрнуто на полшага: иначе узлы встают строго за
        # внутренними, и подписи выстраиваются в одну линию.
        сдвиг = math.pi / сколько if кольцо else 0.0
        for позиция in range(сколько):
            угол = 2 * math.pi * позиция / сколько + сдвиг - math.pi / 2
            индекс = порядок[место]
            узлы[индекс].x = радиус * math.cos(угол)
            узлы[индекс].y = радиус * math.sin(угол)
            место += 1


def bounds(область: Neighbourhood, отступ: float = 90.0) -> tuple[float, float, float, float]:
    """Границы картинки: `viewBox` считается по узлам, а не задаётся наугад.

    Иначе при одном соседе половина холста пустая, а при трёхстах узлы уезжают
    за край.
    """
    точки = [(область.subject.x, область.subject.y)] + [(n.x, n.y) for n in область.nodes]
    xs = [x for x, _ in точки]
    ys = [y for _, y in точки]
    слева, сверху = min(xs) - отступ, min(ys) - отступ
    ширина = (max(xs) + отступ) - слева
    высота = (max(ys) + отступ) - сверху
    return слева, сверху, ширина, высота
