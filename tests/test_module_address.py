"""Перевод между путём файла в выгрузке и адресом на языке метаданных.

Тесты не зависят от `data/`: пары путь/адрес синтетические, повторяют
реальные каталоги выгрузки, но не читают диск.
"""

from mcp1c.module_address import адрес_модуля, путь_модуля, разобрать_адрес

# Пары дословно из брифа задачи 4.
ПАРЫ = [
    ("CommonModules/ОбщегоНазначенияРТ/Ext/Module.bsl", "ОбщийМодуль.ОбщегоНазначенияРТ"),
    ("Documents/ЧекККМ/Ext/ObjectModule.bsl", "Документ.ЧекККМ.МодульОбъекта"),
    ("Documents/ЧекККМ/Ext/ManagerModule.bsl", "Документ.ЧекККМ.МодульМенеджера"),
    ("Catalogs/Номенклатура/Forms/ФормаЭлемента/Ext/Form/Module.bsl",
     "Справочник.Номенклатура.Форма.ФормаЭлемента"),
    ("AccumulationRegisters/ТоварыНаСкладах/Ext/RecordSetModule.bsl",
     "РегистрНакопления.ТоварыНаСкладах.МодульНабораЗаписей"),
]


def test_путь_в_адрес():
    for путь, адрес in ПАРЫ:
        assert адрес_модуля(путь) == адрес


def test_адрес_в_путь_обратим():
    for путь, адрес in ПАРЫ:
        assert путь_модуля(адрес) == путь


def test_адрес_процедуры_отделяется_двойным_двоеточием():
    модуль, процедура = разобрать_адрес("Документ.ЧекККМ.МодульОбъекта::ПриЗаписи")
    assert модуль == "Документ.ЧекККМ.МодульОбъекта"
    assert процедура == "ПриЗаписи"


def test_адрес_без_разделителя_это_модуль():
    модуль, процедура = разобрать_адрес("Справочник.Номенклатура.Форма.ФормаЭлемента")
    assert модуль == "Справочник.Номенклатура.Форма.ФормаЭлемента"
    assert процедура is None


# --- Ниже — тесты сверх брифа: полный круг, общая форма, честный отказ. ---


def test_путь_и_адрес_составляют_полный_круг():
    # Брифовые тесты проверяют обе стрелки по отдельности; здесь — их
    # композиция, чтобы поймать случай, когда обе стрелки согласны
    # по отдельности, но не друг с другом.
    for путь, _ in ПАРЫ:
        assert путь_модуля(адрес_модуля(путь)) == путь


def test_общая_форма_не_вкладывает_слово_форма_в_адрес():
    # ОбщаяФорма — это уже форма сама по себе (не форма объекта), поэтому
    # адрес двухзвенный: "ОбщаяФорма.Имя", а не "ОбщаяФорма.Имя.Форма.Имя".
    путь = "CommonForms/ПанельОтчетов/Ext/Form/Module.bsl"
    адрес = "ОбщаяФорма.ПанельОтчетов"
    assert адрес_модуля(путь) == адрес
    assert путь_модуля(адрес) == путь


def test_неизвестный_каталог_отказывает_а_не_придумывает_адрес():
    # HTTPServices в таблице соответствия нет (см. докстроку модуля).
    # Молчаливое искажение адреса хуже честного отказа.
    import pytest

    with pytest.raises(ValueError, match="HTTPServices"):
        адрес_модуля("HTTPServices/Биллинг/Ext/Module.bsl")


def test_неизвестное_имя_файла_модуля_отказывает():
    import pytest

    with pytest.raises(ValueError, match="RecalcModule.bsl"):
        адрес_модуля("Documents/ЧекККМ/Ext/RecalcModule.bsl")


def test_путь_модуля_для_неизвестного_вида_в_адресе_отказывает():
    import pytest

    with pytest.raises(ValueError, match="НеизвестныйВид"):
        путь_модуля("НеизвестныйВид.Штука")
