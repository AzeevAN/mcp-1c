"""Таблица замен для старых платформ.

Справка говорит, с какой версии элемент существует, но не говорит, чем его
заменить в более старой. Таблица пишется руками — из справки рецепты не
выводятся.
"""

from __future__ import annotations

from mcp1c import replacements
from mcp1c.syntax_model import SyntaxItem
from mcp1c.tools import get_syntax, search_syntax

from conftest import build_syntax_registry as реестр

# Строковые функции, появившиеся в 8.3.6. Похожий список ведёт сборщик обработки
# (`PLATFORM_836_TOKENS` в `exporter-1c/build_modules.py`), но импортировать его
# сюда нельзя: сборщик — отдельный скрипт, он не знает про пакет `mcp1c` и
# запускается без него.
СТРОКОВЫЕ_836 = (
    "СтрНайти",
    "СтрРазделить",
    "СтрСоединить",
    "СтрШаблон",
    "СтрНачинаетсяС",
    "СтрЗаканчиваетсяНа",
)


def test_рецепт_находится_независимо_от_регистра():
    прямо = replacements.find("СтрНайти")
    строчными = replacements.find("стрнайти")

    assert прямо is not None
    assert "Найти" in прямо.instead
    assert строчными is прямо


def test_у_каждой_строковой_функции_836_есть_рецепт():
    без_рецепта = [имя for имя in СТРОКОВЫЕ_836 if replacements.find(имя) is None]

    assert без_рецепта == []


def test_код_рецептов_не_зовёт_функции_836():
    """Рецепт, использующий то, чего в старой платформе нет, бесполезен.

    Проверяется `code` и `instead`, но не `note`: оговорка обязана называть
    оригинал, иначе непонятно, чем замена от него отличается.
    """
    нарушения = []
    for ключ, рецепт in replacements.REPLACEMENTS.items():
        текст = f"{рецепт.instead}\n{рецепт.code}"
        нарушения += [f"{ключ}: {имя}" for имя in СТРОКОВЫЕ_836 if имя in текст]

    assert нарушения == []


def test_у_доступной_в_835_функции_рецепта_нет():
    """`СтрСравнить` появилась в 8.3.5, а не в 8.3.6 — заменять нечего.

    Проверено по справке 2026-08-17. В `PLATFORM_836_TOKENS` сборщика она
    записана ошибочно: запрет там строже, чем требует платформа. Рецепт на неё
    означал бы, что сервер советует обход там, где обходить нечего.
    """
    assert replacements.find("СтрСравнить") is None


def test_карточка_недоступного_элемента_содержит_рецепт(tmp_path):
    registry = реестр(
        tmp_path,
        [
            SyntaxItem(
                id="ctx/СтрРазделить",
                kind="method",
                name_ru="СтрРазделить",
                description="Разделяет строку на части",
                since="8.3.6",
            )
        ],
        "8.3.5.1570",
    )

    ответ = get_syntax(registry, "СтрРазделить")

    assert "8.3.6" in ответ
    assert "РазделитьСтроку" in ответ
    assert "набор символов" in ответ
    # Пустая строка обязательна: без неё markdown склеит запрет и рецепт в один
    # абзац, и заголовок замены потеряется.
    assert "не скомпилируется.\n\n**Чем заменить" in ответ


def test_удалённому_элементу_рецепт_не_подставляется(tmp_path):
    """Рецепт написан для «ещё не появился», а не для «уже убрали».

    Случай собран искусственно — `СтрНайти` из платформы не убирали, — но
    проверяется здесь именно направление: подставить обход назад тому, кому
    нужен путь вперёд, значит соврать.
    """
    registry = реестр(
        tmp_path,
        [
            SyntaxItem(
                id="ctx/СтрНайти",
                kind="method",
                name_ru="СтрНайти",
                description="Находит вхождение подстроки",
                since="8.3.6",
                until="8.3.10",
            )
        ],
        "8.3.27.2130",
    )

    ответ = get_syntax(registry, "СтрНайти")

    assert "8.3.10" in ответ
    assert "Чем заменить" not in ответ


def test_у_одноимённых_рецепт_получает_только_будущий(tmp_path):
    """Причины у однофамильцев разные, и рецепт положен не всем.

    Тому, кто появится позже, нужен обход назад — он есть. Тому, кого убрали,
    нужен путь вперёд, и рецепта для него не написано; подставить туда обход
    для старой платформы значит посоветовать откат вместо обновления.
    """
    registry = реестр(
        tmp_path,
        [
            SyntaxItem(
                id="ctx/СтрРазделить",
                kind="method",
                name_ru="СтрРазделить",
                description="Разделяет строку на части",
                since="8.3.6",
            ),
            SyntaxItem(
                id="obj/Разбор/СтрРазделить",
                kind="method",
                name_ru="СтрРазделить",
                parent_ru="Разбор",
                description="Одноимённый метод объекта",
                until="8.3.4",
            ),
        ],
        "8.3.5.1570",
    )

    ответ = get_syntax(registry, "СтрРазделить")

    assert "РазделитьСтроку" in ответ
    assert ответ.count("Чем заменить") == 1


def test_элемент_без_рецепта_отвечает_прежним_текстом(tmp_path):
    """Таблица покрывает не всё, и молчать про недоступность из-за этого нельзя."""
    registry = реестр(
        tmp_path,
        [
            SyntaxItem(
                id="obj/ЗаписьJSON",
                kind="object",
                name_ru="ЗаписьJSON",
                description="Запись данных в формате JSON",
                since="8.3.6",
            )
        ],
        "8.3.5.1570",
    )

    ответ = get_syntax(registry, "ЗаписьJSON")

    assert "появился в версии **8.3.6**" in ответ
    assert "Нужен способ, доступный в 8.3.5.1570" in ответ
    assert "Чем заменить" not in ответ


def test_поиск_помечает_скрытые_элементы_у_которых_есть_замена(tmp_path):
    """Выдача поиска рецепт не несёт — она называет, что его стоит спросить."""
    registry = реестр(
        tmp_path,
        [
            SyntaxItem(
                id="ctx/СтрРазделить",
                kind="method",
                name_ru="СтрРазделить",
                description="Разделяет строку на части",
                since="8.3.6",
            ),
            SyntaxItem(
                id="obj/ЗаписьJSON",
                kind="object",
                name_ru="ЗаписьJSON",
                description="Разделяет данные на объекты JSON",
                since="8.3.6",
            ),
            # Видимый элемент нужен, чтобы выдача вообще состоялась: когда
            # фильтр версии скрывает всё, поиск отвечает «ничего не найдено» и
            # блока скрытых не печатает. Это отдельный дефект, он записан в
            # доску задач.
            SyntaxItem(
                id="ctx/СтрЧислоСтрок",
                kind="method",
                name_ru="СтрЧислоСтрок",
                description="Разделяет текст на строки и считает их",
            ),
        ],
        "8.3.5.1570",
    )

    ответ = search_syntax(registry, "разделяет")

    assert "`СтрРазделить` — с 8.3.6 · есть замена" in ответ
    assert "`ЗаписьJSON` — с 8.3.6\n" in ответ
    assert "РазделитьСтроку" not in ответ


def test_поиск_прямо_велит_спросить_рецепт(tmp_path):
    """Отметка «есть замена» — намёк, а агент отвечает буквально.

    Проверено на живом агенте 2026-08-17: подсказку в блоке скрытых он увидел,
    но второго вызова не сделал и доложил «метода нет». Рецепт достался только
    после прямого вопроса «чем заменить». Значит нужна не пометка, а указание —
    как в `list_configurations`, где строка «указывайте config явно» работает.
    """
    registry = реестр(
        tmp_path,
        [
            SyntaxItem(
                id="ctx/СтрРазделить",
                kind="method",
                name_ru="СтрРазделить",
                description="Разделяет строку на части",
                since="8.3.6",
            ),
            SyntaxItem(
                id="ctx/СтрЧислоСтрок",
                kind="method",
                name_ru="СтрЧислоСтрок",
                description="Разделяет текст на строки и считает их",
            ),
        ],
        "8.3.5.1570",
    )

    ответ = search_syntax(registry, "разделяет")

    assert "get_syntax" in ответ


