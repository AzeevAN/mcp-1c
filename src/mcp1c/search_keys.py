"""Поисковые ключи языка запросов: чем спрашивают против того, как названо.

Разрыв тут другой природы, чем в словаре конфигураций. Там человек называет
объект чужим словом («заказ клиента» вместо `ЗаказПокупателя`) — лечится
синонимом. Здесь человек **описывает задачу**, а не называет конструкцию:
«количество дней между двумя датами» против `РАЗНОСТЬДАТ`, «убрать повторы»
против `РАЗЛИЧНЫЕ`. Общих слов с целью ноль, и синоним не поможет — заменять
нечего.

Метод известен как doc2query: к документу офлайн приписываются вопросы, на
которые он отвечает, и попадают в обычный лексический индекс отдельным полем.
В рантайме не весит ничего — то же поле, тот же поиск.

**Ключи сочинены, а не выгружены.** Отсюда три ограничения, они записаны
правилом в `docs/data-sources.md`:

- слой живёт здесь, в git, с ревью — а не приписывается разобранному элементу;
- в ответ агенту не попадает: ответ по-прежнему собирается только из справки,
  ключи работают исключительно на попадание в нужную статью;
- привязка по идентификатору страницы, и непривязанный ключ обязан быть виден
  при загрузке (`coverage`), а не проявляться просевшим поиском.

Ключи заведены не всем 127 элементам, и это осознанно. У `Sin`, `Cos`, `Exp`
разрыва нет: спрашивают тем же словом, которым названо. Приписывать им
формулировки — добавлять шум там, где поиск и так не бился.

Формулировки писались по тексту статей, без сверки с `tests/queries/`:
подгонка ключей под набор, которым потом меряют, обесценивает замер.
"""

