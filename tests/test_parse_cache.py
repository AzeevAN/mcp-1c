"""Компактный кэш разборов модулей для `get_procedure`/`search_procedures`.

Разбор модуля — 75–95% времени этих инструментов, а пакет кода после
публикации не меняется. Проверяется наблюдаемое: повтор не зовёт `разобрать`,
выдача совпадает с холодной, новое поколение не получает старый разбор,
бюджет вытесняет давно не тронутые модули.
"""

from __future__ import annotations

from concurrent.futures import ThreadPoolExecutor

import pytest

from mcp1c import tools
from mcp1c.registry import RegistryError

from native_export import загрузить_код


@pytest.fixture
def разборы(monkeypatch):
    счётчик = {"всего": 0}
    настоящий = tools.разобрать

    def считать(текст, **kwargs):
        счётчик["всего"] += 1
        return настоящий(текст, **kwargs)

    monkeypatch.setattr(tools, "разобрать", считать)
    return счётчик


def test_повторное_оглавление_и_карточка_не_разбирают_модуль(
    реестр_с_кодом, разборы
):
    первое = tools.get_procedure(
        реестр_с_кодом, "ОбщийМодуль.ОбщийПример", config="Пример"
    )
    второе = tools.get_procedure(
        реестр_с_кодом, "ОбщийМодуль.ОбщийПример", config="Пример"
    )
    карточка = tools.get_procedure(
        реестр_с_кодом, "ОбщийМодуль.ОбщийПример::Сложить", config="Пример"
    )

    assert разборы["всего"] == 1
    assert первое == второе
    assert "Функция Сложить(Первый, Второй) Экспорт" in первое
    # Тело карточка по-прежнему читает с диска: в кэше текста нет.
    assert "Возврат Первый + Второй" in карточка


def test_карточка_из_кэша_совпадает_с_холодной(реестр_с_кодом, разборы):
    адрес = "ОбщийМодуль.ОбщийПример::Внутренняя"
    холодная = tools.get_procedure(реестр_с_кодом, адрес, config="Пример")
    тёплая = tools.get_procedure(реестр_с_кодом, адрес, config="Пример")

    assert разборы["всего"] == 1
    assert тёплая == холодная
    assert "Сложить(1, 2);" in тёплая


def test_повторный_поиск_не_разбирает_модули(реестр_с_кодом, разборы):
    первый = tools.search_procedures(реестр_с_кодом, "Сложить", config="Пример")
    после_первого = разборы["всего"]
    второй = tools.search_procedures(реестр_с_кодом, "Сложить", config="Пример")

    assert после_первого >= 1
    assert разборы["всего"] == после_первого
    assert второй == первый
    assert "Функция Сложить(Первый, Второй) Экспорт" in второй


def _модуль_смены(корень, текст: str) -> None:
    каталог = корень / "CommonModules" / "Смена" / "Ext"
    каталог.mkdir(parents=True, exist_ok=True)
    (каталог / "Module.bsl").write_text(текст, encoding="utf-8")


def test_новое_поколение_не_получает_старый_разбор(
    корень_кода, реестр_из_кода, архив_кода, разборы
):
    _модуль_смены(
        корень_кода, "Процедура Сменить(СтарыйПараметр) Экспорт\nКонецПроцедуры\n"
    )
    реестр = реестр_из_кода(корень_кода)
    старое = tools.get_procedure(реестр, "ОбщийМодуль.Смена", config="Пример")
    assert "СтарыйПараметр" in старое

    # Те же имя и число процедур, другие сигнатура и номер строки: при
    # ключе только по адресу модуля кэш отдал бы старую сигнатуру.
    _модуль_смены(
        корень_кода,
        "// новое поколение\n"
        "Процедура Сменить(НовыйПараметр) Экспорт\nКонецПроцедуры\n",
    )
    загрузить_код(реестр, архив_кода(корень_кода), configuration="Пример")
    до = разборы["всего"]

    оглавление = tools.get_procedure(реестр, "ОбщийМодуль.Смена", config="Пример")
    поиск = tools.search_procedures(реестр, "Сменить", config="Пример")

    assert разборы["всего"] == до + 1
    for ответ in (оглавление, поиск):
        assert "НовыйПараметр" in ответ
        assert "СтарыйПараметр" not in ответ
        assert "строка 2" in ответ


def test_снятый_код_не_отдаётся_из_кэша(корень_кода, реестр_из_кода, разборы):
    реестр = реестр_из_кода(корень_кода)
    assert "Сложить" in tools.get_procedure(
        реестр, "ОбщийМодуль.ОбщийПример", config="Пример"
    )

    реестр.remove("Пример:modules")
    try:
        ответ = tools.get_procedure(
            реестр, "ОбщийМодуль.ОбщийПример", config="Пример"
        )
    except RegistryError as ошибка:
        ответ = str(ошибка)

    assert "Функция Сложить" not in ответ


def test_бюджет_вытесняет_давно_не_тронутый_модуль(
    реестр_с_кодом, разборы, monkeypatch
):
    общий = "ОбщийМодуль.ОбщийПример"
    объект = "Документ.Пример.МодульОбъекта"
    # Размер записей узнаём на щедром бюджете, затем оставляем место ровно
    # под одну, бо́льшую из двух.
    monkeypatch.setattr(tools, "_РАЗБОРЫ", tools._КэшРазборов(1 << 30))
    tools.get_procedure(реестр_с_кодом, общий, config="Пример")
    tools.get_procedure(реестр_с_кодом, объект, config="Пример")
    размеры = [запись.размер for запись in tools._РАЗБОРЫ._записи.values()]
    assert len(размеры) == 2 and all(размер > 0 for размер in размеры)

    кэш = tools._КэшРазборов(max(размеры))
    monkeypatch.setattr(tools, "_РАЗБОРЫ", кэш)
    первое = tools.get_procedure(реестр_с_кодом, общий, config="Пример")
    tools.get_procedure(реестр_с_кодом, объект, config="Пример")
    до = разборы["всего"]

    tools.get_procedure(реестр_с_кодом, объект, config="Пример")
    assert разборы["всего"] == до
    повтор = tools.get_procedure(реестр_с_кодом, общий, config="Пример")

    assert разборы["всего"] == до + 1
    assert повтор == первое
    assert кэш.объём <= кэш.предел


def test_параллельные_вызовы_дают_одну_выдачу_и_сходящийся_объём(
    реестр_с_кодом, monkeypatch
):
    адреса = [
        "ОбщийМодуль.ОбщийПример",
        "ОбщийМодуль.ОбщийПример::Сложить",
        "Документ.Пример.МодульОбъекта",
    ]
    эталон = {
        адрес: tools.get_procedure(реестр_с_кодом, адрес, config="Пример")
        for адрес in адреса
    }
    кэш = tools._КэшРазборов(1 << 30)
    monkeypatch.setattr(tools, "_РАЗБОРЫ", кэш)
    расхождения: list[str] = []

    def читать(номер: int) -> None:
        адрес = адреса[номер % len(адреса)]
        ответ = tools.get_procedure(реестр_с_кодом, адрес, config="Пример")
        if ответ != эталон[адрес]:
            расхождения.append(адрес)

    with ThreadPoolExecutor(max_workers=8) as пул:
        list(пул.map(читать, range(64)))

    assert not расхождения
    assert len(кэш._записи) == 2
    assert кэш.объём == sum(запись.размер for запись in кэш._записи.values())


def test_тело_не_совпавшее_с_закэшированными_границами_не_отдаётся(
    реестр_с_кодом, monkeypatch
):
    """Границы из кэша, текст — заново с диска: если текст под тем же
    пакетом разошёлся с границами, рассогласованное тело не уходит в ответ."""
    адрес = "ОбщийМодуль.ОбщийПример::Сложить"
    tools.get_procedure(реестр_с_кодом, адрес, config="Пример")
    monkeypatch.setattr(
        tools, "_read_module_snapshot", lambda *args, **kwargs: "\n" * 40
    )

    with pytest.raises(RegistryError, match="сопоставить оглавление"):
        tools.get_procedure(реестр_с_кодом, адрес, config="Пример")


def test_снятый_пакет_освобождает_кэш_без_нового_обращения(реестр_с_кодом):
    import gc

    tools.get_procedure(реестр_с_кодом, "ОбщийМодуль.ОбщийПример", config="Пример")
    assert tools._РАЗБОРЫ.объём > 0
    for source_id in list(реестр_с_кодом.modules):
        реестр_с_кодом.remove(source_id.split(":")[0])
        break
    gc.collect()

    assert tools._РАЗБОРЫ.объём == 0
