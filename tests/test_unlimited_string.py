"""Строки неограниченной длины: пометка у поля и оговорка на карточке.

Живой промах 2026-08-18. Агент собрал запрос с группировкой по реквизиту
`Документ.ЧекККМ.ПредъявленныеКодыОднократныхСкидок.КодСкидки` — строке без
ограничения длины. Платформа такой запрос не выполняет. Данные наши были
верны, но разница читалась только по отсутствию числа в скобках:

    `КодСкидки` — Строка          <- неограниченная
    `КодМаркировки` — Строка(200)

Таких полей в живых конфигурациях от 23% до 38% строковых, то есть это не
единичный случай, а мина под каждым третьим строковым реквизитом.
"""

from mcp1c.model import Configuration, Field, MetadataObject
from mcp1c.render import BRIEF, FIELDS, FULL, render_object


def _объект(*поля: Field) -> MetadataObject:
    return MetadataObject(
        full_name="Документ.ЧекККМ",
        kind="Документ",
        name="ЧекККМ",
        synonym="Чек",
        attributes=list(поля),
    )


КОД_СКИДКИ = Field(name="КодСкидки", synonym="Код скидки", types=["Строка"])
КОД_МАРКИРОВКИ = Field(
    name="КодМаркировки", synonym="Код маркировки", types=["Строка"], string_length=200
)


def test_строка_поля_сама_несёт_рецепт():
    """Пометка `(неогр.)` смысла не несёт: чтобы понять, чем она грозит, надо
    помнить оговорку. Проверено 2026-08-18 на живом агенте — он вызвал
    `get_object` с `detail=fields`, получил карточку с оговоркой и всё равно
    сгруппировал по такому полю. Оговорка стояла последним абзацем, на 721
    токен позже строки поля: решение принимается там, где имя копируют.
    """
    строка = next(
        s for s in render_object(_объект(КОД_СКИДКИ)).splitlines()
        if s.startswith("- `КодСкидки`")
    )

    assert "ПОДСТРОКА" in строка


def test_оговорка_стоит_до_списка_полей():
    """Правило, прочитанное после того, как поле выбрано, не работает."""
    карточка = render_object(_объект(КОД_СКИДКИ))

    assert карточка.index("ПОДСТРОКА(КодСкидки") < карточка.index("## Реквизиты")


def test_строка_без_длины_помечена_неограниченной():
    """Выгрузка пишет `string_length` только когда длина больше нуля, поэтому
    у неограниченной ключа нет вовсе. Отсутствие ключа у строкового поля и
    означает «неограниченная» — `КвалификаторыСтроки.Длина` там ноль."""
    assert КОД_СКИДКИ.type_spec() == "Строка (неогр. — только через ПОДСТРОКА)"
    assert КОД_МАРКИРОВКИ.type_spec() == "Строка(200)"


def test_оговорка_печатается_один_раз_на_карточку():
    карточка = render_object(_объект(КОД_СКИДКИ, Field(name="Штрихкод", types=["Строка"])))

    assert карточка.count("ПОДСТРОКА(") == 1
    assert "неогр." in карточка


def test_оговорка_называет_все_запреты_проверенные_на_платформе():
    """Проверено владельцем 2026-08-18 запросами по КодСкидки: падают
    сравнение, группировка, упорядочивание, РАЗЛИЧНЫЕ и ОБЪЕДИНИТЬ. Агрегатные
    стоят в самой справке. Оговорок вида «возможно» здесь больше нет — каждое
    слово подтверждено либо справкой, либо прогоном на живой базе."""
    карточка = render_object(_объект(КОД_СКИДКИ))

    for запрет in ("сравнивать", "группировать", "упорядочивать",
                   "РАЗЛИЧНЫЕ", "ОБЪЕДИНИТЬ", "КОЛИЧЕСТВО"):
        assert запрет in карточка, запрет
    assert "небезопасн" not in карточка


def test_без_неограниченных_полей_оговорки_нет():
    """Оговорка стоит токенов на каждой карточке, где напечатана. У объектов
    без таких полей — а это большинство — её быть не должно."""
    карточка = render_object(_объект(КОД_МАРКИРОВКИ))

    assert "ПОДСТРОКА(" not in карточка
    assert "неогр." not in карточка


def test_беглый_взгляд_оговорки_не_показывает():
    """`brief` — заголовок, свойства, счётчики; полей там нет вовсе, и
    оговорка про поля без них бессмысленна."""
    assert "ПОДСТРОКА(" not in render_object(_объект(КОД_СКИДКИ), detail=BRIEF)
    assert "ПОДСТРОКА(" in render_object(_объект(КОД_СКИДКИ), detail=FIELDS)
    assert "ПОДСТРОКА(" in render_object(_объект(КОД_СКИДКИ), detail=FULL)


def test_пример_в_оговорке_не_выдумывает_имя_таблицы():
    """Имя поля берётся с этой же карточки — по нему видно, о чём речь.
    А вот псевдоним таблицы взять неоткуда: в запросе агента он свой, и
    подставленный нами `Таблица.` пришлось бы мысленно вычёркивать."""
    карточка = render_object(_объект(КОД_СКИДКИ))

    assert "ПОДСТРОКА(КодСкидки, 1, 100)" in карточка
    assert "Таблица." not in карточка


def test_дашборд_не_рвёт_цитату_на_пустой_строке():
    """Пустая строка внутри цитаты пишется одним знаком `>` без пробела.
    `render_markdown` узнавал только `«> »` с пробелом, и оговорка на странице
    разваливалась на три блока с абзацами `&gt;` между ними."""
    from mcp1c.dashboard_backend import render_markdown

    html = render_markdown("> Первая строка.\n>\n> Вторая строка.")

    assert html.count("<blockquote>") == 1
    assert "&gt;" not in html
    assert "Первая строка." in html and "Вторая строка." in html
