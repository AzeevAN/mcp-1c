"""Приём выгрузки конфигурации в файлы: что берём из архива и куда кладём.

Форматов выгрузки два, и раскладка у них разная (разведка, раздел 6).
Определяем по содержимому, а не по имени архива: имя даёт человек.
"""
from __future__ import annotations

import shutil
import zipfile
from pathlib import Path, PurePosixPath

FORMAT_TREE = "tree"
FORMAT_FLAT = "flat"

# Иерархическая: модуль — отдельный файл, форма — разбираемый XML.
_TREE_SUFFIXES = {".bsl"}
_TREE_NAMES = {"Form.xml"}
# Плоская: модуль в `.txt`, код формы — записью внутри контейнера `.Form`.
_FLAT_SUFFIXES = {".txt", ".Form"}


def detect_format(names: list[str]) -> str:
    """Контейнер `.Form` встречается только в плоской выгрузке."""
    for имя in names:
        if имя.endswith(".Form"):
            return FORMAT_FLAT
    return FORMAT_TREE


def is_wanted(name: str, формат: str) -> bool:
    путь = PurePosixPath(name)
    # Мусор архиватора Finder на macOS («Сжать объекты»): `__MACOSX/` несёт
    # копии ресурсных вилок каждого файла под именем `._Имя` — с тем же
    # суффиксом, что у оригинала. Без исключения `__MACOSX/.../._ObjectModule.bsl`
    # проходит отбор как настоящий `.bsl`, а `._Ext.txt` — как настоящий
    # плоский модуль: рядом с кодом на диске ложится двоичный
    # AppleDouble-файл (найдено ре-ревью: `items_total=2` на архиве с одним
    # настоящим модулем).
    if путь.parts and путь.parts[0] == "__MACOSX":
        return False
    if путь.name.startswith("._"):
        return False
    if формат == FORMAT_FLAT:
        return путь.suffix in _FLAT_SUFFIXES
    return путь.suffix in _TREE_SUFFIXES or путь.name in _TREE_NAMES


def _единственный_верхний_каталог(zf: zipfile.ZipFile) -> str | None:
    """Имя каталога-обёртки — если архив целиком упакован внутрь одного
    каталога верхнего уровня, `None` иначе.

    Правило общее на три вызывающих: `extract`/`planned_size` ниже снимают
    этот уровень при раскладке по диску, `registry._найти_configuration_xml`
    ищет тем же способом `Configuration.xml`, чтобы распознать вид выгрузки
    внутри обёртки, `registry._отбираемых_членов` — предпроверка «есть ли
    что взять» — считает по тем же именам, что реально лягут на диск.
    Правило одно, вызывающих три — как `index_cache.safe_name` для очистки
    имён: разойдись оно на первом же необычном архиве, и распознавание вида
    выгрузки перестало бы совпадать с тем, что реально легло на диск.

    Архив, собранный командой `zip -r архив.zip папка` или через Finder
    («Сжать объекты») на macOS, кладёт всё содержимое внутрь одной папки.
    Finder вдобавок добавляет мусор — служебный каталог `__MACOSX/` (копии
    ресурсных вилок, `._Имя` на каждый файл) и иногда `.DS_Store` прямо в
    корне архива; оба в расчёт не идут: это не второй каталог верхнего
    уровня и не содержимое, которое стоит замечать.

    Разбор пути — через `PurePosixPath.parts`, а не срезание строки: у
    `pathlib` двойной слэш и одиночная точка схлопываются сами (`"A//B"` и
    `"A/./B"` дают те же `parts`, что и `"A/B"`), а ведущий слэш — отдельный
    компонент `"/"`, а не пустая строка. Ручной `str.split("/")` этого не
    делает и превращает абсолютный путь в кандидата на имя обёртки — тогда
    `_без_обёртки` срезала бы у члена ровно то, что помечает его как
    выходящий за пределы корня, и `safe_target` переставал его отвергать
    (ре-ревью: архив из одних абсолютных путей писал файлы на диск).

    `None`, если в корне лежит файл, отличный от `.DS_Store` (содержимое не
    целиком внутри одной папки), каталогов верхнего уровня несколько, путь
    абсолютный, или первый компонент — `..`/`.`/пустая строка (то же самое,
    что `safe_target` отвергает у отдельного члена: считать это обёрткой
    означало бы снять стриппингом именно ту часть пути, которая должна была
    провалить проверку выхода за пределы корня; пустая строка через
    `PurePosixPath.parts` не должна возникать вовсе — см. выше, — но
    проверка не полагается на это молча) — угадывать, какой из кандидатов
    «тот самый», рискованнее, чем не снимать уровень вовсе.

    Настоящий единственный каталог верхнего уровня без обёртки (например,
    расширение, где все объекты — в `Catalogs/`) сюда снятым не попадает:
    без `Configuration.xml` в корне или в этом самом каталоге распознавание
    вида выгрузки (`registry._сведения_о_выгрузке`) отказывает раньше, чем
    архив вообще доходит до `extract` — см. тест
    `test_единственный_каталог_без_манифеста_отклоняется`.
    """
    каталоги: set[str] = set()
    for info in zf.infolist():
        путь = PurePosixPath(info.filename)
        части = путь.parts
        if not части:
            # "." или "" сами по себе — `pathlib` схлопывает такие
            # компоненты без следа (см. докстроку). Не файл и не каталог
            # содержимого — гадать, что это, рискованнее отказа.
            return None
        if части[0] == "__MACOSX":
            continue
        if путь.is_absolute() or части[0] in ("..", ".", ""):
            return None
        if len(части) == 1:
            if not info.is_dir():
                if части[0] == ".DS_Store":
                    continue
                return None
            каталоги.add(части[0])
            continue
        каталоги.add(части[0])
    if len(каталоги) != 1:
        return None
    return next(iter(каталоги))


def _без_обёртки(name: str, обёртка: str | None) -> str:
    """Путь члена архива без каталога-обёртки (см. `_единственный_верхний_каталог`).

    Снимается покомпонентно, через `PurePosixPath.parts`, а не срезанием
    строкового префикса: у `"Обёртка//Catalogs/…"` (двойной слэш — не
    редкость при ручной сборке архива) строковый срез `"Обёртка/"` оставлял
    бы один слэш из двух и превращал остаток в `"/Catalogs/…"` — абсолютный
    путь, который `safe_target` затем тихо отвергал, хотя `planned_size` его
    уже посчитал (ре-ревью). `PurePosixPath` двойной слэш схлопывает сам.

    Мусор Finder (`__MACOSX/`, корневой `.DS_Store`) под обёрткой не лежит —
    она вычисляется без него, поэтому первый компонент к таким именам не
    подходит, и они возвращаются как есть; их отбраковывает собственное
    правило `is_wanted`.
    """
    if обёртка is None:
        return name
    части = PurePosixPath(name).parts
    if части[:1] != (обёртка,):
        return name
    остаток = части[1:]
    return str(PurePosixPath(*остаток)) if остаток else name


def safe_target(name: str, корень: Path) -> Path | None:
    """Куда лечь члену архива. `None` — член отвергнут.

    `ZipFile.open` путь не чистит, в отличие от `extract`: имя внутри архива
    приходит от того, кто архив собрал, и может увести наружу корня.
    """
    путь = PurePosixPath(name)
    if путь.is_absolute() or ".." in путь.parts:
        return None
    цель = (корень / Path(*путь.parts)).resolve()
    корень = корень.resolve()
    if корень != цель and корень not in цель.parents:
        return None
    return цель


# Индекс пишется после отбора и в сумму отобранного не входит. По разведке на
# корпусе Розницы это 18,1 МБ сигнатур и 5,8 МБ форм — берём с запасом.
INDEX_RESERVE = 25 * 1024 * 1024


def planned_size(архив: Path) -> tuple[int, str]:
    """Сколько места займёт отобранное, плюс запас под индекс.

    Размеры берутся из центрального каталога: тело архива не читается вовсе.
    Соврать в опасную сторону это не может — `zipfile` обрезает вывод по
    объявленному размеру, а несовпадение ловит CRC.

    Цифра точная для обоих форматов. Постановка допускала для плоской выгрузки
    «оценку сверху» на том основании, что двоичную запись `form` внутри
    контейнера `.Form` мы не сохраняем, — но `is_wanted` берёт контейнер
    целиком, вместе с ней: разбирать контейнер здесь означало бы тащить в
    приём `v8container`. Что взвешено, то и ляжет на диск.

    Обёртка архива (`_единственный_верхний_каталог`) на сумму не влияет: имя
    без неё то же самое по суффиксу и по последнему компоненту, а значит и
    `is_wanted` решает одинаково что с обёрткой, что без — обёртка меняет
    только КУДА член ляжет (`extract`), а не ЧТО отобрано. Снимаем её здесь
    ровно затем, чтобы совпадение считалось честно, а не по совпадению.
    """
    with zipfile.ZipFile(архив) as zf:
        записи = [i for i in zf.infolist() if not i.is_dir()]
        формат = detect_format([i.filename for i in записи])
        обёртка = _единственный_верхний_каталог(zf)
        нужно = sum(
            i.file_size
            for i in записи
            if is_wanted(_без_обёртки(i.filename, обёртка), формат)
        )
    return нужно + INDEX_RESERVE, формат


def enough_space(нужно: int, каталог: Path) -> tuple[bool, int]:
    свободно = shutil.disk_usage(каталог).free
    return свободно >= нужно, свободно


# Версия правила отбора. Поднимается, когда меняется то, ЧТО мы достаём из
# архива, — тогда и только тогда нужен переразбор zip. Правки, меняющие лишь
# индекс, сервер переживает сам, пересобрав его из `data/modules/`.
#
# 2: обёртка архива (единственный каталог верхнего уровня — `zip -r архив.zip
# папка` или Finder) больше не воспроизводится в целевом пути. Меняется КУДА
# ложится уже отобранное — тот же файл, разобранный старым правилом, лежит на
# диске на один уровень глубже, чем разобранный новым.
SELECTION_VERSION = 2


def extract(архив: Path, корень: Path) -> tuple[int, int]:
    """Достать из архива модули и формы. Возвращает (файлов, байт).

    Читается членом за членом: развёрнутого архива на диске не возникает.
    Счётчики отражают количество файлов и байт, реально лежащих на диске:
    при дублирующихся имёнах в архиве последняя запись побеждает, и считается
    только фактическое содержимое на диске.

    Обёртка архива (единственный каталог верхнего уровня — см.
    `_единственный_верхний_каталог`) в целевом пути не воспроизводится: член
    `Обёртка/Catalogs/…` ложится как `<корень>/Catalogs/…`, а не
    `<корень>/Обёртка/Catalogs/…`. Санитизация (`safe_target`) применяется
    ПОСЛЕ снятия обёртки, а не вместо неё — снимается только обёртка из
    имени, правило безопасности остаётся прежним.
    """
    содержимое_целей = {}  # цель → размер последней записи
    корень.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(архив) as zf:
        записи = [i for i in zf.infolist() if not i.is_dir()]
        формат = detect_format([i.filename for i in записи])
        обёртка = _единственный_верхний_каталог(zf)
        for info in записи:
            имя = _без_обёртки(info.filename, обёртка)
            if not is_wanted(имя, формат):
                continue
            цель = safe_target(имя, корень)
            if цель is None:
                continue
            цель.parent.mkdir(parents=True, exist_ok=True)
            with zf.open(info) as входящий, цель.open("wb") as исходящий:
                shutil.copyfileobj(входящий, исходящий, length=1 << 20)
            # При дублирующихся именах (после снятия обёртки тоже) запоминаем
            # размер последней записи.
            содержимое_целей[цель] = info.file_size
    файлов = len(содержимое_целей)
    байт = sum(содержимое_целей.values())
    return файлов, байт
