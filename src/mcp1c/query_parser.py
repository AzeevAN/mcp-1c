# Страницы секций языка запросов. По ним справка отличается от соседних:
# `__categories__` есть и у `shlang_ru.hbk`, а секций у него ноль.
SECTION_PAGES = ("SELECTSection", "UNIONSection", "ORDERBYSection")

# Граница «статья против ключевого слова». Сравнивается с длиной уже
# декодированного текста страницы, не с байтами исходного файла: кириллица в
# UTF-8 занимает два байта на символ, и порог по сырым байтам делит примерно
# вдвое не там, где размечено на самом деле (замер 2026-08-17: 8 длинных
# статей и 119 коротких страниц из 127 элементов, медиана страницы 1 438 Б —
# это тоже байты исходника, но сам порог с тех пор проверяется по символам).
ARTICLE_BYTES = 8192

# `present.html` — двуязычная таблица ключевых слов рус↔англ (см.
# `docs/query-language-design.md`, раздел «Разбор»), а не статья и не
# ключевое слово. Разбор пар терминов из неё — отдельная задача, отложена.
СЛУЖЕБНЫЕ = ("__categories__", "present.html")

# Место диаграммы в потоке абзацев. Нулевой байт в HTML-тексте справки не
# встречается, и ни `_text()`, ни `_свернуть()` его не трогают.
_МЕТКА = "\x00диаграмма-{номер}\x00"

# Ячейка ровно из этого — нарисованная линия ветвления, а не содержимое.
_ЧЕРТА = "|"


class ОбрывТаблицы(ValueError):
    """Разметка таблицы на странице не сходится.

    Отдельный класс, чтобы вызывающий отличал испорченную разметку от
    любой другой ошибки и мог сказать о ней вслух, а не проглотить.
    """


def looks_like_query_help(names: Iterable[str]) -> bool:
    """Похоже ли содержимое контейнера на справку по языку запросов."""
    имена = set(names)
    if any(name.startswith("objects/") for name in имена):
        return False
    if "__categories__" not in имена:
        return False
    return any(section in имена for section in SECTION_PAGES)


_RE_H1 = re.compile(r"<h1[^>]*>(.*?)</h1>", re.I | re.S)
_RE_P = re.compile(r"<p[^>]*>(.*?)</p>", re.I | re.S)
_RE_BLOCKQUOTE = re.compile(r"<blockquote[^>]*>(.*?)</blockquote>", re.I | re.S)
_RE_PRE = re.compile(r"<pre[^>]*>(.*?)</pre>", re.I | re.S)
_RE_TABLE_TAG = re.compile(r"<(/?)table\b[^>]*>", re.I)
_RE_TR = re.compile(r"<tr[^>]*>(.*?)</tr>", re.I | re.S)
_RE_TD = re.compile(r"<t[dh][^>]*>(.*?)</t[dh]>", re.I | re.S)
# Позиции тегов — не их содержимое: чтобы понять, какой из двух стоит на
# странице раньше, а не пытаться распарсить их вложенность. `(?=[\s>])`
# отсекает ложное совпадение `<p...>` внутри `<pre...>` (у него после «p»
# идёт «r», а не пробел и не «>»).
_RE_PRE_TAG = re.compile(r"<pre[^>]*>", re.I)
_RE_REAL_P_TAG = re.compile(r"<p(?=[\s>])[^>]*>", re.I)
# «Функция КОНЕЦПЕРИОДА» -> «КОНЕЦПЕРИОДА». Слово-приставка в заголовке нужна
# человеку, а искать будут по имени. «Агрегатная функция» — та же приставка,
# просто длиннее. Приставка — в своей группе: и `_имя()`, и `_вид_по_заголовку()`
# разбирают заголовок этой единственной регуляркой, чтобы у них не могло
# разойтись правило (`startswith` без проверки границы слова после приставки
# отличалась бы от требующей пробел регулярки — например, «ФункцияОсобая»
# без пробела `startswith` посчитал бы функцией, а регулярка — нет).
_RE_ЗАГОЛОВОК = re.compile(
    r"^(Агрегатная функция|Функция|Оператор|Ключевое слово|Литерал типа|"
    r"Секция|Предложение)\s+(.+)$"
)
# «КОНЕЦПЕРИОДА (<Дата периода>, <Тип периода>)» — сигнатура, а не проза.
# Сопоставляется не с сырым абзацем, а со схлопнутым `_свернуть()`: длинные
# сигнатуры в исходнике переносятся на вторую строку ради читаемости, а без
# схлопывания `.` без `re.S` за перенос не видит — страница молча уезжает в
# keyword.
_RE_СИГНАТУРА = re.compile(r"^([A-ZА-ЯЁ][A-Za-zА-Яа-яЁё0-9]*)\s*\((.*)\)\s*$")
# «<Дата периода> – выражение типа ДАТА, …» — строка параметра. Тире в
# источнике встречается трёх видов: короткое, длинное и дефис-заменитель.
_RE_ПАРАМЕТР = re.compile(r"^<([^<>]+)>\s*[–—-]?\s*(.*)$")


def _разобрать_заголовок(заголовок: str) -> tuple[str, str]:
    """(приставка, имя без приставки). Приставка пустая, если заголовок не
    начинается ни с одного из известных слов ровно по правилу регулярки —
    отсюда одно место разбора на оба потребителя (`_имя`, `_вид_по_заголовку`),
    а не два похожих правила, которые могут разойтись."""
    совпало = _RE_ЗАГОЛОВОК.match(заголовок)
    if совпало is None:
        return "", заголовок
    return совпало.group(1), совпало.group(2).strip()


def _имя(заголовок: str) -> str:
    _, имя = _разобрать_заголовок(заголовок)
    return имя


def _без_английского(имя: str, name_en: str) -> str:
    """Убрать английское имя из русского: «СтрНайти(StrFind)» → «СтрНайти».

    Часть страниц справки по языку запросов озаглавлена обоими именами сразу.
    Английское и так лежит в `name_en` (берётся из имени файла), а внутри
    русского оно ломает точное совпадение: `get_syntax("СтрНайти")` отвечал
    «Точного совпадения нет» и предлагал в подсказках сам `СтрНайти(StrFind)`.
    На `shquery_ru.hbk` так названы 8 функций из 127, среди них `Лев`, `Прав`,
    `ВРег`, `НРег`, `СтрЗаменить`.

    Скобка снимается только когда внутри действительно английское имя этой же
    страницы: скобка в заголовке бывает и содержательной.
    """
    if not name_en:
        return имя
    совпало = re.match(r"^(.*?)\s*\(([^()]+)\)$", имя)
    if совпало is None:
        return имя
    внутри = совпало.group(2).strip()
    if внутри.casefold() != name_en.strip().casefold():
        return имя
    очищенное = совпало.group(1).strip()
    return очищенное or имя


def _свернуть(текст: str) -> str:
    """Схлопнуть пробелы и переносы строк в один пробел.

    `_text()` переносы внутри абзаца сохраняет — они разметке HTML не мешают,
    но строке-выражению вроде сигнатуры функции они не нужны и мешают её
    разобрать регуляркой без `re.S`.
    """
    return re.sub(r"\s+", " ", текст).strip()


def _вид_по_заголовку(заголовок: str, body: str) -> str:
    """Вид элемента: сначала слово в заголовке, только потом — длина текста.

    Определять функцию по наличию сигнатуры нельзя: у 22 функций из 52 (даты
    вроде «Функция МЕСЯЦ», «Функция ГОД», агрегатные «Агрегатная функция
    СРЕДНЕЕ») сигнатуры на странице нет вовсе, только проза — по сигнатуре
    они бы потерялись (замер на реальном файле 2026-08-17 после всех правок
    парсера; из оставшихся 30 функций с сигнатурой 27 берут её из `<PRE>`,
    3 — из первой строки первого абзаца, см. `_сигнатура_функции`).
    """
    приставка, _ = _разобрать_заголовок(заголовок)
    if приставка in ("Функция", "Агрегатная функция"):
        return KIND_QUERY_FUNCTION
    if len(body) > ARTICLE_BYTES:
        return KIND_QUERY_ARTICLE
    return KIND_QUERY_KEYWORD


def _сигнатура_функции(body: str, абзацы: list[str]) -> tuple[str, bool]:
    """Найти сигнатуру функции. Возвращает (сигнатура, взята_из_абзаца).

    Порядок: сначала `<PRE>`, если он стоит раньше первого настоящего `<P>`
    (так у 27 функций из 52 — математических и строковых вроде Sin, Left);
    иначе — первая строка первого абзаца, если похожа на вызов (так у 3 из
    52, включая КОНЕЦПЕРИОДА, ДОБАВИТЬКДАТЕ). Ещё у 22 из 52 сигнатуры нет
    нигде — только проза, `_вид_по_заголовку()` их не теряет. Порядок именно
    такой, а не «любой `<PRE>` на странице»: у части функций с сигнатурой в
    абзаце (СГРУППИРОВАНОПО) `<PRE>` тоже есть, но дальше по странице — это
    код примера, а не сигнатура; взять его безусловно значило бы сломать уже
    работающий разбор.
    Второй элемент кортежа говорит вызывающему коду, входит ли первый абзац
    в сигнатуру (и его нужно убрать из description) или нет.
    """
    pre_tag = _RE_PRE_TAG.search(body)
    p_tag = _RE_REAL_P_TAG.search(body)
    if pre_tag is not None and (p_tag is None or pre_tag.start() < p_tag.start()):
        pre = _RE_PRE.search(body)
        if pre is not None:
            return _свернуть(_text(pre.group(1))), False

    if абзацы:
        первый = _свернуть(абзацы[0])
        if _RE_СИГНАТУРА.match(первый):
            return первый, True

    return "", False


def _параметры(тело: str) -> list[SyntaxParam]:
    params: list[SyntaxParam] = []
    for кусок in _RE_P.findall(тело):
        строка = _text(кусок)
        совпало = _RE_ПАРАМЕТР.match(строка)
        if совпало:
            params.append(
                SyntaxParam(name=совпало.group(1).strip(), description=совпало.group(2).strip())
            )
    return params


def _границы_таблиц(body: str) -> list[tuple[int, int]]:
    """Границы таблиц верхнего уровня, с учётом вложенности.

    Регуляркой `<table>.*?</table>` здесь не обойтись: таблицы вложены (7
    страниц справки), и неленивое совпадение останавливается на закрывающем
    теге внутренней. Остаток внешней тогда утекает в описание обычными
    абзацами — ровно тот дефект, ради которого разбор и затевался.
    """
    границы = []
    глубина = 0
    начало = 0
    for тег in _RE_TABLE_TAG.finditer(body):
        открывающий = not тег.group(1)
        if открывающий:
            if глубина == 0:
                начало = тег.start()
            глубина += 1
        elif глубина > 0:
            глубина -= 1
            if глубина == 0:
                границы.append((начало, тег.end()))
    if глубина > 0:
        # Незакрытая таблица. Проглотить остаток страницы молча нельзя: текст
        # после неё — обычная проза, и она нужна и карточке, и поиску.
        raise ОбрывТаблицы(
            f"таблица не закрыта: открывающих <TABLE> на {глубина} больше, "
            "чем закрывающих"
        )
    return границы


def _строки_таблицы(содержимое: str) -> list[list[str]]:
    """Строки и ячейки одной таблицы, без содержимого вложенных."""
    return [
        [_свернуть(_text(ячейка)) for ячейка in _RE_TD.findall(строка)]
        for строка in _RE_TR.findall(содержимое)
    ]


def _отделить_вложенные(содержимое: str) -> tuple[str, list[str]]:
    """Разделить содержимое таблицы на собственное и вложенные таблицы.

    Без этого строки внешней таблицы получаются рваными: `<TD>` вложенной
    попадают в выборку ячеек внешней, и таблица данных с таблицей в колонке
    (в справке такая одна) выглядит как рисованная диаграмма.
    """
    куски, вложенные, предыдущий = [], [], 0
    for начало, конец in _границы_таблиц(содержимое):
        куски.append(содержимое[предыдущий:начало])
        вложенные.append(содержимое[начало:конец])
        предыдущий = конец
    куски.append(содержимое[предыдущий:])
    return "".join(куски), вложенные


def _это_таблица_данных(строки: list[list[str]]) -> bool:
    """Таблица данных против рисованной синтаксической диаграммы.

    Признак по разметке, а не по классу: `class=SimplyTable` стоит не на всех
    (7 настоящих таблиц справки идут без него) и не только на них. Различает
    геометрия. У таблицы данных строки одной ширины и в ячейках значения. У
    диаграммы ширины рваные — колонки держат отступ ветвления, а не смысл, —
    и есть ячейки из одной вертикальной черты: это нарисованная линия.
    """
    if len(строки) < 2 or len({len(строка) for строка in строки}) != 1:
        return False
    return not any(ячейка == "|" for строка in строки for ячейка in строка)


def _лесенка(строки: list[list[str]]) -> str:
    """Диаграмма в текст: отступ по числу пустых ячеек слева.

    Выбрасывать диаграмму нельзя — это грамматика языка запросов, самое
    полезное на странице тому, кто пишет запрос. Печатать её markdown-таблицей
    тоже нельзя: колонок в ней нет, есть уровень ветвления, и он передаётся
    отступом.

    Ячейка из одной вертикальной черты — нарисованная линия, а не текст.
    Приклеенная к содержимому, она читается как часть грамматики: строка
    «| | | | ЛЕВОЕ СОЕДИНЕНИЕ» выглядит перечислением, которого в языке нет.
    Поэтому черта остаётся только там, где вся строка из неё и состоит.
    """
    строки_текста = []
    for строка in строки:
        отступ = next(
            (номер for номер, ячейка in enumerate(строка) if ячейка), 0
        )
        значимые = [
            ячейка for ячейка in строка if ячейка and ячейка != _ЧЕРТА
        ]
        if not значимые:
            if any(строка):
                строки_текста.append("    " * отступ + _ЧЕРТА)
            continue
        строки_текста.append("    " * отступ + " ".join(значимые))
    return "\n".join(строки_текста)


def _разобрать_блок(блок: str, таблицы: list[SyntaxTable]) -> str:
    """Одна таблица со всем вложенным. Возвращает текст, остающийся в описании.

    Таблицы данных уходят в `таблицы` и из описания исчезают; диаграммы
    остаются текстом-лесенкой.
    """
    содержимое = блок[блок.index(">") + 1 : блок.rindex("<")]
    своё, вложенные = _отделить_вложенные(содержимое)
    строки = [строка for строка in _строки_таблицы(своё) if any(строка)]

    куски = []
    if строки:
        if _это_таблица_данных(строки):
            куски.append(МЕТКА_ТАБЛИЦЫ.format(номер=len(таблицы)))
            таблицы.append(SyntaxTable(header=строки[0], rows=строки[1:]))
        else:
            куски.append(_лесенка(строки))
    for вложенная in вложенные:
        куски.append(_разобрать_блок(вложенная, таблицы))
    return "\n".join(кусок for кусок in куски if кусок)


def _таблицы(
    body: str, *, разбирать_таблицы: bool = True
) -> tuple[str, list[SyntaxTable], list[str]]:
    """Вынуть таблицы из тела страницы до сбора абзацев.

    Возвращает тело, таблицы данных и тексты диаграмм. На месте диаграммы в
    теле остаётся метка: вернуть её текст прямо в разметку нельзя — абзацы
    потом проходят через `_text()` ещё раз, и он срежет и угловые скобки
    (примет за теги), и отступы (обрезает каждую строку). Метку он не тронет.
    """
    if not разбирать_таблицы:
        # Разметка этой страницы уже признана испорченной. Оставляем тело как
        # есть: текст в описании ценнее вырезанной таблицы, а вырезать по
        # сломанным границам — потерять прозу вместе с ней.
        return body, [], []

    таблицы: list[SyntaxTable] = []
    диаграммы: list[str] = []
    куски, предыдущий = [], 0
    for начало, конец in _границы_таблиц(body):
        куски.append(body[предыдущий:начало])
        предыдущий = конец
        остаток = _разобрать_блок(body[начало:конец], таблицы)
        if остаток:
            куски.append(f"<P>{_МЕТКА.format(номер=len(диаграммы))}</P>")
            диаграммы.append(остаток)
    куски.append(body[предыдущий:])
    return "".join(куски), таблицы, диаграммы


def _вернуть_диаграммы(описание: str, диаграммы: list[str]) -> str:
    """Подставить тексты диаграмм вместо меток."""
    for номер, текст in enumerate(диаграммы):
        описание = описание.replace(_МЕТКА.format(номер=номер), текст)
    return описание


def parse_page(
    name: str, raw: bytes, *, разбирать_таблицы: bool = True
) -> SyntaxItem | None:
    """Страница -> элемент. `None`, если это не статья (служебные файлы)."""
    if name in СЛУЖЕБНЫЕ or name.endswith(".st"):
        return None

    body = _decode(raw)
    body, таблицы, диаграммы = _таблицы(
        body, разбирать_таблицы=разбирать_таблицы
    )
    h1 = _RE_H1.search(body)
    if h1 is None:
        return None
    заголовок = _text(h1.group(1))

    английское = Path(name).stem
    item = SyntaxItem(
        id=f"query/{name}",
        kind=_вид_по_заголовку(заголовок, body),
        name_ru=_без_английского(_имя(заголовок), английское),
        name_en=английское,
        # Версия появления берётся из курируемой таблицы: в самой справке её
        # нет ни на одной из 129 страниц (`query_versions.py`).
        since=query_versions.since_for(английское),
        tables=таблицы,
    )

    if item.kind == KIND_QUERY_FUNCTION:
        # Абзацы параметров внутри BLOCKQUOTE уже разбираются отдельно в
        # `_параметры()`. Убрать их отсюда нужно именно здесь, а не для всех
        # видов: у прочих видов BLOCKQUOTE — обычный содержательный текст
        # (например, описание полей выборки на 32 899 символов суммарно на
        # 58 страницах, замер 2026-08-17), и резать его значило бы терять
        # текст статьи, а не задвоенные параметры.
        blockquote = _RE_BLOCKQUOTE.search(body)
        тело_без_параметров = _RE_BLOCKQUOTE.sub("", body)
        абзацы = [_text(кусок) for кусок in _RE_P.findall(тело_без_параметров)]

        сигнатура, из_абзаца = _сигнатура_функции(body, абзацы)
        item.variants = [
            SyntaxVariant(
                signature=сигнатура,
                params=_параметры(blockquote.group(1) if blockquote else ""),
            )
        ]
        # Первый абзац занял variants[0].signature только когда сигнатура
        # взята из него — тогда в описании он второй раз не нужен. Когда
        # сигнатура из <PRE> или её нет вовсе, первый абзац — обычная проза.
        абзацы_описания = абзацы[1:] if из_абзаца else абзацы
        item.description = _вернуть_диаграммы(
            "\n\n".join(абзацы_описания).strip(), диаграммы
        )
    else:
        абзацы = [_text(кусок) for кусок in _RE_P.findall(body)]
        item.description = _вернуть_диаграммы(
            "\n\n".join(абзацы).strip(), диаграммы
        )
    return item


def parse_pages(pages: dict[str, bytes]) -> SyntaxIndex:
    """Разобрать набор страниц. Отдельно от файла — чтобы тесты не лезли в `data/`."""
    index = SyntaxIndex(platforms=[], source="query", language="ru")
    for name, raw in pages.items():
        try:
            item = parse_page(name, raw)
        except ОбрывТаблицы as ошибка:
            # Одна испорченная страница не повод потерять справку целиком, но
            # и молчать нельзя: без таблиц карточка беднее, а разницу иначе
            # никто не заметит. Разбираем страницу без таблиц и называем её.
            index.warnings.append(
                f"{name}: {ошибка}. Страница разобрана без таблиц — "
                "в описании они останутся столбцом значений."
            )
            item = parse_page(name, raw, разбирать_таблицы=False)
        if item is not None:
            index.add(item)
    return index


def parse_hbk(hbk_path: str | Path) -> SyntaxIndex:
    with open_file_storage(hbk_path) as storage:
        pages = {name: storage.read(name) for name in storage.namelist()}
    return parse_pages(pages)
