"""`get_syntax` по голому имени: метод глобального контекста — по умолчанию.

`Сообщить` есть и в глобальном контексте, и у объекта `СообщениеПользователю`.
Агент, написавший `Сообщить(...)`, имеет в виду глобальный метод, а список из
двух одноимённых элементов заставлял делать лишний вызов. Теперь для имени без
точки при наличии глобального варианта показывается его карточка, а остальные
адреса — строкой «Есть также».
"""

from __future__ import annotations

from mcp1c.syntax_model import SyntaxItem
from mcp1c.tools import get_syntax

from conftest import build_syntax_registry

ПЛАТФОРМА = "8.3.27.2130"


def _метод(родитель: str, имя: str, описание: str) -> SyntaxItem:
    return SyntaxItem(
        id=f"objects/{родитель}/methods/{имя}",
        kind="method",
        name_ru=имя,
        parent_ru=родитель,
        description=описание,
    )


def _реестр(tmp_path):
    return build_syntax_registry(
        tmp_path,
        [
            _метод("Глобальный контекст", "Сообщить", "Выводит сообщение пользователю."),
            _метод("СообщениеПользователю", "Сообщить", "Выводит это сообщение."),
        ],
        ПЛАТФОРМА,
    )


def test_сообщить_показывает_глобальный_контекст(tmp_path):
    реестр = _реестр(tmp_path)

    ответ = get_syntax(реестр, "Сообщить")

    assert ответ.startswith("# Метод: Глобальный контекст.Сообщить")
    assert "Выводит сообщение пользователю." in ответ
    assert "Выводит это сообщение." not in ответ
    assert "Одноимённых элементов" not in ответ
    assert "Есть также: `СообщениеПользователю.Сообщить` — Метод" in ответ
    assert ответ.index("Есть также") > ответ.index("Выводит сообщение пользователю.")


def test_имя_с_точкой_без_изменений(tmp_path):
    реестр = _реестр(tmp_path)

    ответ = get_syntax(реестр, "СообщениеПользователю.Сообщить")

    assert ответ.startswith("# Метод: СообщениеПользователю.Сообщить")
    assert "Выводит это сообщение." in ответ
    assert "Есть также" not in ответ


def test_глобальный_адрес_с_точкой_без_пометки_есть_также(tmp_path):
    реестр = _реестр(tmp_path)

    ответ = get_syntax(реестр, "Глобальный контекст.Сообщить")

    assert ответ.startswith("# Метод: Глобальный контекст.Сообщить")
    assert "Есть также" not in ответ


def test_без_глобального_варианта_список(tmp_path):
    реестр = build_syntax_registry(
        tmp_path,
        [
            _метод("ПервыйОбъект", "Показать", "Показывает первое."),
            _метод("ВторойОбъект", "Показать", "Показывает второе."),
        ],
        ПЛАТФОРМА,
    )

    ответ = get_syntax(реестр, "Показать")

    assert "Одноимённых элементов: 2" in ответ
    assert "`ПервыйОбъект.Показать`" in ответ
    assert "`ВторойОбъект.Показать`" in ответ
    assert "Есть также" not in ответ


def test_есть_также_ограничен_пятнадцатью(tmp_path):
    реестр = build_syntax_registry(
        tmp_path,
        [
            _метод("Глобальный контекст", "Найти", "Глобальный поиск."),
            *(
                _метод(f"Объект{номер:02d}", "Найти", f"Ищет в объекте {номер}.")
                for номер in range(1, 21)
            ),
        ],
        ПЛАТФОРМА,
    )

    ответ = get_syntax(реестр, "Найти")

    адреса = [строка for строка in ответ.splitlines() if строка.startswith("Есть также: `")]
    assert ответ.startswith("# Метод: Глобальный контекст.Найти")
    assert len(адреса) == 15
    assert "Есть также: ещё 5" in ответ
