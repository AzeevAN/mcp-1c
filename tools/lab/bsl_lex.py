"""Прототип лексера BSL: отличить код от строк и комментариев.

Разведочный. Нужен, чтобы замерить, сколько стоит собственный разбор и на
сколько он расходится с регуляркой — прежде чем решать «своё или готовое».

Что обязан пережить (проверено на «Рознице», 7 878 модулей):

* многострочные тексты запросов: 239 574 строки-продолжения через `|`,
  из них 5 563 содержат `//` внутри литерала — регулярка режет там хвост
  запроса, считая его комментарием;
* удвоенную кавычку `""` внутри строки — 38 341 строка;
* слова языка внутри литералов: 38 раз `Процедура`/`Функция`, дважды
  `КонецПроцедуры` — то есть объявление и его конец нельзя искать текстом;
* препроцессор (5 120 строк `#Если`), аннотации и директивы (72 718 строк с
  `&`).

Разбор построчный с состоянием «внутри строки»: посимвольный проход по 260 МБ
на чистом Python обошёлся бы дороже, а состояние строки в BSL не выходит за
границу строки файла иначе как через `|`.
"""
import re
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path

# Ключевые слова границ. Русские и английские: в типовых встречаются оба.
НАЧАЛО = {"процедура": "процедура", "функция": "функция",
          "procedure": "процедура", "function": "функция"}
# Асинхронное объявление (8.3.18+): `Асинх Процедура Имя() Экспорт`. Слово
# стоит ПЕРЕД видом, поэтому проверка «первое слово строки» его пропускает —
# на «Рознице» так терялось 17 процедур.
АСИНХ = {"асинх", "async"}
КОНЕЦ = {"конецпроцедуры", "конецфункции", "endprocedure", "endfunction"}
ЭКСПОРТ = {"экспорт", "export"}

ИМЯ = r"[А-Яа-яЁёA-Za-z_][А-Яа-яЁёA-Za-z_0-9]*"
СЛОВО = re.compile(ИМЯ)
ОБЪЯВЛЕНИЕ = re.compile(rf"^\s*({ИМЯ})\s+({ИМЯ})\s*\(", re.IGNORECASE)
АННОТАЦИЯ = re.compile(rf"^\s*&\s*({ИМЯ})\s*(?:\(\s*\"([^\"]*)\"\s*\))?", re.IGNORECASE)
ВЫЗОВ = re.compile(rf"(?:({ИМЯ})\s*\.\s*)?({ИМЯ})\s*\(")

# После этих слов скобка не означает вызова процедуры.
НЕ_ВЫЗОВ = {
    "если", "иначеесли", "пока", "для", "возврат", "новый", "и", "или", "не",
    "тогда", "цикл", "по", "из", "выполнить", "вычислить",
    "if", "elsif", "while", "for", "return", "new", "and", "or", "not",
    "then", "do", "to", "in", "execute", "eval",
    "процедура", "функция", "procedure", "function",
}


@dataclass(slots=True)
class Процедура:
    вид: str
    имя: str
    параметры: str
    экспорт: bool
    строка: int
    конец: int = 0
    директива: str = ""          # &НаКлиенте, &НаСервереБезКонтекста
    перекрытие: tuple = ()       # (&ИзменениеИКонтроль, "ИмяЦели")
    вызовы: list = field(default_factory=list)


def код_строки(строка: str, в_строке: bool) -> tuple[str, bool]:
    """Вернуть код строки без литералов и комментария и новое состояние.

    Содержимое литералов заменяется пробелами, а не выбрасывается: позиции
    остальных символов обязаны сохраниться, иначе номера колонок поедут.
    """
    результат = []
    i, n = 0, len(строка)

    if в_строке:
        # Внутри незакрытого литерала строка файла, начинающаяся с `//`, —
        # комментарий, а не содержимое: 1С разрешает комментировать куски
        # текста запроса прямо посреди многострочной строки. Найдено на живом
        # коде: разработчик закомментировал строку `//| … ";` вместе с
        # закрывающей кавычкой, и лексер, считающий эту кавычку закрывающей,
        # теряет состояние до конца файла — в «Мире музыки» одна такая строка
        # съела 184 объявления.
        if строка.lstrip().startswith("//"):
            return " " * len(строка), True
        # Продолжение литерала: до закрывающей кавычки всё — содержимое,
        # включая `//` в середине строки и слова языка.
        i = 0
        while i < n:
            if строка[i] == '"':
                if i + 1 < n and строка[i + 1] == '"':
                    i += 2               # удвоенная кавычка — часть текста
                    continue
                i += 1
                в_строке = False
                break
            i += 1
        результат.append(" " * i)

    while i < n:
        символ = строка[i]
        if символ == '"':
            начало = i
            i += 1
            закрыт = False
            while i < n:
                if строка[i] == '"':
                    if i + 1 < n and строка[i + 1] == '"':
                        i += 2
                        continue
                    i += 1
                    закрыт = True
                    break
                i += 1
            результат.append(" " * (i - начало))
            if not закрыт:
                # Литерал не закрыт — продолжится на следующей строке через `|`.
                в_строке = True
                return "".join(результат), в_строке
            continue
        if символ == "/" and i + 1 < n and строка[i + 1] == "/":
            результат.append(" " * (n - i))
            break
        результат.append(символ)
        i += 1

    return "".join(результат), в_строке


def разобрать(текст: str) -> list[Процедура]:
    """Процедуры модуля с границами, директивами и вызовами."""
    процедуры: list[Процедура] = []
    текущая: Процедура | None = None
    в_строке = False
    ожидает_директива = ""
    ожидает_перекрытие: tuple = ()

    for номер, исходная in enumerate(текст.splitlines(), 1):
        строка, в_строке_после = код_строки(исходная, в_строке)
        было_в_строке, в_строке = в_строке, в_строке_после

        голая = строка.strip()
        if not голая:
            continue

        if голая.startswith("&"):
            м = АННОТАЦИЯ.match(строка)
            if м:
                вид = м.group(1).lower()
                if вид in ("вместо", "после", "перед", "изменениеиконтроль"):
                    ожидает_перекрытие = (м.group(1), м.group(2) or "")
                else:
                    ожидает_директива = м.group(1)
            continue

        if голая.startswith("#"):
            continue                      # препроцессор и области

        первое = СЛОВО.match(голая)
        ключ = первое.group(0).lower() if первое else ""
        асинхронная = ключ in АСИНХ
        if асинхронная:
            голая = голая[первое.end():].lstrip()
            строка = строка.replace(первое.group(0), " " * len(первое.group(0)), 1)
            первое = СЛОВО.match(голая)
            ключ = первое.group(0).lower() if первое else ""

        if ключ in НАЧАЛО and текущая is None:
            м = ОБЪЯВЛЕНИЕ.match(строка)
            if м:
                # Параметры могут переноситься: добираем до закрывающей скобки.
                хвост = строка[м.end() - 1:]
                параметры, экспорт = _параметры(хвост)
                текущая = Процедура(
                    вид=НАЧАЛО[ключ], имя=м.group(2), параметры=параметры,
                    экспорт=экспорт, строка=номер,
                    директива=ожидает_директива, перекрытие=ожидает_перекрытие)
                ожидает_директива, ожидает_перекрытие = "", ()
                continue

        if ключ in КОНЕЦ and текущая is not None:
            текущая.конец = номер
            процедуры.append(текущая)
            текущая = None
            continue

        if текущая is not None and "(" in строка:
            for м in ВЫЗОВ.finditer(строка):
                имя = м.group(2)
                if имя.lower() in НЕ_ВЫЗОВ:
                    continue
                текущая.вызовы.append((м.group(1) or "", имя, номер))

    if текущая is not None:            # модуль оборвался без КонецПроцедуры
        текущая.конец = -1
        процедуры.append(текущая)
    return процедуры


def _параметры(хвост: str) -> tuple[str, bool]:
    """Текст параметров до закрывающей скобки и признак `Экспорт` за ней.

    Хвост уже очищен от литералов, поэтому скобки считаются просто.
    """
    глубина = 0
    for i, символ in enumerate(хвост):
        if символ == "(":
            глубина += 1
        elif символ == ")":
            глубина -= 1
            if глубина == 0:
                после = хвост[i + 1:].strip().lower()
                слово = СЛОВО.match(после)
                return хвост[1:i].strip(), bool(слово and слово.group(0) in ЭКСПОРТ)
    return хвост[1:].strip(), False


def разобрать_файл(путь: Path) -> list[Процедура]:
    return разобрать(путь.read_text(encoding="utf-8-sig", errors="replace"))


if __name__ == "__main__":
    КОРЕНЬ = Path(sys.argv[1])
    пути = sorted(КОРЕНЬ.rglob("*.bsl")) or sorted(КОРЕНЬ.rglob("*.txt"))
    начало = time.monotonic()
    всего = экспортных = вызовов = оборванных = 0
    многострочных = перекрытий = 0
    for путь in пути:
        текст = путь.read_text(encoding="utf-8-sig", errors="replace")
        for п in разобрать(текст):
            всего += 1
            экспортных += bool(п.экспорт)
            вызовов += len(п.вызовы)
            оборванных += п.конец == -1
            многострочных += "\n" in п.параметры
            перекрытий += bool(п.перекрытие)
    длительность = time.monotonic() - начало
    print(f"файлов                 : {len(пути):,}".replace(",", " "))
    print(f"процедур и функций     : {всего:,}".replace(",", " "))
    print(f"  экспортных           : {экспортных:,}".replace(",", " "))
    print(f"  с перекрытием        : {перекрытий:,}".replace(",", " "))
    print(f"  без КонецПроцедуры   : {оборванных:,}".replace(",", " "))
    print(f"вызовов внутри тел     : {вызовов:,}".replace(",", " "))
    print(f"время разбора          : {длительность:.1f} с")
