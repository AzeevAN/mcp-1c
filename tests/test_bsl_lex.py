"""Лексер BSL — границы процедур, многострочная сигнатура, `Экспорт`.

Все случаи синтетические, без обращения к `data/` (`AGENTS.md`, раздел
«Тесты»). Числа в докстроках — из замера на «Рознице», см.
`docs/modules-provider-design.md`, раздел 3.
"""
from mcp1c.bsl_lex import разобрать, нормализовать


def test_простое_объявление_с_границами():
    процедуры = разобрать("Процедура Пример()\n\tА = 1;\nКонецПроцедуры\n")
    assert len(процедуры) == 1
    assert процедуры[0].имя == "Пример"
    assert процедуры[0].вид == "процедура"
    assert процедуры[0].строка == 1
    assert процедуры[0].конец == 3
    assert процедуры[0].частичный is False


def test_экспорт_не_теряется_на_многострочной_сигнатуре():
    """Разбор по одной строке терял Экспорт у 2 074 процедур из 49 182."""
    текст = (
        "Функция Длинная(Знач Первый,\n"
        "\tВторой = Неопределено,\n"
        "\tТретий) Экспорт\n"
        "\tВозврат 1;\n"
        "КонецФункции\n"
    )
    процедура = разобрать(текст)[0]
    assert процедура.экспорт is True
    assert "Третий" in процедура.параметры
    assert процедура.вид == "функция"


def test_асинх_объявление():
    """Асинх стоит перед видом; проверка «первое слово» теряла 207 процедур."""
    процедуры = разобрать("Асинх Процедура Пример() Экспорт\nКонецПроцедуры\n")
    assert [п.имя for п in процедуры] == ["Пример"]
    assert процедуры[0].экспорт is True


def test_объявление_и_конец_в_одной_строке():
    процедуры = разобрать(
        "Процедура Пустая() КонецПроцедуры\n"
        "Процедура Вторая()\nКонецПроцедуры\n"
    )
    assert [п.имя for п in процедуры] == ["Пустая", "Вторая"]


def test_модуль_без_конца_помечается_частичным():
    процедуры = разобрать("Процедура Обрыв()\n\tА = 1;\n")
    assert процедуры[0].частичный is True
    assert процедуры[0].конец == 0


def test_одиночный_cr_не_считается_переводом_строки():
    """В корпусе 50 таких символов; splitlines() сдвигал нумерацию."""
    текст = "// шапка\rпродолжение\nПроцедура Пример()\nКонецПроцедуры\n"
    assert разобрать(текст)[0].строка == 2


def test_экспорт_и_конец_на_одной_строке_после_переноса():
    """Экспорт и КонецПроцедуры на последней строке переноса — оба должны сработать."""
    текст = (
        "Функция П(Знач А,\n"
        "\tБ) Экспорт КонецФункции\n"
    )
    процедура = разобрать(текст)[0]
    assert процедура.экспорт is True
    assert процедура.конец == 2
    assert процедура.частичный is False


def test_вложенные_скобки_в_значении_по_умолчанию_не_рвут_баланс():
    текст = "Процедура П(Рег = Новый(\"Массив\"))\nКонецПроцедуры\n"
    процедура = разобрать(текст)[0]
    assert процедура.конец == 2
    assert "Новый" in процедура.параметры


def test_поля_второй_и_третьей_задачи_пустые():
    """`перекрытие`, `шапка`, `вызовы`, `директива` — заполнят задачи 2 и 3."""
    процедура = разобрать("Процедура П() Экспорт\nКонецПроцедуры\n")[0]
    assert процедура.директива == ""
    assert процедура.перекрытие == ()
    assert процедура.шапка == ""
    assert процедура.вызовы == []


def test_две_процедуры_на_одной_физической_строке_не_теряются():
    """Ревью 2026-08-20: `номер = конец_строки + 1` перепрыгивал остаток строки.

    Одна физическая строка с двумя объявлениями — обычный побочный эффект
    того, что `нормализовать` схлопывает одиночный `CR` в пробел, а не в
    перевод строки, и может слить две исходные строки в одну.
    """
    процедуры = разобрать(
        "Процедура П1() КонецПроцедуры Процедура П2() КонецПроцедуры\n"
    )
    assert [п.имя for п in процедуры] == ["П1", "П2"]
    assert [п.конец for п in процедуры] == [1, 1]
    assert all(п.частичный is False for п in процедуры)


def test_конецпроцедуры_в_середине_строки_тела_не_теряет_следующую_процедуру():
    """Ре-ревью 2026-08-20: тот же дефект, что и в объявлении, но в ветке тела.

    `А = 1; КонецПроцедуры` в одной строке — валидный BSL, не мусор. Ветка
    тела проверяла только первое слово от курсора и потом безусловно уходила
    на следующую строку — `КонецПроцедуры` посреди строки терялся, П1
    закрывался чужим `КонецПроцедуры` только на строке 4, а П2 пропадал
    целиком, потому что П1 всё ещё считался открытым, когда до него доходил
    разбор.
    """
    процедуры = разобрать(
        "Процедура П1()\n\tА = 1; КонецПроцедуры\nПроцедура П2()\nКонецПроцедуры\n"
    )
    assert [п.имя for п in процедуры] == ["П1", "П2"]
    assert [п.конец for п in процедуры] == [2, 4]
    assert all(п.частичный is False for п in процедуры)
