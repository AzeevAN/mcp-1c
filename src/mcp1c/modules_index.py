def _ключ_проблемы_формы(problem: ПроблемаФормы) -> tuple:
    return (
        problem.адрес.casefold(),
        problem.адрес,
        problem.категория,
        problem.причина,
        -1 if problem.маркер is None else problem.маркер,
    )


def _публичные_проблемы_форм(
    problems: tuple[ПроблемаФормы, ...] | list[ПроблемаФормы],
) -> tuple[ПроблемаФормы, ...]:
    """Убрать общий ``form_structure_missing`` при наличии точной причины."""
    точные = {
        problem.адрес.casefold()
        for problem in problems
        if problem.категория != "form_structure_missing"
    }
    unique = {
        (problem.категория, problem.адрес, problem.причина, problem.маркер): problem
        for problem in problems
        if not (
            problem.категория == "form_structure_missing"
            and problem.адрес.casefold() in точные
        )
    }
    return tuple(sorted(unique.values(), key=_ключ_проблемы_формы))


class Формы:
    """Индекс форм из XML-дескрипторов, ``Form.xml`` и записи ``form``.

    Без этого слоя «кто вызывает» пуст для четверти корпуса: 33 743
    процедуры из 137 115 (24,6%) не вызываются по имени нигде, и 25 606 из
    них — в модулях форм. Платформа вызывает их не по имени из кода, а по
    привязке в `Form.xml` (`<Event name="OnOpen">ПриОткрытии</Event>`), и
    без этого индекса такая процедура выглядит мёртвым кодом, хотя вызывается
    каждый раз при открытии формы.

    **Адрес формы выводится из пути `Form.xml`, не из пути `Module.bsl`.**
    `Form.xml` лежит на файл выше модуля той же формы: `.../Ext/Form.xml`
    рядом с `.../Ext/Form/Module.bsl`. Вместо того чтобы заново разбирать
    пять форм пути (design doc, `module_address`), путь `Form.xml`
    достраивается до пути модуля (`Ext/Form.xml` -> `Ext/Form/Module.bsl`)
    и отдаётся уже проверенному `адрес_модуля` — второй разбор того же
    пути прямо в этом классе был бы дублированием, расходящимся с
    оригиналом при первой же находке нового вида пути.

    **`адрес_модуля` не оборачивается в `try`** — тот же приём, что у
    `Оглавление.построить`: незнакомый каталог выгрузки — честный отказ, а
    не форма, молча пропущенная из индекса. Это другая забота, чем
    «битый `Form.xml`» ниже: там XML на диске синтаксически повреждён и
    прочитать нечего в принципе, здесь — путь не такой, каким его знает
    таблица соответствия, и подстановка была бы враньём.

    **Битый `Form.xml` форму не роняет.** `ET.fromstring` кидает
    `ParseError` на повреждённом XML — индекс расходный (как кэш), и одна
    испорченная форма не должна ронять сборку по всей выгрузке. Форма всё
    равно получает запись в индексе — с пустыми реквизитами, элементами и
    событиями и битом `битая` — вместо того чтобы тихо исчезнуть из
    индекса, что для потребителя неотличимо от «формы без единого
    реквизита».

    **Хранение — общий пул интернированных строк плюс параллельные
    `array('i')` со смещениями (CSR), а не список `Форма` на форму.** Тот
    же приём, что и в `Оглавление`/`Вызовы`: реквизит `Объект`,
    обработчик `ПриОткрытии` и подобные имена повторяются в тысячах форм,
    и общий пул хранит такую строку один раз, а не по копии на форму.
    Смещения по трём категориям (реквизиты, элементы, события) держат
    только начало диапазона каждой формы в общем плоском массиве — та же
    идея, что «имя цели -> array('i') троек» у `Вызовы`, только сгруппировано
    по форме, а не по имени. Для события рядом лежит индекс владельца:
    ``-1`` означает саму форму, иначе это имя ближайшего элемента.
    """

    __slots__ = (
        "модули", "_по_модулю", "_пул",
        "_реквизиты_начало", "_реквизиты",
        "_элементы_начало", "_элементы",
        "_события_начало", "_события_проц", "_события_имя", "_события_элемент",
        "_флаги", "_маркеры", "_состояния_xml", "_идентификаторы", "_имена",
        "_синонимы", "_типы", "битых", "полных", "частичных",
        "непрочитанных", "неизвестных_маркеров", "известных_неполных",
        "превышений_бюджета", "проблемы", "problem_counts", "object_problems",
    )

    БИТАЯ = 1
    НЕТ_СТРУКТУРЫ = 2
    ЧАСТИЧНАЯ = 4
    XML_ОТСУТСТВУЕТ = 0
    XML_ГОТОВ = 1
    XML_БИТЫЙ = 2

    def __init__(
        self,
        модули: list[str],
        _по_модулю: dict[str, int],
        _пул: list[str],
        _реквизиты_начало: array,
        _реквизиты: array,
        _элементы_начало: array,
        _элементы: array,
        _события_начало: array,
        _события_проц: array,
        _события_имя: array,
        _события_элемент: array,
        _флаги: array,
        _маркеры: array,
        _состояния_xml: array,
        _идентификаторы: array,
        _имена: array,
        _синонимы: array,
        _типы: array,
        битых: int,
        полных: int = 0,
        частичных: int = 0,
        непрочитанных: int = 0,
        неизвестных_маркеров: int = 0,
        известных_неполных: int = 0,
        превышений_бюджета: int = 0,
        проблемы: tuple[ПроблемаФормы, ...] = (),
        problem_counts: tuple[tuple[str, int], ...] = (),
        object_problems: dict[str, tuple[ПроблемаФормы, ...]] | None = None,
    ) -> None:
        # Приватный конструктор, как у Оглавление и Вызовы: собирает
        # готовые данные, ничего не вычисляет. Публичный вход —
        # `построить` (с диска) и `прочитать` (из ранее записанного файла).
        self.модули = модули
        self._по_модулю = _по_модулю
        self._пул = _пул
        self._реквизиты_начало = _реквизиты_начало
        self._реквизиты = _реквизиты
        self._элементы_начало = _элементы_начало
        self._элементы = _элементы
        self._события_начало = _события_начало
        self._события_проц = _события_проц
        self._события_имя = _события_имя
        self._события_элемент = _события_элемент
        self._флаги = _флаги
        self._маркеры = _маркеры
        self._состояния_xml = _состояния_xml
        self._идентификаторы = _идентификаторы
        self._имена = _имена
        self._синонимы = _синонимы
        self._типы = _типы
        self.битых = битых
        self.полных = полных
        self.частичных = частичных
        self.непрочитанных = непрочитанных
        self.неизвестных_маркеров = неизвестных_маркеров
        self.известных_неполных = известных_неполных
        self.превышений_бюджета = превышений_бюджета
