"""Псевдоним не зависит от формы слова.

Встроенные псевдонимы записаны во множественном числе — «контрагенты»,
«физические лица», «товары», — потому что так называются справочники. Человек
спрашивает в единственном: «контрагент», «склад», «физическое лицо».

Псевдоним сопоставлялся по точной фразе, поэтому в единственном числе не
срабатывал, и выдачу забирал `ОпределяемыйТип`: он в 1С именуется как раз в
единственном числе и получал точное совпадение всей строки — множитель ×12,
против которого не помогает ни вес вида, ни вес основы.

Теперь фраза псевдонима и запрос сравниваются по основам. Перечислять формы
в `synonyms.py` не нужно: одна запись работает для всех.
"""

from __future__ import annotations

from mcp1c.search import Doc, SearchIndex


def _index(**kwargs) -> SearchIndex:
    docs = [
        Doc(
            id="ОпределяемыйТип.Контрагент",
            kind="ОпределяемыйТип",
            payload="контрагент",
            exact_keys=["ОпределяемыйТип.Контрагент"],
            boost=0.45,
            fields={"name": "Контрагент", "synonym": "Контрагент"},
        ),
        Doc(
            id="Справочник.Контрагенты",
            kind="Справочник",
            payload="контрагенты",
            exact_keys=["Справочник.Контрагенты"],
            boost=1.0,
            fields={"name": "Контрагенты", "synonym": "Контрагенты"},
        ),
    ]
    return SearchIndex(docs, **kwargs)


def test_псевдоним_срабатывает_в_единственном_числе():
    index = _index(aliases={"контрагенты": ["Справочник.Контрагенты"]})

    hits = index.search("контрагент")

    assert hits[0].doc.id == "Справочник.Контрагенты"
    assert hits[0].reason == "псевдоним из словаря"


def test_псевдоним_срабатывает_и_в_записанной_форме():
    """Прежнее поведение не должно пострадать."""
    index = _index(aliases={"контрагенты": ["Справочник.Контрагенты"]})

    hits = index.search("контрагенты")

    assert hits[0].doc.id == "Справочник.Контрагенты"
    assert hits[0].reason == "псевдоним из словаря"


def test_форма_псевдонима_работает_в_обе_стороны():
    """Записан в единственном — находится и во множественном."""
    index = _index(aliases={"контрагент": ["Справочник.Контрагенты"]})

    assert index.search("контрагенты")[0].doc.id == "Справочник.Контрагенты"


def test_многословный_псевдоним_сопоставляется_по_основам():
    docs = [
        Doc(
            id="Справочник.ФизическиеЛица",
            kind="Справочник",
            payload="физлица",
            exact_keys=["Справочник.ФизическиеЛица"],
            boost=1.0,
            fields={"name": "ФизическиеЛица", "synonym": "Физические лица"},
        )
    ]
    index = SearchIndex(
        docs, aliases={"физические лица": ["Справочник.ФизическиеЛица"]}
    )

    hits = index.search("физическое лицо")

    assert hits[0].doc.id == "Справочник.ФизическиеЛица"
    assert hits[0].reason == "псевдоним из словаря"


def test_чужая_фраза_не_считается_псевдонимом():
    """Совпадение по основам — не повод хватать что попало."""
    index = _index(aliases={"контрагенты": ["Справочник.Контрагенты"]})

    hits = index.search("склад")

    assert all(h.reason != "псевдоним из словаря" for h in hits)


def test_замена_словаря_подхватывается():
    """`reload_dictionary` подменяет таблицу на живом индексе."""
    index = _index(aliases={"контрагенты": ["Справочник.Контрагенты"]})
    assert index.search("контрагент")[0].doc.id == "Справочник.Контрагенты"

    index.aliases = {}

    hits = index.search("контрагент")
    assert all(h.reason != "псевдоним из словаря" for h in hits)
