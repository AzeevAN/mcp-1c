"""Редакция конфигурации: граница, через которую полное обновление не идёт.

Типовые 1С меняют поколение сменой первых двух чисел версии: «Розница»
2.3 и 3.0 — одно внутреннее имя, но разные конфигурации на разных
платформах. Сервер различает конфигурации только по имени, поэтому полное
обновление 2.3 → 3.0 молча подменило бы рабочую конфигурацию другим
поколением. Переход между редакциями — это удаление старой и загрузка новой:
вместе со старой уходят её расширения и объявленная платформа, которые к
новому поколению не подходят.
"""

from __future__ import annotations

import re

_EDITION = re.compile(r"(\d{1,9})\.(\d{1,9})(?:\.|$)", re.ASCII)


def edition(version: str) -> tuple[int, int] | None:
    """Первые два числа версии; ``None`` — версия пустая или не номерная.

    Не номерная версия встречается у самописных конфигураций
    (``20080620(0935)``). Редакции в ней нет, и две такие версии между собой
    не сравниваются: иначе обновить такую конфигурацию было бы нельзя никогда.
    """
    match = _EDITION.match(version.strip())
    if match is None:
        return None
    return int(match.group(1)), int(match.group(2))


def _label(version: str) -> str:
    value = edition(version)
    if value is not None:
        return f"редакции {value[0]}.{value[1]}"
    if version.strip():
        return f"с версией без номера редакции ({version.strip()})"
    return "без версии"


def edition_conflict(configuration: str, current: str, incoming: str) -> str:
    """Причина запрета полного обновления; пустая строка — обновление допустимо."""
    # Пустая версия не задаёт редакцию: её первое назначение допустимо.
    # Непустую нечисловую версию по-прежнему нельзя заменить номерной.
    if not current.strip() or edition(current) == edition(incoming):
        return ""
    return (
        f"Загружена конфигурация «{configuration}» {_label(current)}, "
        f"новая выгрузка — {_label(incoming)}. Это другое поколение "
        "конфигурации, полное обновление между редакциями не выполняется. "
        "Чтобы перейти, удалите загруженную конфигурацию вместе с её "
        "расширениями и загрузите выгрузку как новую."
    )
