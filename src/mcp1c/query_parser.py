"""Разбор справки по языку запросов 1С (`shquery_ru.hbk`).

Отдельный модуль, а не ветка в `syntax_parser.py`: там разметка с классами
`V8SH_*`, здесь их нет вовсе — обычные `H1`, `P`, `BLOCKQUOTE`, `STRONG`.

Версий появления в этом файле нет: в `__categories__` все 624 отметки равны
`0.0.0`. Поэтому `since` и `until` остаются пустыми, и фильтр версии такие
элементы пропускает сам.
"""

