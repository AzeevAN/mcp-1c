def test_словоформы_сводятся_к_одной_основе():
    """Склонение коротких слов: «чеков» обязано находить «Чека».

    Обрезка до шести символов сводила только длинные слова
    («контрагент/контрагенты» → «контра»), а «чек/чека/чеков», «вид/виды»,
    «оплат/оплаты» оставались разными токенами — запрос «виды оплат чеков» не
    находил `ВидыОплатЧекаККМ` вовсе, слово «чеков» не совпадало ни с чем.
    """
    from mcp1c.search import stem

    for формы in (
        ("чек", "чека", "чеков", "чеки"),
        ("вид", "виды", "видов"),
        ("оплата", "оплат", "оплаты"),
        ("склад", "склады", "складов"),
        ("товар", "товары", "товаров"),
        ("контрагент", "контрагенты"),
    ):
        assert len({stem(w) for w in формы}) == 1, формы


