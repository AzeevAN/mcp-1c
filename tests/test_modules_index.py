def test_событие_вложенного_элемента_тоже_привязка(tmp_path):
    """На живой выгрузке верхнеуровневый `<Events>` формы даёт 8 183
    привязки, а с учётом вложенных — 24 202: у каждого элемента (кнопка,
    таблица) свой блок `Events`, и обработчики там объявлены в том же
    модуле формы. Разбор, ограниченный верхним уровнем, потерял бы три
    четверти привязок — этот тест ловит именно такое сужение."""
    ext = tmp_path / "Catalogs" / "Пример" / "Forms" / "ФормаЭлемента" / "Ext"
    (ext / "Form").mkdir(parents=True)
    (ext / "Form" / "Module.bsl").write_text(
        "&НаКлиенте\nПроцедура ПриОткрытии(Отказ)\nКонецПроцедуры\n"
        "\n"
        "&НаКлиенте\nПроцедура КнопкаНажатие(Элемент)\nКонецПроцедуры\n",
        encoding="utf-8",
    )
    (ext / "Form.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>'
        '<Form><Events><Event name="OnOpen">ПриОткрытии</Event></Events>'
        '<ChildItems><UsualGroup name="Группа" id="1"><ChildItems>'
        '<Button name="Кнопка" id="2">'
        '<Events><Event name="OnClick">КнопкаНажатие</Event></Events>'
        "</Button></ChildItems></UsualGroup></ChildItems></Form>",
        encoding="utf-8",
    )
    ф = Формы.построить(tmp_path)
    адрес = "Справочник.Пример.Форма.ФормаЭлемента"
    assert ф.обработчик(адрес, "КнопкаНажатие") == "OnClick"


def test_техническая_обвязка_элемента_не_элемент_формы(tmp_path):
    """`ExtendedTooltip` и `ContextMenu` платформа заводит на каждый
    интерактивный элемент автоматически — это не то, что разработчик
    добавил в форму. На живой выгрузке разница огромна: с ними в дереве
    89 528 «элементов» вместо кратно меньшего числа настоящих полей и
    групп. Тест ловит именно случай, когда обвязка просочилась бы в
    список наравне с настоящим элементом."""
    ext = tmp_path / "Catalogs" / "Пример" / "Forms" / "ФормаЭлемента" / "Ext"
    (ext / "Form").mkdir(parents=True)
    (ext / "Form" / "Module.bsl").write_text("", encoding="utf-8")
    (ext / "Form.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>'
        '<Form><ChildItems><Button name="Кнопка" id="1">'
        '<ExtendedTooltip name="КнопкаПодсказка" id="2"/>'
        '</Button></ChildItems></Form>',
        encoding="utf-8",
    )
    ф = Формы.построить(tmp_path)
    элементы = ф.состав("Справочник.Пример.Форма.ФормаЭлемента").элементы
    assert элементы == ["Кнопка"]
    assert "КнопкаПодсказка" not in элементы


