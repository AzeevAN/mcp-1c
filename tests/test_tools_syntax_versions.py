def test_примечание_элемента_не_теряется_при_своей_сигнатуре(tmp_path):
    """Примечание относится к элементу, а не к разбору параметров: выкидывать
    его вместе с ними — терять предупреждение о поведении метода."""
    incoming = tmp_path / "incoming"
    старая = справка(incoming, "8.3.5.1570", {"ЗаписьXML.ОткрытьФайл": "ОткрытьФайл(<ИмяФайлаXML>)"})
    новая = справка(incoming, "8.3.27.2130", {"ЗаписьXML.ОткрытьФайл": "ОткрытьФайл(<ИмяФайлаXML>, <ДобавлятьBOM>)"})
    _проставить_примечание(новая, "Файл открывается монопольно.")
    registry = реестр(tmp_path, [старая, новая], "8.3.5.1570")

    ответ = get_syntax(registry, "ЗаписьXML.ОткрытьФайл")

    assert "монопольно" in ответ


def test_одноимённые_недоступные_перечисляются_с_причинами(tmp_path):
    """Причины у однофамильцев разные: один удалён, другой ещё не появился.
    Ответ про одного из них умалчивает про второй."""
    incoming = tmp_path / "incoming"
    старая = справка(incoming, "8.3.5.1570", {"КаноническаяЗаписьXML.Закрыть": "Закрыть()"})
    новая = справка(incoming, "8.3.27.2130", {"ФайловыйПоток.Закрыть": "Закрыть()"})
    _проставить_since(новая, "8.3.20")
    registry = реестр(tmp_path, [старая, новая], "8.3.10.1000")

    ответ = get_syntax(registry, "Закрыть")

    assert "КаноническаяЗаписьXML" in ответ
    assert "ФайловыйПоток" in ответ


def _проставить_since(путь, версия: str) -> None:
    from mcp1c.store import load_syntax

    index = load_syntax(путь)
    for item in index.items.values():
        item.since = версия
    save_syntax(index, путь)


def _проставить_примечание(путь, текст: str) -> None:
    from mcp1c.store import load_syntax

    index = load_syntax(путь)
    for item in index.items.values():
        item.note = текст
    save_syntax(index, путь)


