@dataclass(slots=True)
class Запись:
    """Одна процедура оглавления — собирается по запросу из массивов.

    `функция: bool`, а не `вид: str` — тех же двух значений ("процедура" /
    "функция") строкой хотелось избежать намеренно: строка приглашает
    сравнивать её текстом (`з.вид == "Функция"`, регистр не тот — тихая
    ошибка) или, того хуже, выводить вид из имени процедуры вместо этого
    поля. `bool` такого соблазна не оставляет и совпадает по духу с
    остальными флагами записи (`экспорт`, `перекрыта`, `частичный`).
    """

    модуль: str
    имя: str
    экспорт: bool
    строка: int
    конец: int
    перекрыта: bool
    частичный: bool
    функция: bool


class Оглавление:
    """Процедуры корпуса: параллельные массивы, имена интернированы.

    Сигнатура не хранится: она лежит на диске в строке объявления, чтение
    обходится в 0,1 мс на модуль. Хранение стоило бы +66 МБ на конфигурацию.
    """

    __slots__ = ("модули", "имена", "_модуль", "_строка", "_конец", "_флаги",
                 "_по_имени", "_по_модулю")

    ЭКСПОРТ = 1
    ПЕРЕКРЫТА = 2
    ЧАСТИЧНЫЙ = 4
    ФУНКЦИЯ = 8

    def __init__(
        self,
        модули: list[str],
        имена: list[str],
        _модуль: array,
        _строка: array,
        _конец: array,
        _флаги: array,
        _по_имени: dict[str, array],
        _по_модулю: dict[str, array],
    ) -> None:
        # Приватный конструктор: собирает готовые массивы, ничего не
        # вычисляет. Публичный вход — `построить` (с диска) и `прочитать`
        # (из ранее записанного файла).
        self.модули = модули
        self.имена = имена
        self._модуль = _модуль
        self._строка = _строка
        self._конец = _конец
        self._флаги = _флаги
        self._по_имени = _по_имени
        self._по_модулю = _по_модулю

    @staticmethod
    def _индексы(
        имена: list[str], _модуль: array, модули: list[str]
    ) -> tuple[dict[str, array], dict[str, array]]:
        """Обратные индексы «имя -> позиции» и «модуль -> позиции».

        Строится и после сборки с диска, и после подъёма из файла — на диске
        эти индексы не лежат: они целиком выводятся из `имена`/`_модуль`, а
        хранить производное вторым слоем значило бы удваивать файл ради того,
        что и так пересчитывается за доли секунды одним проходом.
        """
        по_имени: dict[str, array] = {}
        по_модулю: dict[str, array] = {}
        for i, имя in enumerate(имена):
            по_имени.setdefault(имя.lower(), array("i")).append(i)
            по_модулю.setdefault(модули[_модуль[i]], array("i")).append(i)
        return по_имени, по_модулю

    @classmethod
    def построить(cls, корень: Path) -> "Оглавление":
        """Проход по выгрузке: адрес модуля из пути, процедуры — из текста.

        Порядок файлов детерминированный (`sorted`) ради воспроизводимости
        замеров и стабильного порядка индексов между прогонами — само
        оглавление от порядка не зависит.

        `адрес_модуля` не оборачивается в `try`: незнакомый каталог или файл
        выгрузки — честный отказ (см. докстроку `module_address`), а не
        объект, молча пропущенный из оглавления.
        """
        модули: list[str] = []
        индекс_модуля: dict[str, int] = {}
        имена: list[str] = []
        _модуль = array("i")
        _строка = array("i")
        _конец = array("i")
        _флаги = array("i")

        for файл in sorted(корень.rglob("*.bsl")):
            относительный = файл.relative_to(корень).as_posix()
            адрес = адрес_модуля(относительный)
            индекс = индекс_модуля.get(адрес)
            if индекс is None:
                индекс = len(модули)
                модули.append(адрес)
                индекс_модуля[адрес] = индекс

            for процедура in разобрать(прочитать_модуль(файл)):
                # Интернируем на записи, не на чтении: одно и то же имя
                # («ПриСозданииНаСервере» — 3 003 раза на живом корпусе)
                # иначе заводило бы отдельный строковый объект на каждое
                # вхождение вместо одного общего.
                имена.append(sys.intern(процедура.имя))
                _модуль.append(индекс)
                _строка.append(процедура.строка)
                _конец.append(процедура.конец)
                флаги = 0
                if процедура.экспорт:
                    флаги |= cls.ЭКСПОРТ
                if процедура.перекрытие:
                    флаги |= cls.ПЕРЕКРЫТА
                if процедура.частичный:
                    флаги |= cls.ЧАСТИЧНЫЙ
                if процедура.вид == "функция":
                    флаги |= cls.ФУНКЦИЯ
                _флаги.append(флаги)

        по_имени, по_модулю = cls._индексы(имена, _модуль, модули)
        return cls(модули, имена, _модуль, _строка, _конец, _флаги, по_имени, по_модулю)

    def _состояние(self) -> dict:
        """Параллельные массивы в виде, годном для `marshal`, — общее тело
        для `записать` (файл напрямую) и `сохранить_индексы` (через кэш
        проекта, со штампом и сжатием).

        Обратные индексы (`по_имени`, `по_модулю`) не входят — они
        производные от `имена`/`_модуль` и пересчитываются на подъёме.
        Массивы идут байтами (`tobytes()`), не списками: `marshal` умеет
        сохранять `array` только как обычную последовательность чисел, а
        это для миллиона элементов дороже и на запись, и на чтение.
        """
        return {
            "модули": self.модули,
            "имена": self.имена,
            "модуль": self._модуль.tobytes(),
            "строка": self._строка.tobytes(),
            "конец": self._конец.tobytes(),
            "флаги": self._флаги.tobytes(),
        }

    def записать(self, путь: Path) -> None:
        """Сохраняет параллельные массивы на диск через голый `marshal`,
        без штампа и без сжатия — круг «построить -> записать -> прочитать»
        для тестов и разовой проверки на месте. Постоянное хранение кэша
        проекта — `сохранить_индексы`/`поднять_индексы`, через `index_cache`."""
        путь.write_bytes(marshal.dumps(self._состояние()))

    @classmethod
    def _из_состояния(cls, данные: dict) -> "Оглавление":
        """Собирает оглавление из словаря `_состояние` — общее тело для
        `прочитать` и `поднять_индексы`.

        Массивы поднимаются `frombytes()` напрямую в пустой `array('i')`,
        без промежуточного `list` — см. докстроку модуля про 97 МБ вместо 62.
        """
        _модуль = array("i")
        _модуль.frombytes(данные["модуль"])
        _строка = array("i")
        _строка.frombytes(данные["строка"])
        _конец = array("i")
        _конец.frombytes(данные["конец"])
        _флаги = array("i")
        _флаги.frombytes(данные["флаги"])

        модули = данные["модули"]
        имена = данные["имена"]
        по_имени, по_модулю = cls._индексы(имена, _модуль, модули)
        return cls(модули, имена, _модуль, _строка, _конец, _флаги, по_имени, по_модулю)

    @classmethod
    def прочитать(cls, путь: Path) -> "Оглавление":
        """Поднимает оглавление из файла `записать`."""
        return cls._из_состояния(marshal.loads(путь.read_bytes()))

    def _запись(self, i: int) -> Запись:
        флаги = self._флаги[i]
        return Запись(
            модуль=self.модули[self._модуль[i]],
            имя=self.имена[i],
            экспорт=bool(флаги & self.ЭКСПОРТ),
            строка=self._строка[i],
            конец=self._конец[i],
            перекрыта=bool(флаги & self.ПЕРЕКРЫТА),
            частичный=bool(флаги & self.ЧАСТИЧНЫЙ),
            функция=bool(флаги & self.ФУНКЦИЯ),
        )

    def все(self) -> list[Запись]:
        """Все процедуры корпуса — для полного прохода (сборка других индексов)."""
        return [self._запись(i) for i in range(len(self.имена))]

    def по_имени(self, имя: str) -> list[Запись]:
        """Все процедуры с этим именем во всех модулях, без учёта регистра.

        Может вернуть несколько записей — ключ оглавления «модуль + имя»,
        не одно имя (докстрока модуля).
        """
        return [self._запись(i) for i in self._по_имени.get(имя.lower(), ())]

    def модуля(self, адрес: str) -> list[Запись]:
        """Все процедуры модуля, включая неэкспортные."""
        return [self._запись(i) for i in self._по_модулю.get(адрес, ())]

    def известно(self, имя: str) -> bool:
        """Объявлена ли хоть одна процедура с этим именем где-либо в корпусе.

        Дешёвый сторож для индекса вызовов (задача 6, `Вызовы.построить`):
        на живом корпусе кандидатов в вызовы около миллиона, и строить на
        каждом `Запись`-объекты через `по_имени` только ради проверки
        «есть или нет» значило бы платить за то, что тут же выбрасывается.
        Словарь `_по_имени` для этого и существует.
        """
        return имя.lower() in self._по_имени


@dataclass(slots=True)
class Место:
    """Одно место вызова — модуль-вызыватель, строка и, если удалось
    разрешить, адрес модуля-цели."""

    модуль: str
    строка: int
    цель: str | None


class Вызовы:
    """Индекс вызовов корпуса: «кто вызывает эту процедуру», с разрешением
    цели до модуля там, где это возможно (design doc, раздел 4).

    **Ключ по одному имени врёт.** `ПриСозданииНаСервере` объявлена в
    3 003 модулях живой конфигурации — агент, спросивший «кто вызывает мою
    процедуру» и получивший ответ по имени, получит два десятка чужих
    мест и либо решит, что правка задевает пол-конфигурации, либо, что
    хуже, не увидит настоящего вызывающего среди них и сделает вывод
    «никто не вызывает, менять безопасно». Поэтому ребро несёт третье
    поле — индекс модуля-цели или −1, а не только имя.

    Разрешается только то, в чём мы уверены (`_разрешить`):
    квалифицированный вызов `Х.Метод(`, где `Х` — имя общего модуля
    корпуса, и неквалифицированный вызов, чьё имя объявлено в самом
    модуле-вызывателе. Остальное остаётся −1 и честно называется в ответе
    (это забота задачи 14) — подставлять «похоже, это оно» здесь так же
    неуместно, как и в `module_address`.

    **Фильтр «имя объявлено где-то в корпусе».** Вызов платформенного
    метода (`ЗначениеЗаполнено`, `Сообщить`) целью быть не может — ни один
    модуль корпуса такое имя не объявляет — и такое ребро не индексируется
    вовсе, а не заводится неразрешённым: без фильтра рёбер на 63% больше
    (1 009 479 против 619 030 на живой выгрузке), и все они бесполезны.

    **Хранение — `имя цели -> array('i')` плоских троек** «модуль-вызыватель,
    строка, модуль-цель или −1» на ключ, без объекта на ребро. Группировка
    по имени уже есть на этапе сборки — `места(имя)` для этого и вызывается
    — так что отдельного параллельного массива с именем на каждое ребро
    (619 030 интернированных ссылок) заводить незачем: имя один раз лежит
    ключом словаря, а не миллион раз копией указателя. Замер живой
    выгрузки: 619 030 рёбер, 52% разрешено, 51 МБ при подъёме.
    """

    __slots__ = ("модули", "_по_имени", "рёбер", "разрешённых")

    def __init__(
        self,
        модули: list[str],
        _по_имени: dict[str, array],
        рёбер: int,
        разрешённых: int,
    ) -> None:
        # Приватный конструктор, как у Оглавление: собирает готовые данные,
        # ничего не вычисляет. Публичный вход — `построить` и `прочитать`.
        self.модули = модули
        self._по_имени = _по_имени
        self.рёбер = рёбер
        self.разрешённых = разрешённых

    @staticmethod
    def _общие_модули(модули: list[str]) -> dict[str, int]:
        """Имя общего модуля (без вида) -> его индекс в списке модулей корпуса.

        Разрешаются только квалифицированные вызовы к ОБЩИМ модулям: у
        остальных видов квалификатор перед вызовом — это имя переменной
        объекта (`Объект.Общая()`), а не имя типа, и совпадение с адресом
        модуля там ничего не доказывает — ровно та подстановка, от которой
        уходит разрешение до модуля.
        """
        return {
            адрес.split(".", 1)[1].lower(): i
            for i, адрес in enumerate(модули)
            if адрес.startswith("ОбщийМодуль.")
        }

    @staticmethod
    def _разрешить(
        квалификатор: str, имя: str, модуль: int,
        общие: dict[str, int], свои: set[str],
    ) -> int:
        """Индекс модуля-цели или −1.

        Разрешаем только то, в чём уверены: остальное честно помечается в
        ответе. Ключ по одному имени врал бы — `ПриСозданииНаСервере`
        объявлена в 3 003 модулях живой конфигурации.

        `@staticmethod`, а не метод экземпляра (в отличие от чернового
        вида в брифе задачи): вызывается из `построить` до того, как
        экземпляр `Вызовы` собран — `self` тут неоткуда взять, а тело и
        так не трогает состояние объекта.
        """
        if квалификатор:
            return общие.get(квалификатор.lower(), -1)
        return модуль if имя in свои else -1

    @classmethod
    def построить(cls, корень: Path, оглавление: "Оглавление") -> "Вызовы":
        """Второй проход по выгрузке: места вызова из `Процедура.вызовы`,
        которых оглавление не хранит (оно помнит только границы объявлений).

        `оглавление` принимается готовым, а не строится заново: `известно`
        (фильтр по корпусу) и список объявленных в модуле имён (для «своих»
        неквалифицированных вызовов) — это уже посчитанный проходом задачи 5
        ответ, и второй полный обход исходников ради тех же чисел был бы
        пустой тратой времени сборки.
        """
        адрес_к_индексу = {адрес: i for i, адрес in enumerate(оглавление.модули)}
        общие = cls._общие_модули(оглавление.модули)

        _по_имени: dict[str, array] = {}
        рёбер = 0
        разрешённых = 0

        for файл in sorted(корень.rglob("*.bsl")):
            относительный = файл.relative_to(корень).as_posix()
            адрес = адрес_модуля(относительный)
            индекс_модуля = адрес_к_индексу[адрес]
            # Имена, объявленные в ЭТОМ модуле — для неквалифицированных
            # вызовов (`_разрешить`). Не только имя самой вызывающей
            # процедуры: любая процедура модуля годится целью, так что
            # набор строится по всему модулю разом, один раз на файл.
            свои = {
                оглавление.имена[i].lower()
                for i in оглавление._по_модулю.get(адрес, ())
            }

            for процедура in разобрать(прочитать_модуль(файл)):
                for квалификатор, имя, строка in процедура.вызовы:
                    # Платформенный метод корпусом не объявлен нигде — не
                    # индексируем вовсе (докстрока класса, 63%).
                    if not оглавление.известно(имя):
                        continue
                    ключ = имя.lower()
                    цель = cls._разрешить(
                        квалификатор, ключ, индекс_модуля, общие, свои
                    )
                    массив = _по_имени.get(ключ)
                    if массив is None:
                        массив = array("i")
                        _по_имени[ключ] = массив
                    массив.append(индекс_модуля)
                    массив.append(строка)
                    массив.append(цель)
                    рёбер += 1
                    if цель != -1:
                        разрешённых += 1

        return cls(оглавление.модули, _по_имени, рёбер, разрешённых)

    def _состояние(self) -> dict:
        """Рёбра в виде, годном для `marshal` — общее тело для `записать`
        и `сохранить_индексы`. Массивы идут байтами (`tobytes()`), не
        списками чисел, дороже на запись и на чтение вдвое-втрое."""
        return {
            "модули": self.модули,
            "по_имени": {имя: массив.tobytes() for имя, массив in self._по_имени.items()},
        }

    def записать(self, путь: Path) -> None:
        """Сохраняет рёбра на диск через голый `marshal`, без штампа и без
        сжатия — круг «построить -> записать -> прочитать» для тестов.
        Постоянное хранение кэша проекта — `сохранить_индексы`/
        `поднять_индексы`, через `index_cache`."""
        путь.write_bytes(marshal.dumps(self._состояние()))

    @classmethod
    def _из_состояния(cls, данные: dict) -> "Вызовы":
        """Собирает индекс вызовов из словаря `_состояние` — общее тело для
        `прочитать` и `поднять_индексы`.

        Оглавление сюда не нужно: адреса модулей и уже разрешённые цели
        лежат в самих данных, второй проход по исходникам не требуется.
        Массивы поднимаются `frombytes()` напрямую в пустой `array('i')`,
        без промежуточного `list` — см. докстроку модуля.
        """
        _по_имени: dict[str, array] = {}
        рёбер = 0
        разрешённых = 0
        for имя, байты in данные["по_имени"].items():
            массив = array("i")
            массив.frombytes(байты)
            _по_имени[имя] = массив
            for i in range(2, len(массив), 3):
                рёбер += 1
                if массив[i] != -1:
                    разрешённых += 1

        return cls(данные["модули"], _по_имени, рёбер, разрешённых)

    @classmethod
    def прочитать(cls, путь: Path) -> "Вызовы":
        """Поднимает индекс вызовов из файла `записать`."""
        return cls._из_состояния(marshal.loads(путь.read_bytes()))

    def _место(self, модуль: int, строка: int, цель: int) -> Место:
        return Место(
            модуль=self.модули[модуль],
            строка=строка,
            цель=self.модули[цель] if цель != -1 else None,
        )

    def места(self, имя: str) -> list[Место]:
        """Все места вызова процедуры с этим именем, без учёта регистра.

        `цель` заполнена только там, где источник надёжен (докстрока
        класса и `_разрешить`); иначе — `None`, а не имя, угаданное по
        совпадению.
        """
        массив = self._по_имени.get(имя.lower())
        if массив is None:
            return []
        return [
            self._место(массив[i], массив[i + 1], массив[i + 2])
            for i in range(0, len(массив), 3)
        ]


# Технические узлы `Form.xml`, которые не считаются элементами формы:
# `Events` — отдельный слой (обработчики, не элементы палитры), а
# `ExtendedTooltip`/`ContextMenu` платформа заводит автоматически на каждый
# интерактивный элемент — это не то, что разработчик сам добавил в форму.
# Замерено на живой выгрузке: без исключения этих трёх узлов дерево несёт
# 244 313 «элементов» вместо 89 528 — почти три четверти были бы чужой
# автогенерацией, а не составом формы.
_НЕ_ЭЛЕМЕНТЫ_ФОРМЫ = frozenset({"Events", "ExtendedTooltip", "ContextMenu"})


def _тег(узел: ET.Element) -> str:
    """Локальное имя тега без пространства имён.

    Настоящий `Form.xml` объявляет полный набор `xmlns` (`xcf/logform` и
    ещё девять служебных), и каждый тег на самом деле выглядит как
    `{http://v8.1c.ru/8.3/xcf/logform}Form`. Синтетические фикстуры тестов
    пространство имён не несут вовсе. Сравнение по тому, что после
    последней `}`, — единственный способ разбирать оба случая одним кодом,
    не заводя раздельных путей для «настоящего» XML и тестового.
    """
    return узел.tag.rsplit("}", 1)[-1]


def _прямой_ребёнок(узел: ET.Element, тег: str) -> ET.Element | None:
    """Первый прямой потомок с данным локальным именем тега, без поиска
    вглубь: `Attributes` и `ChildItems` — оба прямые дети корня `Form`,
    искать их через `.iter()` значило бы сканировать всё дерево ради
    одного узла у самого корня."""
    for ребёнок in узел:
        if _тег(ребёнок) == тег:
            return ребёнок
    return None


def _реквизиты_формы(корень: ET.Element) -> list[str]:
    """Имена реквизитов — прямые дети `<Attributes>`.

    Колонки табличных частей лежат глубже (`Attribute/Columns/Column`) и
    несут другой тег (`Column`, не `Attribute`) — в реквизиты формы не
    попадают: это состав табличной части, а не самой формы. Замерено на
    живой выгрузке: 25 651 реквизит именно на этом правиле.
    """
    узел = _прямой_ребёнок(корень, "Attributes")
    if узел is None:
        return []
    return [
        ребёнок.get("name") for ребёнок in узел
        if _тег(ребёнок) == "Attribute" and ребёнок.get("name") is not None
    ]


def _собрать_элементы(узел: ET.Element, накопитель: list[str]) -> None:
    for ребёнок in узел:
        тег = _тег(ребёнок)
        if тег in _НЕ_ЭЛЕМЕНТЫ_ФОРМЫ:
            continue
        имя = ребёнок.get("name")
        if имя is not None:
            накопитель.append(имя)
        _собрать_элементы(ребёнок, накопитель)


def _элементы_формы(корень: ET.Element) -> list[str]:
    """Имена элементов — всё дерево `<ChildItems>`, включая вложенные
    группы и страницы, но без спуска в технические обвязки
    (`_НЕ_ЭЛЕМЕНТЫ_ФОРМЫ`). Группа сама остаётся элементом — исключены
    только автогенерируемые платформой спутники, не пользовательские
    контейнеры."""
    узел = _прямой_ребёнок(корень, "ChildItems")
    накопитель: list[str] = []
    if узел is not None:
        _собрать_элементы(узел, накопитель)
    return накопитель


def _события_формы(корень: ET.Element) -> list[tuple[str, str]]:
    """(имя процедуры, имя события) для каждой непустой привязки — по
    всему дереву формы, а не только верхнеуровневому `<Events>` самой
    формы: у каждого элемента (кнопка, таблица, поле) свой блок `Events`,
    и обработчики в нём объявлены в том же модуле формы, что и обработчики
    формы целиком. Замерено на живой выгрузке: верхний уровень даёт 8 183
    привязки, дерево целиком — 24 202; ограничиться верхним уровнем значило
    бы потерять три из четырёх привязок.
    """
    пары = []
    for узел in корень.iter():
        if _тег(узел) != "Event":
            continue
        имя_процедуры = (узел.text or "").strip()
        имя_события = узел.get("name")
        if имя_процедуры and имя_события:
            пары.append((имя_процедуры, имя_события))
    return пары


@dataclass(slots=True)
class Форма:
    """Одна форма, собранная по запросу из массивов `Формы`.

    `битая` в интерфейсе задачи прямо не названа — та же ситуация, что с
    `вид` в `Запись` задачи 6: без поля тест «битый Form.xml не роняет
    разбор» нечем было бы проверить снаружи, а прятать признак битости
    только во флаге индекса значило бы отдавать наружу пустую форму,
    неотличимую от настоящей пустой.

    `события` — `dict[str, tuple[str, ...]]`, не `dict[str, str]` брифа.
    Правка по ревью: на живой выгрузке 12 процедур из 23 210 привязок
    объявлены обработчиком ДВУХ разных событий (например,
    `BeforeLoadDataFromSettingsAtServer` и `OnLoadDataFromSettingsAtServer`
    — обе на одну процедуру), и `dict[str, str]` в исходной версии кода
    отдавал только последнюю привязку по порядку обхода XML — причём
    `состав` и `обработчик` расходились между собой (словарь оставлял
    последнюю пару, `обработчик` возвращал первую по раннему `return`):
    один и тот же вопрос имел два разных ответа в одном и том же индексе.
    Кортеж хранит все РАЗЛИЧНЫЕ события процедуры в порядке первого
    появления в XML — без дублей: одна и та же процедура нередко висит на
    одном и том же событии сразу у нескольких элементов (общий обработчик
    `ПриИзменении` на десяти полях), и повторение одного и того же имени
    события в кортеже не добавляет агенту знания, только дублирует его.
    """

    реквизиты: list[str]
    элементы: list[str]
    события: dict[str, tuple[str, ...]]
    битая: bool


class Формы:
    """Индекс форм корпуса: реквизиты, элементы и привязки «процедура ->
    событие» из `Form.xml` (design doc, раздел 4).

    Без этого слоя «кто вызывает» пуст для четверти корпуса: 33 743
    процедуры из 137 115 (24,6%) не вызываются по имени нигде, и 25 606 из
    них — в модулях форм. Платформа вызывает их не по имени из кода, а по
    привязке в `Form.xml` (`<Event name="OnOpen">ПриОткрытии</Event>`), и
    без этого индекса такая процедура выглядит мёртвым кодом, хотя вызывается
    каждый раз при открытии формы.

    **Адрес формы выводится из пути `Form.xml`, не из пути `Module.bsl`.**
    `Form.xml` лежит на файл выше модуля той же формы: `.../Ext/Form.xml`
    рядом с `.../Ext/Form/Module.bsl`. Вместо того чтобы заново разбирать
    пять форм пути (design doc, `module_address`), путь `Form.xml`
    достраивается до пути модуля (`Ext/Form.xml` -> `Ext/Form/Module.bsl`)
    и отдаётся уже проверенному `адрес_модуля` — второй разбор того же
    пути прямо в этом классе был бы дублированием, расходящимся с
    оригиналом при первой же находке нового вида пути.

    **`адрес_модуля` не оборачивается в `try`** — тот же приём, что у
    `Оглавление.построить`: незнакомый каталог выгрузки — честный отказ, а
    не форма, молча пропущенная из индекса. Это другая забота, чем
    «битый `Form.xml`» ниже: там XML на диске синтаксически повреждён и
    прочитать нечего в принципе, здесь — путь не такой, каким его знает
    таблица соответствия, и подстановка была бы враньём.

    **Битый `Form.xml` форму не роняет.** `ET.fromstring` кидает
    `ParseError` на повреждённом XML — индекс расходный (как кэш), и одна
    испорченная форма не должна ронять сборку по всей выгрузке. Форма всё
    равно получает запись в индексе — с пустыми реквизитами, элементами и
    событиями и битом `битая` — вместо того чтобы тихо исчезнуть из
    индекса, что для потребителя неотличимо от «формы без единого
    реквизита».

    **Хранение — общий пул интернированных строк плюс параллельные
    `array('i')` со смещениями (CSR), а не список `Форма` на форму.** Тот
    же приём, что и в `Оглавление`/`Вызовы`: реквизит `Объект`,
    обработчик `ПриОткрытии` и подобные имена повторяются в тысячах форм,
    и общий пул хранит такую строку один раз, а не по копии на форму.
    Смещения по трём категориям (реквизиты, элементы, события) держат
    только начало диапазона каждой формы в общем плоском массиве — та же
    идея, что «имя цели -> array('i') троек» у `Вызовы`, только сгруппировано
    по форме, а не по имени.
    """

    __slots__ = (
        "модули", "_по_модулю", "_пул",
        "_реквизиты_начало", "_реквизиты",
        "_элементы_начало", "_элементы",
        "_события_начало", "_события_проц", "_события_имя",
        "_флаги", "битых",
    )

    БИТАЯ = 1

    def __init__(
        self,
        модули: list[str],
        _по_модулю: dict[str, int],
        _пул: list[str],
        _реквизиты_начало: array,
        _реквизиты: array,
        _элементы_начало: array,
        _элементы: array,
        _события_начало: array,
        _события_проц: array,
        _события_имя: array,
        _флаги: array,
        битых: int,
    ) -> None:
        # Приватный конструктор, как у Оглавление и Вызовы: собирает
        # готовые данные, ничего не вычисляет. Публичный вход —
        # `построить` (с диска) и `прочитать` (из ранее записанного файла).
        self.модули = модули
        self._по_модулю = _по_модулю
        self._пул = _пул
        self._реквизиты_начало = _реквизиты_начало
        self._реквизиты = _реквизиты
        self._элементы_начало = _элементы_начало
        self._элементы = _элементы
        self._события_начало = _события_начало
        self._события_проц = _события_проц
        self._события_имя = _события_имя
        self._флаги = _флаги
        self.битых = битых

    @staticmethod
    def _по_модулю_из(модули: list[str]) -> dict[str, int]:
        """Обратный индекс «адрес -> позиция», как `Оглавление._индексы`:
        производный от `модули`, на диске не хранится и пересчитывается
        что после сборки, что после подъёма."""
        return {адрес: i for i, адрес in enumerate(модули)}

    @classmethod
    def построить(cls, корень: Path) -> "Формы":
        """Проход по всем `Form.xml` выгрузки: адрес формы из пути,
        реквизиты/элементы/события — из XML.

        Порядок файлов детерминированный (`sorted`), как у
        `Оглавление.построить` и `Вызовы.построить` — ради воспроизводимости
        замеров между прогонами.
        """
        модули: list[str] = []
        _пул: list[str] = []
        индекс_строки: dict[str, int] = {}

        _реквизиты_начало = array("i")
        _реквизиты = array("i")
        _элементы_начало = array("i")
        _элементы = array("i")
        _события_начало = array("i")
        _события_проц = array("i")
        _события_имя = array("i")
        _флаги = array("i")
        битых = 0

        def интерн(строка: str) -> int:
            позиция = индекс_строки.get(строка)
            if позиция is None:
                позиция = len(_пул)
                _пул.append(sys.intern(строка))
                индекс_строки[строка] = позиция
            return позиция

        for файл in sorted(корень.rglob("Form.xml")):
            относительный = файл.relative_to(корень).as_posix()
            # Form.xml лежит на файл выше Module.bsl той же формы —
            # достраиваем путь до вида, который уже понимает адрес_модуля,
            # вместо того чтобы заново разбирать пять форм пути здесь.
            псевдо_путь = относительный[: -len("Form.xml")] + "Form/Module.bsl"
            адрес = адрес_модуля(псевдо_путь)
            модули.append(адрес)

            _реквизиты_начало.append(len(_реквизиты))
            _элементы_начало.append(len(_элементы))
            _события_начало.append(len(_события_проц))

            битая = False
            try:
                корень_xml = ET.fromstring(файл.read_bytes())
            except ET.ParseError:
                # Индекс расходный: одна повреждённая форма помечается и
                # не роняет сборку по всей выгрузке (решение координатора).
                битая = True
                битых += 1
            else:
                for имя in _реквизиты_формы(корень_xml):
                    _реквизиты.append(интерн(имя))
                for имя in _элементы_формы(корень_xml):
                    _элементы.append(интерн(имя))
                for имя_процедуры, имя_события in _события_формы(корень_xml):
                    _события_проц.append(интерн(имя_процедуры))
                    _события_имя.append(интерн(имя_события))

            _флаги.append(cls.БИТАЯ if битая else 0)

        # Сентинел CSR: конец последнего диапазона — общая длина массива.
        _реквизиты_начало.append(len(_реквизиты))
        _элементы_начало.append(len(_элементы))
        _события_начало.append(len(_события_проц))

        return cls(
            модули, cls._по_модулю_из(модули), _пул,
            _реквизиты_начало, _реквизиты,
            _элементы_начало, _элементы,
            _события_начало, _события_проц, _события_имя,
            _флаги, битых,
        )

    def _состояние(self) -> dict:
        """Пул строк и массивы в виде, годном для `marshal` — общее тело
        для `записать` и `сохранить_индексы`. `array` идёт байтами
        (`tobytes()`), обратный индекс `_по_модулю` не входит, он
        производный от `модули`."""
        return {
            "модули": self.модули,
            "пул": self._пул,
            "реквизиты_начало": self._реквизиты_начало.tobytes(),
            "реквизиты": self._реквизиты.tobytes(),
            "элементы_начало": self._элементы_начало.tobytes(),
            "элементы": self._элементы.tobytes(),
            "события_начало": self._события_начало.tobytes(),
            "события_проц": self._события_проц.tobytes(),
            "события_имя": self._события_имя.tobytes(),
            "флаги": self._флаги.tobytes(),
            "битых": self.битых,
        }

    def записать(self, путь: Path) -> None:
        """Сохраняет пул строк и массивы на диск через голый `marshal`, без
        штампа и без сжатия — круг «построить -> записать -> прочитать»
        для тестов. Постоянное хранение кэша проекта — `сохранить_индексы`/
        `поднять_индексы`, через `index_cache`."""
        путь.write_bytes(marshal.dumps(self._состояние()))

    @classmethod
    def _из_состояния(cls, данные: dict) -> "Формы":
        """Собирает индекс форм из словаря `_состояние` — общее тело для
        `прочитать` и `поднять_индексы`. Массивы — через `frombytes()`
        напрямую в пустой `array('i')`, без промежуточного `list`
        (докстрока модуля, про 97 МБ вместо 62 на `Оглавление`)."""

        def массив(ключ: str) -> array:
            восстановленный = array("i")
            восстановленный.frombytes(данные[ключ])
            return восстановленный

        модули = данные["модули"]
        return cls(
            модули, cls._по_модулю_из(модули), данные["пул"],
            массив("реквизиты_начало"), массив("реквизиты"),
            массив("элементы_начало"), массив("элементы"),
            массив("события_начало"), массив("события_проц"), массив("события_имя"),
            массив("флаги"), данные["битых"],
        )

    @classmethod
    def прочитать(cls, путь: Path) -> "Формы":
        """Поднимает индекс форм из файла `записать`."""
        return cls._из_состояния(marshal.loads(путь.read_bytes()))

    def _события_формы_из_индекса(self, i: int) -> dict[str, tuple[str, ...]]:
        """Группирует плоские пары CSR-диапазона формы `i` по имени
        процедуры, без потери событий и без дублей.

        Общий код для `_состав` и `обработчик` (задача ревью: те же данные
        читались дважды двумя разными способами и расходились между
        собой). Порядок ключей и порядок событий внутри каждого кортежа —
        порядок первого появления в XML, `dict`/`list` в CPython его
        сохраняют.
        """
        накопитель: dict[str, list[str]] = {}
        начало, конец = self._события_начало[i], self._события_начало[i + 1]
        for j in range(начало, конец):
            проц = self._пул[self._события_проц[j]]
            событие = self._пул[self._события_имя[j]]
            список = накопитель.setdefault(проц, [])
            if событие not in список:
                список.append(событие)
        return {проц: tuple(имена) for проц, имена in накопитель.items()}

    def _состав(self, i: int) -> Форма:
        реквизиты = [
            self._пул[self._реквизиты[j]]
            for j in range(self._реквизиты_начало[i], self._реквизиты_начало[i + 1])
        ]
        элементы = [
            self._пул[self._элементы[j]]
            for j in range(self._элементы_начало[i], self._элементы_начало[i + 1])
        ]
        return Форма(
            реквизиты=реквизиты,
            элементы=элементы,
            события=self._события_формы_из_индекса(i),
            битая=bool(self._флаги[i] & self.БИТАЯ),
        )

    def состав(self, адрес: str) -> Форма | None:
        """Форма по адресу модуля, или `None`, если адрес не найден.

        Правка по ревью: раньше неизвестный адрес был `KeyError`, а
        `обработчик` на том же случае молча отдавал `None` — асимметрия,
        которой в остальном индексе нет (`Оглавление.модуля`,
        `Вызовы.места` тоже деградируют мягко на неизвестном адресе).
        Агент почти всегда составляет адрес формы руками, и опечатка —
        рядовой случай, а не исключительная ситуация; `None`, а не пустая
        `Форма` — потому что пустая форма неотличима от формы, у которой
        на самом деле нет ни одного реквизита (это рассуждение не
        изменилось, изменился только тип отказа).
        """
        индекс = self._по_модулю.get(адрес)
        if индекс is None:
            return None
        return self._состав(индекс)

    def обработчик(self, адрес_модуля: str, имя: str) -> tuple[str, ...] | None:
        """События платформы, обработчиком которых объявлена процедура
        `имя` в форме `адрес_модуля` — кортеж имён в порядке первого
        появления в `Form.xml`, или `None`, если это не обработчик (или
        форма вовсе не найдена).

        Тот же кортеж, что лежит в `состав(адрес_модуля).события[имя]` —
        считается общим `_события_формы_из_индекса`, поэтому два метода
        физически не могут разойтись, как расходились до правки по
        ревью.

        Сравнение без учёта регистра — BSL не различает регистр имён
        (тот же приём, что `Оглавление.по_имени`).
        """
        индекс = self._по_модулю.get(адрес_модуля)
        if индекс is None:
            return None
        имя_нижний = имя.lower()
        for проц, события in self._события_формы_из_индекса(индекс).items():
            if проц.lower() == имя_нижний:
                return события
        return None


# Буква или цифра (кириллица/латиница) — сторож для декоративных строк
# шапки: голое `//`, ряд слэшей (`////...`), разделитель `//----...`. Без
# единой буквы или цифры строка не несёт текста, только оформление.
_НЕ_БУКВЫ_ЦИФРЫ = re.compile(r"[^0-9A-Za-zА-Яа-яЁё]+")


def _содержательна(строка: str) -> bool:
    """Есть ли в строке шапки хоть одна буква или цифра.

    Разведка по живой конфигурации (ревью задачи 8): 22 экспортные
    процедуры из 31 044 с непустой шапкой начинают её именно такой
    строкой-разделителем, а не текстом.
    """
    return bool(_НЕ_БУКВЫ_ЦИФРЫ.sub("", строка))


def _первая_строка_шапки(шапка: str) -> str:
    """Первая СОДЕРЖАТЕЛЬНАЯ строка шапки, а не обязательно первая по счёту.

    `шапка.split("\n", 1)[0]` — прежняя версия — брала буквально первую
    строку и на 22 процедурах из 31 044 индексировала декоративный
    разделитель (`//`, `////////`, `//----…`) вместо описания, которое
    стоит следующей строкой: поле `header` было фактически пустым ровно
    там, где шапка ценнее всего (короткое имя, ничего не говорящее само
    по себе). Пустая шапка (нет ни одной строки) и шапка из одних
    разделителей — оба честно дают "": в первом случае описания нет, во
    втором оно не написано, и подставлять что-то вместо него значило бы
    врать о содержимом документа.
    """
    for строка in шапка.split("\n"):
        if _содержательна(строка):
            return строка
    return ""


def построить_поиск(оглавление: Оглавление, корень: Path) -> SearchIndex:
    """Поиск словами — только по экспортным: 173 МБ против 473 МБ на живой
    выгрузке (design doc, раздел 4). Неэкспортную процедуру из чужого
    модуля всё равно не вызвать; внутри своего модуля её отдаёт оглавление
    модуля за 0,001 мс — доступ не теряется, теряется только угадывание по
    смыслу.

    **Документ несёт имя, адрес модуля и первую СОДЕРЖАТЕЛЬНУЮ строку
    комментария-шапки** (`_первая_строка_шапки`, не обязательно первую по
    счёту — декоративные разделители вроде голого `//` пропускаются, см.
    докстроку хелпера). В BSL типов в сигнатуре нет: `Функция
    ПроверитьОстатки(Склад)` не говорит ничего о том, что такое `Склад`, а
    шапка над объявлением — по стандарту БСП единственное место, где это
    написано. Замер на живой конфигурации (`tools/lab/
    measure_modules_search.py`, три прогона на вариант, медиана): без
    шапки — 138 МБ, шапка целиком — 254 МБ (+84%), первая содержательная
    строка шапки — 173 МБ (+25%). 84% больше порога брифа в 30% — берётся
    первая строка, решение по замеру, а не по удобству кода (полные цифры
    и команда воспроизведения — docs/modules-provider-design.md, раздел 4).
    Одной строки хватает почти всегда: у БСП шапка начинается кратким
    описанием, а `Параметры:`/`Возвращаемое значение:` идут дальше и
    добавляют главным образом имена параметров, которые и так в сигнатуре.

    **Второй проход по выгрузке, не переиспользование уже разобранного.**
    `Оглавление.построить` вызывает тот же `разобрать`, но не хранит
    `Процедура.шапка` — она, как и сигнатура, читается с диска по
    требованию (докстрока класса `Оглавление`, 62 МБ вместо 128). Второй
    проход обходится дешевле первого: `оглавление.модуля(адрес)` уже знает,
    в каком модуле есть хоть одна экспортная процедура, и файл без единой
    экспортной вовсе не открывается — читать и разбирать его здесь ради
    факта, который оглавление уже подтвердило отрицательным, было бы
    тратой второго прохода на то, что первый уже посчитал.

    **Полезная нагрузка — `Запись` оглавления, не новый тип.** Тот же
    объект, что отдают `Оглавление.по_имени`/`модуля`: адрес, имя,
    экспортность, границы, перекрытие, вид — всё, что нужно `search_
    procedures`, чтобы дочитать сигнатуру и тело с диска по адресу
    (design doc, раздел 5), без второго словаря «как найти процедуру по
    попаданию поиска».
    """
    индекс = SearchIndex(field_weights={"name": 1.0, "module": 0.4, "header": 0.6})
    for файл in sorted(корень.rglob("*.bsl")):
        относительный = файл.relative_to(корень).as_posix()
        адрес = адрес_модуля(относительный)
        if not any(запись.экспорт for запись in оглавление.модуля(адрес)):
            continue
        for процедура in разобрать(прочитать_модуль(файл)):
            if not процедура.экспорт:
                continue
            индекс.add(
                Doc(
                    id=f"{адрес}::{процедура.имя}",
                    payload=Запись(
                        модуль=адрес,
                        имя=процедура.имя,
                        экспорт=True,
                        строка=процедура.строка,
                        конец=процедура.конец,
                        перекрыта=bool(процедура.перекрытие),
                        частичный=процедура.частичный,
                        функция=процедура.вид == "функция",
                    ),
                    fields={
                        "name": процедура.имя,
                        "module": адрес,
                        # Первая СОДЕРЖАТЕЛЬНАЯ строка, а не шапка целиком
                        # (решение по замеру — докстрока функции) и не
                        # обязательно первая по счёту (декоративные
                        # разделители пропускаются — докстрока
                        # `_первая_строка_шапки`).
                        "header": _первая_строка_шапки(процедура.шапка),
                    },
                )
            )
    return индекс


# Имена файлов кэша — дословно то, что должно лежать в `Registry.CACHE_KINDS`
# под `KIND_MODULES`/`KIND_EXTENSION` (`registry.py`). Четыре разных имени,
# а не одно общее: `index_cache.sweep` на старте считает своим только то,
# что названо в `CACHE_KINDS`, и одно общее имя на четыре структуры (как
# было до задачи 9) значило бы, что три из четырёх сносятся на первом же
# перезапуске, молча, и пересобираются заново каждый раз.
_КЭШ_ОГЛАВЛЕНИЯ = "modules-toc"
_КЭШ_ВЫЗОВОВ = "modules-calls"
_КЭШ_ФОРМ = "modules-forms"
_КЭШ_ПОИСКА = "modules-search"


@dataclass(slots=True)
class Индексы:
    """Четыре структуры провайдера `modules` одним пакетом.

    Читаются и пишутся вместе (`сохранить_индексы`/`поднять_индексы`): они
    описывают один и тот же корпус кода, и рассогласование между ними
    (например, свежее оглавление и устаревший поиск) было бы молчаливой
    порчей ответа — хуже полной пересборки, которая хотя бы честно медленная.
    """

    оглавление: Оглавление
    вызовы: Вызовы
    формы: Формы
    поиск: SearchIndex


def сохранить_индексы(registry, source_id: str, индексы: Индексы) -> None:
    """Записать все четыре структуры в кэш проекта — под четырьмя именами.

    Оглавление, вызовы и формы хранят параллельные массивы напрямую — им
    подходит низкоуровневый `index_cache.save_blob`: он берёт ровно то, что
    несёт `_состояние()` каждой структуры, и добавляет сверху штамп версии
    кода и sha256 источника, которых у голого `marshal` (`записать`) нет.

    Поиск идёт другим путём, `index_cache.save`, не `save_blob`: у него уже
    есть готовая пара `SearchIndex.export_state`/`from_state`, и полезная
    нагрузка документов (записи оглавления) на диск намеренно не пишется —
    `поднять_индексы` подставляет её заново из уже поднятого оглавления
    (докстрока `SearchIndex.export_state`).
    """
    источник = registry.sources[source_id]
    index_cache.save_blob(
        индексы.оглавление._состояние(),
        index_cache.path_for(registry.cache_dir, source_id, _КЭШ_ОГЛАВЛЕНИЯ),
        source_sha256=источник.sha256,
        kind=_КЭШ_ОГЛАВЛЕНИЯ,
    )
    index_cache.save_blob(
        индексы.вызовы._состояние(),
        index_cache.path_for(registry.cache_dir, source_id, _КЭШ_ВЫЗОВОВ),
        source_sha256=источник.sha256,
        kind=_КЭШ_ВЫЗОВОВ,
    )
    index_cache.save_blob(
        индексы.формы._состояние(),
        index_cache.path_for(registry.cache_dir, source_id, _КЭШ_ФОРМ),
        source_sha256=источник.sha256,
        kind=_КЭШ_ФОРМ,
    )
    index_cache.save(
        индексы.поиск,
        index_cache.path_for(registry.cache_dir, source_id, _КЭШ_ПОИСКА),
        source_sha256=источник.sha256,
        kind=_КЭШ_ПОИСКА,
    )


def _полезная_нагрузка(оглавление: Оглавление) -> dict[str, Запись]:
    """`doc.id -> Запись` для ровно тех документов, что индексировал
    `построить_поиск`: экспортные процедуры, ключ `f"{модуль}::{имя}"`.

    Без записи оглавления подставить нечего — вот почему подъём поиска
    возможен только после подъёма оглавления, а не параллельно с ним.
    """
    return {
        f"{запись.модуль}::{запись.имя}": запись
        for запись in оглавление.все()
        if запись.экспорт
    }


def поднять_индексы(registry, source_id: str) -> "Индексы | None":
    """Поднять все четыре структуры из кэша проекта. `None` — кэш не годится
    хотя бы для одной из них, тогда собирать нужно все четыре заново:
    частичный подъём (например, свежее оглавление поверх устаревшего
    индекса вызовов) был бы более опасной порчей ответа, чем честная
    пересборка.

    Порядок принципиален: оглавление поднимается первым, потому что
    полезная нагрузка документов поиска — записи оглавления, а не свой
    собственный слой на диске (решение координатора, docs/modules-provider
    -design.md, раздел 9) — без свежего оглавления её неоткуда взять.
    """
    источник = registry.sources.get(source_id)
    if источник is None:
        return None
    сигнатура = источник.sha256

    данные_оглавления = index_cache.load_blob(
        index_cache.path_for(registry.cache_dir, source_id, _КЭШ_ОГЛАВЛЕНИЯ),
        source_sha256=сигнатура,
        kind=_КЭШ_ОГЛАВЛЕНИЯ,
    )
    if данные_оглавления is None:
        return None

    данные_вызовов = index_cache.load_blob(
        index_cache.path_for(registry.cache_dir, source_id, _КЭШ_ВЫЗОВОВ),
        source_sha256=сигнатура,
        kind=_КЭШ_ВЫЗОВОВ,
    )
    if данные_вызовов is None:
        return None

    данные_форм = index_cache.load_blob(
        index_cache.path_for(registry.cache_dir, source_id, _КЭШ_ФОРМ),
        source_sha256=сигнатура,
        kind=_КЭШ_ФОРМ,
    )
    if данные_форм is None:
        return None

    состояние_поиска = index_cache.load_blob(
        index_cache.path_for(registry.cache_dir, source_id, _КЭШ_ПОИСКА),
        source_sha256=сигнатура,
        kind=_КЭШ_ПОИСКА,
    )
    if состояние_поиска is None:
        return None

    try:
        оглавление = Оглавление._из_состояния(данные_оглавления)
        вызовы = Вызовы._из_состояния(данные_вызовов)
        формы = Формы._из_состояния(данные_форм)
        поиск = SearchIndex.from_state(
            состояние_поиска,
            _полезная_нагрузка(оглавление),
            synonyms=registry.dictionary.synonyms(),
        )
    except (KeyError, TypeError, ValueError):
        # Штампы совпали у всех четырёх файлов, но форма содержимого не та
        # (например, кэш от другой версии индекса, которую штамп почему-то
        # не отсёк) — тот же принцип, что в `index_cache.load`: промах
        # кэша, а не повод падать.
        return None

    return Индексы(оглавление=оглавление, вызовы=вызовы, формы=формы, поиск=поиск)
