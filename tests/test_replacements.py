def _токены_сборщика() -> tuple[str, ...]:
    """`PLATFORM_836_TOKENS` из скрипта сборки обработки.

    Скрипт живёт вне пакета и о нём не знает, поэтому загружается по пути. Он
    тянет только стандартную библиотеку — импорт безопасен.
    """
    import importlib.util
    from pathlib import Path

    путь = Path(__file__).resolve().parent.parent / "exporter-1c" / "build_modules.py"
    spec = importlib.util.spec_from_file_location("build_modules", путь)
    модуль = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(модуль)
    return модуль.PLATFORM_836_TOKENS


def test_сборщик_не_запрещает_доступное_в_835():
    """`СтрСравнить` есть в 8.3.5 — запрещать её в XML-варианте не за что.

    Список писался по памяти в первом же коммите обработки (`c498cee`,
    2026-08-15), когда справку ещё не умели разбирать. Теперь есть чем сверить.
    """
    assert "СтрСравнить" not in _токены_сборщика()


def test_каждому_запрету_сборщика_есть_замена():
    """Если сборщик считает вызов невозможным на 8.3.5, агенту нужен обход.

    Иначе получается разнобой: обработка знает, что так писать нельзя, а сервер
    на вопрос «чем заменить» молчит.
    """
    без_рецепта = [имя for имя in _токены_сборщика() if replacements.find(имя) is None]

    assert без_рецепта == []
