"""Лексер BSL: границы процедур, сигнатура с переносом строк, `Экспорт`.

Фундамент провайдера `modules` (`docs/modules-provider-design.md`, раздел 3):
оглавление процедур, индекс вызовов и три инструмента MCP читают код через
этот модуль. Разведочный прототип лежит в `tools/lab/bsl_lex.py`; в нём
найдены четыре дефекта, и переносить его как есть нельзя. Эта задача закрывает
один из них: разбор, читающий только строку объявления, теряет `Экспорт` у
2 074 процедур из 49 182 — именно у самых длинных сигнатур, где перенос строк
случается чаще всего. Параметры теперь добираются до баланса скобок, и только
после закрывающей ищется `Экспорт`, даже если он оказался на другой строке.

Задача 2 закрывает второй дефект: состояние «внутри незакрытого литерала»
теперь ведётся между строками (`_код_строки`), а не гаснет на границе строки
файла. Без этого комментарий внутри незакрытого текста запроса и директивы
правки расширения `#Вставка`/`#Удаление` теряют состояние молча — на живом
коде это стоило 184 объявлений в одном файле (design doc, раздел 3).

Разбор аннотаций и вызовов внутри тела — задача 3. Поля датакласса под них
(`директива`, `перекрытие`, `шапка`, `вызовы`) объявлены уже здесь и всегда
пустые: иначе датакласс пришлось бы перекраивать под каждую следующую задачу.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

# Границы объявления. Русские и английские написания — оба встречаются в
# живых конфигурациях.
_НАЧАЛО = {
    "процедура": "процедура",
    "функция": "функция",
    "procedure": "процедура",
    "function": "функция",
}
_КОНЕЦ = {"конецпроцедуры", "конецфункции", "endprocedure", "endfunction"}
_ЭКСПОРТ = {"экспорт", "export"}

_ИМЯ = r"[А-Яа-яЁёA-Za-z_][А-Яа-яЁёA-Za-z_0-9]*"
_СЛОВО = re.compile(_ИМЯ)
# `Асинх` (8.3.18+) стоит ПЕРЕД видом («Асинх Процедура Имя() Экспорт»), а не
# первым словом строки в обычном смысле — без сдвига на это слово терялось
# 207 процедур (design doc, раздел 3). Он необязателен и не сохраняется:
# полей под него в датаклассе нет, только вид и имя нужны для оглавления.
#
# Без `^`: разбор возобновляется и с произвольного столбца, не только с
# начала строки (см. `разобрать` — хвост после `Экспорт`/`КонецПроцедуры` на
# той же физической строке). `^` без re.MULTILINE привязан к абсолютному
# началу строки-аргумента и с `pos>0` в `.match()` не совпал бы никогда;
# `.match(код, столбец)` и без `^` уже пытается совпасть ровно с этой позиции,
# так что якорь был лишним даже при столбец=0.
_ОБЪЯВЛЕНИЕ = re.compile(
    rf"\s*(?:(?:асинх|async)\s+)?({_ИМЯ})\s+({_ИМЯ})\s*\(",
    re.IGNORECASE,
)
# Тело — почти все строки корпуса (3,9 млн из ~4 млн), поэтому поиск конца
# внутри тела обязан быть одним re.search на строку, а не циклом по словам:
# `А = 1; КонецПроцедуры` в одной строке — валидный BSL, и КонецПроцедуры там
# не первое слово. Построена из _КОНЕЦ, чтобы не держать список ключевых слов
# в двух местах.
_ЗАКРЫТИЕ = re.compile(rf"\b(?:{'|'.join(_КОНЕЦ)})\b", re.IGNORECASE)


@dataclass(slots=True)
class Процедура:
    """Одно объявление `Процедура…КонецПроцедуры` / `Функция…КонецФункции`.

    `директива`, `перекрытие`, `шапка`, `вызовы` заполняет задача 3
    (директивы компиляции, аннотации перекрытия, шапка, индекс вызовов);
    здесь они всегда пустые.
    """

    имя: str
    вид: str                       # "процедура" | "функция"
    параметры: str
    экспорт: bool
    строка: int
    конец: int = 0                  # 0 — КонецПроцедуры/КонецФункции не найден
    директива: str = ""
    перекрытие: tuple[str, str] | tuple[()] = ()
    шапка: str = ""
    частичный: bool = False
    вызовы: list[tuple[str, str, int]] = field(default_factory=list)


def нормализовать(текст: str) -> str:
    """Переводы строк к `\\n`; одиночный `CR` без пары `\\n` — не граница строки.

    `str.splitlines()` не применяется нигде в проекте: он режет ещё и по
    `\\v`, `\\f`, `\\x1c`–`\\x1e`, `\\x85`, `U+2028`, которых для 1С не
    существует. Но и наивная замена `\\r` → `\\n` не годится: в корпусе 50
    одиночных `CR` в 6 файлах — случайные байты, а не старый маковский
    перевод строки, и превращать их в `\\n` значит молча сдвигать номера
    строк ровно там, где эта функция обязана их не сдвигать. Одиночный `\\r`
    заменяется пробелом: строку не рвёт и соседние токены не склеивает.
    """
    return текст.replace("\r\n", "\n").replace("\r", " ")


def _код_строки(строка: str, в_строке: bool, мёртвая_ветка: bool) -> tuple[str, bool]:
    """Строка без литералов и комментария плюс новое состояние.

    Содержимое литерала заменяется пробелами, а не выбрасывается: позиции
    остальных символов обязаны сохраниться, иначе номера колонок поедут — на
    них опирается `_сигнатура`.

    Три правила, найденные на живом коде (design doc, раздел 3):

    * внутри незакрытого литерала строка, начинающаяся с `//`, — комментарий,
      а не содержимое и не конец. Разработчик комментирует куски текста
      запроса вместе с тем, что выглядит как закрывающая кавычка; лексер,
      считающий эту кавычку закрывающей, теряет состояние до конца файла —
      одна такая строка съела 184 объявления;
    * внутри `#Удаление … #КонецУдаления` текст мёртв и на состояние не
      влияет: удаляемая и вставляемая ветки несут каждая свою закрывающую
      кавычку, и состояние обязано вестись только по ветке `#Вставка`
      (`мёртвая_ветка` переключает вызывающий код `разобрать`, здесь только
      применяется — при мёртвой ветке состояние на входе возвращается как
      есть, что бы в тексте ни было);
    * удвоенная кавычка `""` внутри литерала — часть текста, а не закрытие
      плюс новое открытие.
    """
    if мёртвая_ветка:
        return " " * len(строка), в_строке
    if в_строке and строка.lstrip().startswith("//"):
        return " " * len(строка), True

    маска = list(строка)
    i, n = 0, len(строка)
    if в_строке:
        # Продолжение литерала, открытого на предыдущей строке: ищем
        # закрывающую кавычку с самого начала, а не заново решаем, что тут
        # литерал — это уже решено состоянием на входе.
        начало = i
        закрыт = False
        while i < n:
            if строка[i] == '"':
                if i + 1 < n and строка[i + 1] == '"':
                    i += 2               # удвоенная кавычка — часть текста
                    continue
                i += 1
                закрыт = True
                break
            i += 1
        for j in range(начало, i):
            маска[j] = " "
        if not закрыт:
            return "".join(маска), True
        в_строке = False
        # Литерал закрылся посреди строки — остаток разбираем как код.

    while i < n:
        if строка[i] == '"':
            начало = i
            i += 1
            закрыт = False
            while i < n:
                if строка[i] == '"':
                    if i + 1 < n and строка[i + 1] == '"':
                        i += 2           # удвоенная кавычка — часть текста
                        continue
                    i += 1
                    закрыт = True
                    break
                i += 1
            for j in range(начало, i):
                маска[j] = " "
            if not закрыт:
                # Не закрылась до конца строки — продолжится на следующей
                # через `|`, состояние уходит в следующий вызов.
                return "".join(маска), True
            continue
        if строка[i] == "/" and i + 1 < n and строка[i + 1] == "/":
            for j in range(i, n):
                маска[j] = " "
            break
        i += 1
    return "".join(маска), False


def _сигнатура(маски: list[str], начало: int, столбец: int) -> tuple[str, int, int]:
    """Текст параметров до баланса скобок и место сразу за закрывающей.

    Читать одну строку нельзя: у 2 074 процедур из 49 182 сигнатура
    перенесена, и `Экспорт` стоит на последней строке (design doc, раздел 3).
    Строки уже без литералов и комментариев (`маски`) — скобка внутри
    строкового умолчания параметра в баланс не идёт. Столбец на выходе — не
    параметр, а точка, откуда вызывающий код ищет `Экспорт` и следом
    `КонецПроцедуры`: `Процедура П() КонецПроцедуры` — обычная запись в одну
    строку, без этого столбца её было бы негде искать.
    """
    глубина, куски, номер = 0, [], начало
    while номер < len(маски):
        строка = маски[номер]
        начиная_с = столбец if номер == начало else 0
        for позиция in range(начиная_с, len(строка)):
            символ = строка[позиция]
            if символ == "(":
                глубина += 1
                if глубина == 1:
                    continue
            elif символ == ")":
                глубина -= 1
                if глубина == 0:
                    return "".join(куски).strip(), номер, позиция + 1
            if глубина >= 1:
                куски.append(символ)
        куски.append(" ")
        номер += 1
    # Скобка не закрылась до конца текста — модуль оборван внутри сигнатуры.
    return "".join(куски).strip(), начало, столбец


def _слово_с(строка: str, столбец: int) -> tuple[str, int]:
    """Первое слово строки от `столбец` и позиция сразу за ним.

    Пустое слово и тот же столбец — там нет идентификатора (конец строки,
    знак препинания и т. п.).
    """
    хвост = строка[столбец:]
    голый = хвост.lstrip()
    слово = _СЛОВО.match(голый)
    if not слово:
        return "", столбец
    начало_слова = столбец + (len(хвост) - len(голый))
    return слово.group(0), начало_слова + len(слово.group(0))


def разобрать(текст: str) -> list[Процедура]:
    """Процедуры и функции модуля: границы, сигнатура с переносом, `Экспорт`.

    Проход ведёт курсор (строка, столбец), а не только строка: закрыв
    сигнатуру и проверив `Экспорт`/`КонецПроцедуры`, разбор возвращается на ТУ
    ЖЕ физическую строку с позиции сразу после найденного слова, а не
    перескакивает через её остаток. Без этого второе объявление на одной
    физической строке — «Процедура П1() КонецПроцедуры Процедура П2() …» —
    пропадало молча: обычное следствие того, что `нормализовать` схлопывает
    одиночный `CR` в пробел, а не в перевод строки, и может слить две
    исходные строки в одну.

    Внутри тела (`текущая is not None`) та же логика, но не по слову за раз —
    `КонецПроцедуры` ищется `re.search`-ом по всей оставшейся строке сразу:
    `А = 1; КонецПроцедуры` в одну строку — валидный BSL, и без этого поиска
    (только по первому слову) граница уезжала на первый попавшийся
    `КонецПроцедуры` дальше по файлу, а всё, что должно было открыться между
    ними, терялось. Тело — почти весь корпус построчно, поэтому один поиск на
    строку допустим, а разбор строки по словам в цикле — нет. Вызовы и
    аннотации посреди тела остаются за задачей 3.
    """
    строки = нормализовать(текст).split("\n")
    маски: list[str] = []
    в_строке = False
    мёртвая_ветка = False
    for строка in строки:
        # Директивы правки расширения всегда занимают строку целиком (это
        # формат выгрузки, не догадка) — проверяются по исходному тексту, а
        # не по маске, и раньше вызова `_код_строки`: `#Удаление` может
        # встретиться посреди ещё не закрытого литерала (design doc,
        # раздел 3, пример с `АналитикаХозяйственныхОпераций`), и на решение
        # «мёртвая ветка или нет» это не влияет.
        голая = строка.strip().lower()
        if голая == "#удаление":
            мёртвая_ветка = True
        elif голая == "#конецудаления":
            мёртвая_ветка = False
        код, в_строке = _код_строки(строка, в_строке, мёртвая_ветка)
        маски.append(код)

    процедуры: list[Процедура] = []
    текущая: Процедура | None = None
    номер, столбец = 0, 0
    while номер < len(строки):
        код = маски[номер]
        голая = код[столбец:].strip()
        if not голая:
            номер += 1
            столбец = 0
            continue

        if текущая is None:
            м = _ОБЪЯВЛЕНИЕ.match(код, столбец)
            вид_слово = м.group(1).lower() if м else ""
            if м and вид_слово in _НАЧАЛО:
                открывающая = м.end() - 1      # позиция "("
                параметры, конец_строки, после_скобки = _сигнатура(маски, номер, открывающая)
                маска_конца = маски[конец_строки]
                слово, после_слова = _слово_с(маска_конца, после_скобки)
                экспорт = слово.lower() in _ЭКСПОРТ
                if экспорт:
                    слово, после_слова = _слово_с(маска_конца, после_слова)

                текущая = Процедура(
                    имя=м.group(2), вид=_НАЧАЛО[вид_слово],
                    параметры=параметры, экспорт=экспорт, строка=номер + 1,
                )
                if слово.lower() in _КОНЕЦ:
                    # Объявление и конец в одной строке уже разобраны целиком.
                    текущая.конец = конец_строки + 1
                    процедуры.append(текущая)
                    текущая = None
                # Не перескакиваем через остаток строки — на ней может стоять
                # ещё одно объявление (закрытый случай) или просто хвост,
                # который следующая проверка обязана увидеть, а не потерять.
                номер, столбец = конец_строки, после_слова
                continue
        else:
            м = _ЗАКРЫТИЕ.search(код, столбец)
            if м:
                текущая.конец = номер + 1
                процедуры.append(текущая)
                текущая = None
                # Тот же приём, что и для объявления: остаток строки после
                # найденного слова может держать следующую процедуру
                # («…КонецПроцедуры Процедура П2()…») — досканировать его, а
                # не перепрыгивать.
                столбец = м.end()
                continue

        номер += 1
        столбец = 0

    if текущая is not None:
        # Модуль оборвался раньше `КонецПроцедуры` — выгрузка обрезана или
        # файл битый; отдаём разобранное, а не молчим.
        текущая.частичный = True
        процедуры.append(текущая)
    return процедуры
