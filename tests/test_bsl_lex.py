def test_удвоенная_кавычка_не_закрывает_литерал():
    """`""` внутри литерала — часть текста. Если счесть её концом строки,
    состояние уедет и следующее объявление пропадёт."""
    текст = (
        'Процедура Пример()\n'
        '\tА = "он сказал ""да"" вчера";\n'
        'КонецПроцедуры\n'
        'Процедура Следующая()\n'
        'КонецПроцедуры\n'
    )
    assert [п.имя for п in разобрать(текст)] == ["Пример", "Следующая"]


def test_слова_языка_внутри_литерала_не_объявления():
    текст = (
        'Процедура Пример()\n'
        '\tС = "Процедура: %1\n'
        '\t|КонецПроцедуры";\n'
        'КонецПроцедуры\n'
    )
    процедура = разобрать(текст)[0]
    assert процедура.имя == "Пример"
    # Слово внутри литерала не должно закрыть процедуру раньше времени: без
    # состояния между строками кавычка на строке 3 читается как ОТКРЫВАЮЩАЯ,
    # и "КонецПроцедуры" перед ней остаётся видимым кодом — конец уезжает на
    # строку 3 вместо настоящей строки 4. Проверка одних имён это не ловит.
    assert процедура.конец == 4
    assert процедура.частичный is False


def test_удаление_с_кавычкой_вставка_без_кавычки():
    """Обратная асимметрия: кавычка есть в мёртвой ветке и не должна закрыть
    литерал — состояние остаётся открытым и после `#КонецВставки`, до
    настоящей закрывающей кавычки дальше по телу."""
    текст = (
        'Процедура Перекрытая()\n'
        '\tТ = "ВЫБРАТЬ\n'
        '#Удаление\n'
        '\t|\tСтароеСКавычкой";\n'
        '#КонецУдаления\n'
        '#Вставка\n'
        '\t|\tНовоеБезКавычки\n'
        '#КонецВставки\n'
        'Возврат Т;";\n'
        'КонецПроцедуры\n'
        'Процедура Следующая()\n'
        'КонецПроцедуры\n'
    )
    процедуры = разобрать(текст)
    assert [п.имя for п in процедуры] == ["Перекрытая", "Следующая"]
    assert [п.конец for п in процедуры] == [10, 12]
    assert all(п.частичный is False for п in процедуры)


