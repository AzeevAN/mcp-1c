"""Оглавление процедур корпуса: сборка с диска, хранение, подъём.

Опора для поиска, «кто вызывает» и выдачи тела процедуры (design doc,
раздел 4). Хранение — параллельные массивы `array('i')`, имена
интернированы, сигнатура не хранится: она читается с диска по номеру
строки за 0,1 мс, держать её в памяти — лишние +66 МБ на конфигурацию ради
того, что и так под рукой.
"""
from __future__ import annotations

from mcp1c.modules_index import Вызовы, Оглавление


def test_оглавление_видит_все_процедуры(корень_кода):
    о = Оглавление.построить(корень_кода)
    имена = sorted(з.имя for з in о.все())
    assert имена == ["Внутренняя", "ПриЗаписи", "ПриОткрытии", "Сложить"]


def test_оглавление_знает_экспортность_и_границы(корень_кода):
    о = Оглавление.построить(корень_кода)
    сложить = о.по_имени("сложить")[0]
    assert сложить.экспорт is True
    assert сложить.модуль == "ОбщийМодуль.ОбщийПример"
    assert сложить.строка == 2 and сложить.конец == 4


def test_оглавление_модуля_отдаёт_и_неэкспортные(корень_кода):
    о = Оглавление.построить(корень_кода)
    имена = sorted(з.имя for з in о.модуля("ОбщийМодуль.ОбщийПример"))
    assert имена == ["Внутренняя", "Сложить"]


def test_оглавление_переживает_запись_и_подъём(корень_кода, tmp_path):
    файл = tmp_path / "toc.marshal"
    Оглавление.построить(корень_кода).записать(файл)
    поднятое = Оглавление.прочитать(файл)
    assert поднятое.по_имени("призаписи")[0].модуль == "Документ.Пример.МодульОбъекта"


def test_оглавление_различает_процедуру_и_функцию(корень_кода, tmp_path):
    """Вид — бит в тех же флагах (ФУНКЦИЯ), не отдельный массив; обязан
    пережить запись и подъём наравне с экспортностью и границами."""
    о = Оглавление.построить(корень_кода)
    сложить = о.по_имени("сложить")[0]        # Функция Сложить(...)
    внутренняя = о.по_имени("внутренняя")[0]  # Процедура Внутренняя()
    assert сложить.функция is True
    assert внутренняя.функция is False

    файл = tmp_path / "toc.marshal"
    о.записать(файл)
    поднятое = Оглавление.прочитать(файл)
    assert поднятое.по_имени("сложить")[0].функция is True
    assert поднятое.по_имени("внутренняя")[0].функция is False


def test_одноимённые_в_разных_модулях_живут_обе(tmp_path):
    """Ключ — пара «модуль + имя»: ПриСозданииНаСервере объявлена в 3 003
    модулях живой конфигурации."""
    for имя in ("Первый", "Второй"):
        каталог = tmp_path / "CommonModules" / имя / "Ext"
        каталог.mkdir(parents=True)
        (каталог / "Module.bsl").write_text(
            "Процедура Общая() Экспорт\nКонецПроцедуры\n", encoding="utf-8"
        )
    о = Оглавление.построить(tmp_path)
    модули = sorted(з.модуль for з in о.по_имени("общая"))
    assert модули == ["ОбщийМодуль.Второй", "ОбщийМодуль.Первый"]


def test_квалифицированный_вызов_разрешается_до_модуля(корень_кода):
    о = Оглавление.построить(корень_кода)
    в = Вызовы.построить(корень_кода, о)
    места = [м for м in в.места("сложить") if м.модуль == "Документ.Пример.МодульОбъекта"]
    assert места[0].цель == "ОбщийМодуль.ОбщийПример"


def test_вызов_внутри_своего_модуля_разрешается(корень_кода):
    о = Оглавление.построить(корень_кода)
    в = Вызовы.построить(корень_кода, о)
    свои = [м for м in в.места("сложить") if м.модуль == "ОбщийМодуль.ОбщийПример"]
    assert свои[0].цель == "ОбщийМодуль.ОбщийПример"


def test_неизвестное_имя_не_индексируется(корень_кода):
    """Платформенные методы целями не бывают: без фильтра рёбер на 63% больше."""
    о = Оглавление.построить(корень_кода)
    в = Вызовы.построить(корень_кода, о)
    assert в.места("значениезаполнено") == []


def test_неразрешённый_вызов_помечен(tmp_path):
    каталог = tmp_path / "CommonModules" / "Первый" / "Ext"
    каталог.mkdir(parents=True)
    (каталог / "Module.bsl").write_text(
        "Процедура Общая() Экспорт\nКонецПроцедуры\n"
        "Процедура Зовущая()\n\tОбъект.Общая();\nКонецПроцедуры\n",
        encoding="utf-8",
    )
    о = Оглавление.построить(tmp_path)
    в = Вызовы.построить(tmp_path, о)
    места = [м for м in в.места("общая") if м.строка == 4]
    assert места[0].цель is None


def test_вызов_платформенного_метода_не_создаёт_ребро(tmp_path):
    """Дополнение к тесту брифа: `корень_кода` не содержит вызова
    незнакомого имени, и `test_неизвестное_имя_не_индексируется` на нём
    зелен даже с отключённым фильтром — не доказательство. Здесь имя
    вызывается по-настоящему, и фильтр обязан не завести ребро вовсе, а не
    оставить его неразрешённым (докстрока класса: без фильтра рёбер на
    63% больше)."""
    каталог = tmp_path / "CommonModules" / "Первый" / "Ext"
    каталог.mkdir(parents=True)
    (каталог / "Module.bsl").write_text(
        "Процедура Общая() Экспорт\n\tЗначениеЗаполнено(1);\nКонецПроцедуры\n",
        encoding="utf-8",
    )
    о = Оглавление.построить(tmp_path)
    в = Вызовы.построить(tmp_path, о)
    assert в.места("значениезаполнено") == []
    assert в.рёбер == 0
