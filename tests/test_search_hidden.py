"""Что поиск отвечает, когда фильтр версии убрал всё.

«Ничего не найдено» и «есть, но не в вашей версии» — противоположные ответы.
Первый отправляет агента искать опечатку в имени, второй — обновлять платформу
или брать замену. Спутать их дороже, чем промолчать.
"""

from __future__ import annotations

from mcp1c.syntax_model import SyntaxItem
from mcp1c.tools import get_syntax, search_syntax

from conftest import build_syntax_registry


def test_всё_скрытое_по_версии_не_выдаётся_за_ненайденное(tmp_path):
    """Воспроизведено на живой справке 2026-08-17.

    Запрос «ПолучитьБуферДвоичныхДанных» под отраслевой (8.3.5) отвечал «ничего
    не найдено», хотя `РезультатЧтенияДанных.ПолучитьБуферДвоичныхДанных`
    существует и появился в 8.3.9.
    """
    registry = build_syntax_registry(
        tmp_path,
        [
            SyntaxItem(
                id="obj/РезультатЧтенияДанных/ПолучитьБуферДвоичныхДанных",
                kind="method",
                name_ru="ПолучитьБуферДвоичныхДанных",
                parent_ru="РезультатЧтенияДанных",
                description="Возвращает буфер двоичных данных",
                since="8.3.9",
            )
        ],
        "8.3.5.1570",
    )

    ответ = search_syntax(registry, "ПолучитьБуферДвоичныхДанных")

    assert "ничего не найдено" not in ответ
    assert "ПолучитьБуферДвоичныхДанных" in ответ
    assert "8.3.9" in ответ


def test_когда_скрывать_нечего_ответ_прежний(tmp_path):
    """Настоящая пустота остаётся пустотой — выдумывать причину нельзя."""
    registry = build_syntax_registry(
        tmp_path,
        [
            SyntaxItem(
                id="ctx/СтрДлина",
                kind="method",
                name_ru="СтрДлина",
                description="Возвращает длину строки",
            )
        ],
        "8.3.5.1570",
    )

    ответ = search_syntax(registry, "рекламация поставщику")

    assert "ничего не найдено" in ответ


def test_скрытое_потому_что_удалено_тоже_называется(tmp_path):
    """Причины две, и обе должны доходить, а не только «появился позже»."""
    registry = build_syntax_registry(
        tmp_path,
        [
            SyntaxItem(
                id="obj/Старьё/ЗагрузитьИзФайла",
                kind="method",
                name_ru="ЗагрузитьИзФайла",
                parent_ru="Старьё",
                description="Загружает данные из файла",
                until="8.3.4",
            )
        ],
        "8.3.5.1570",
    )

    ответ = search_syntax(registry, "ЗагрузитьИзФайла")

    assert "ничего не найдено" not in ответ
    assert "8.3.4" in ответ


def test_подсказки_называют_похожее_из_других_версий(tmp_path):
    """Опечатка в имени нового метода не должна выглядеть как «такого нет».

    Воспроизведено на живой справке 2026-08-17: `get_syntax` на
    «БуферДвоичныхДанных.ЗаписатьВФайлик» под отраслевой отвечал «нет элемента»,
    хотя `БуферДвоичныхДанных.Записать` существует с 8.3.9. Кандидаты
    отсеивались фильтром версии до проверки на пустоту, и подсказок не
    оставалось — притом что для старого элемента та же опечатка их даёт.
    """
    registry = build_syntax_registry(
        tmp_path,
        [
            SyntaxItem(
                id="obj/БуферДвоичныхДанных/Записать",
                kind="method",
                name_ru="Записать",
                parent_ru="БуферДвоичныхДанных",
                description="Записывает данные в буфер",
                since="8.3.9",
            )
        ],
        "8.3.5.1570",
    )

    ответ = get_syntax(registry, "БуферДвоичныхДанных.ЗаписатьВФайлик")

    assert "8.3.9" in ответ
    assert "БуферДвоичныхДанных.Записать" in ответ


def test_подсказки_не_умалчивают_о_скрытом_рядом_с_доступным(tmp_path):
    """Часть подсказок доступна, часть скрыта — сказать надо про обе."""
    registry = build_syntax_registry(
        tmp_path,
        [
            SyntaxItem(
                id="ctx/СтрЗаменить",
                kind="method",
                name_ru="СтрЗаменить",
                description="Заменяет подстроку",
            ),
            SyntaxItem(
                id="ctx/СтрЗаменитьВсе",
                kind="method",
                name_ru="СтрЗаменитьВсе",
                description="Заменяет подстроку целиком",
                since="8.3.20",
            ),
        ],
        "8.3.5.1570",
    )

    ответ = get_syntax(registry, "СтрЗаменитьЧастично")

    assert "СтрЗаменить" in ответ
    assert "8.3.20" in ответ


def test_cli_называет_скрытое_по_версии(tmp_path, capsys):
    """Отладочный CLI печатал пустоту — тот же ложный вывод, но человеку.

    Он живёт внутри контейнера и им разбирают, почему поиск ведёт себя так;
    молчание здесь стоит дороже обычного, потому что разбор начинается именно
    с него.
    """
    from mcp1c.cli import main

    build_syntax_registry(
        tmp_path,
        [
            SyntaxItem(
                id="obj/РезультатЧтенияДанных/ПолучитьБуферДвоичныхДанных",
                kind="method",
                name_ru="ПолучитьБуферДвоичныхДанных",
                parent_ru="РезультатЧтенияДанных",
                description="Возвращает буфер двоичных данных",
                since="8.3.9",
            )
        ],
        "8.3.5.1570",
    )

    код = main(
        [
            "reg-search",
            "ПолучитьБуферДвоичныхДанных",
            "--syntax",
            "--config",
            "ТестоваяКонфигурация",
            "--data",
            str(tmp_path / "data"),
        ]
    )
    вывод = capsys.readouterr().out

    assert код == 0
    assert "скрыто" in вывод
    assert "8.3.9" in вывод
