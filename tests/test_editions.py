"""Редакция конфигурации: первые две числовые части версии."""

from __future__ import annotations

import pytest

from mcp1c.editions import edition, edition_conflict


@pytest.mark.parametrize(
    ("версия", "ожидается"),
    [
        ("2.3.26.24", (2, 3)),
        ("3.0.14.178", (3, 0)),
        ("2.3", (2, 3)),
        ("10.5.1.3", (10, 5)),
        (" 2.3.1 ", (2, 3)),
        ("", None),
        ("  ", None),
        ("20080620(0935)", None),
        ("2", None),
        ("a.b", None),
        ("v2.3.1", None),
        ("٢.٣.١", None),
    ],
    ids=[
        "четыре_части", "ноль_во_второй", "две_части", "двузначная",
        "пробелы_по_краям", "пусто", "пробелы", "дата_со_скобками",
        "одно_число", "буквы", "префикс_v", "не_ascii_цифры",
    ],
)
def test_edition(версия, ожидается):
    assert edition(версия) == ожидается


@pytest.mark.parametrize(
    ("текущая", "новая"),
    [
        ("2.3.26.24", "2.3.27.1"),
        ("", ""),
        ("20080620(0935)", "20090101(1000)"),
        ("2.3", "2.3.1.1"),
    ],
    ids=["та_же_редакция", "обе_пустые", "обе_не_номерные", "две_части_и_четыре"],
)
def test_обновление_разрешено(текущая, новая):
    assert edition_conflict("Розница", текущая, новая) == ""


@pytest.mark.parametrize(
    ("текущая", "новая", "фрагменты"),
    [
        ("2.3.26.24", "3.0.14.178", ["редакции 2.3", "редакции 3.0"]),
        ("3.0.14.178", "2.3.26.24", ["редакции 3.0", "редакции 2.3"]),
        ("2.3", "3.0", ["редакции 2.3", "редакции 3.0"]),
        ("2.3.1.1", "", ["редакции 2.3", "без версии"]),
        (
            "2.3.1.1",
            "20080620(0935)",
            ["редакции 2.3", "без номера редакции (20080620(0935))"],
        ),
        ("2.3.1.1", "2.4.1.1", ["редакции 2.3", "редакции 2.4"]),
    ],
    ids=[
        "повышение", "понижение", "две_части", "номерная_в_пустую",
        "номерная_в_не_номерную", "смена_второй_части",
    ],
)
def test_обновление_запрещено_и_причина_называет_обе_редакции(
    текущая, новая, фрагменты
):
    reason = edition_conflict("Розница", текущая, новая)

    assert "«Розница»" in reason
    for фрагмент in фрагменты:
        assert фрагмент in reason
    assert "удалите загруженную конфигурацию" in reason
    assert "как новую" in reason




def test_edition_не_бросает_на_пяти_тысячах_цифр_версии():
    assert edition("9" * 5000 + ".1") is None


@pytest.mark.parametrize(
    ('current', 'incoming', 'conflict'),
    [
        ('', '1.0.0.1', False),
        ('1.0.0.1', '', True),
        ('2.3.26.24', '3.0.14.178', True),
        ('20080620(0935)', '1.0.0.1', True),
    ],
    ids=['empty-to-numbered', 'numbered-to-empty', 'different-editions', 'calendar-to-numbered'],
)
def test_назначение_версии_не_снимает_защиту_других_редакций(current, incoming, conflict):
    reason = edition_conflict('СинтетическаяКонфигурация', current, incoming)
    assert bool(reason) is conflict
    if conflict:
        assert 'удалите загруженную конфигурацию' in reason


@pytest.mark.parametrize(
    "version,expected",
    [
        ("123456789.1", (123456789, 1)),
        ("1.123456789.5", (1, 123456789)),
        ("1234567890.1", None),
        ("1.1234567890", None),
    ],
)
def test_m11_граница_девять_цифр_в_компоненте_редакции(version, expected):
    # С L2 компонента длиннее девяти цифр не номер редакции: без предела
    # огромное число давало необработанный ValueError в int().
    assert edition(version) == expected
