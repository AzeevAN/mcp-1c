"""Живой прогон самого приёма — не оценка по центральному каталогу, а вызов
того же кода, что стоит за кнопкой «разобрать» на странице «Источники».

`measure_intake.py` (рядом) считает, что БУДЕТ отобрано, по одним лишь именам
и размерам из центрального каталога zip. Этот скрипт идёт дальше: реально
зовёт `intake.planned_size`, `intake.enough_space` и `intake.extract` — то
есть измеряет время и память, которых стоит сам процесс, а не то, что он
предсказывает. Тела архивов запускать в CI незачем — гигабайтных выгрузок в
репозитории нет и не будет (`AGENTS.md`, «Данные»); скрипт существует для
ручного прогона на своих файлах и умрёт вместе с появлением провайдера
`modules`, как и его соседи по `tools/lab/`.

Запуск: python3 tools/lab/measure_intake_run.py <каталог для распаковки> <архив.zip> [ещё .zip]

Каталог распаковки — рабочая директория для реально извлечённых файлов,
по одной подпапке на архив (по имени архива без расширения). Держите его
ВНЕ репозитория и вне `data/`: это чужой код конкретного внедрения, а не то,
что должно провалиться в git по забывчивости. Скрипт убирает распакованное
за собой в `finally` — если он упал на середине, `du -sh` по каталогу
распаковки покажет, что осталось, и это стоит убрать руками.
"""
from __future__ import annotations

import resource
import shutil
import sys
import time
from pathlib import Path

sys.path.insert(0, "src")
from mcp1c import intake  # noqa: E402

# `ru_maxrss` меряет разное на разных платформах: на macOS — байты, на
# Linux — килобайты. Переводим сразу в МБ одним делением каждый раз.
_ДЕЛИТЕЛЬ_МБ = 1024 * 1024 if sys.platform == "darwin" else 1024


def _пик_мб() -> float:
    return resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / _ДЕЛИТЕЛЬ_МБ


def _на_диске(корень: Path) -> tuple[int, int]:
    """Что реально лежит после распаковки: файлов и байт, без учёта каталогов."""
    файлов = 0
    байт = 0
    for путь in корень.rglob("*"):
        if путь.is_file():
            файлов += 1
            байт += путь.stat().st_size
    return файлов, байт


def прогон(архив: Path, рабочий_каталог: Path) -> None:
    корень = рабочий_каталог / архив.stem
    мб = lambda b: b / 2**20

    print(f"\n=== {архив.name} ===")

    начало = time.monotonic()
    нужно, формат = intake.planned_size(архив)
    оценка_с = time.monotonic() - начало
    хватает, свободно = intake.enough_space(нужно, рабочий_каталог)

    print(f"  формат              : {формат}")
    print(f"  требуемое место     : {мб(нужно):>8.1f} МБ (с запасом {мб(intake.INDEX_RESERVE):.0f} МБ под индекс)")
    print(f"  оценка места заняла : {оценка_с:>8.3f} с (только центральный каталог zip)")
    print(f"  свободно на месте   : {мб(свободно):>8.0f} МБ, хватает: {хватает}")

    if not хватает:
        print("  ОТКАЗ: места не хватает, распаковка не запускается.")
        return

    rss_до = _пик_мб()
    начало = time.monotonic()
    try:
        файлов_возврат, байт_возврат = intake.extract(архив, корень)
        распаковка_с = time.monotonic() - начало
        rss_после = _пик_мб()

        файлов_диск, байт_диск = _на_диске(корень)

        print(f"  распаковка заняла   : {распаковка_с:>8.3f} с")
        print(f"  пик RSS процесса    : {rss_после:>8.0f} МБ (до распаковки {rss_до:.0f} МБ)")
        print(f"  вернул extract()    : {файлов_возврат:>8} файлов, {мб(байт_возврат):.1f} МБ")
        print(f"  фактически на диске : {файлов_диск:>8} файлов, {мб(байт_диск):.1f} МБ")
        совпало = файлов_возврат == файлов_диск and байт_возврат == байт_диск
        print(f"  цифры совпали       : {совпало}")
    finally:
        # Распакованное — чужой код конкретного внедрения, а не то, что должно
        # пережить прогон разведочного скрипта. Убираем всегда, даже на сбое.
        if корень.exists():
            shutil.rmtree(корень)


def main(argv: list[str]) -> int:
    if len(argv) < 3:
        print(__doc__)
        return 2
    рабочий_каталог = Path(argv[1])
    рабочий_каталог.mkdir(parents=True, exist_ok=True)
    for путь in argv[2:]:
        прогон(Path(путь), рабочий_каталог)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
