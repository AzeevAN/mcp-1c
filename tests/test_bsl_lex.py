def test_вызов_первым_токеном_тела_на_строке_объявления():
    """Проверка на Экспорт/КонецПроцедуры сразу после сигнатуры снимает ровно
    одно слово курсором. Если это слово — не ключевое, а первый вызов тела
    в одну строку с объявлением (`Процедура П() Рассчитать(1); КонецПроцедуры`),
    курсор для обычного разбора тела уже ушёл за пределы имени вызова — окно
    между концом сигнатуры и местом, где остановилась проверка, обязано быть
    просмотрено на вызовы отдельно."""
    вызовы = разобрать("Процедура Пример() Рассчитать(1); КонецПроцедуры\n")[0].вызовы
    assert ("", "Рассчитать", 1) in вызовы


def test_шапка_не_переживает_пустую_строку():
    """Пустая строка рвёт цепочку «шапка прямо над объявлением». Без этого
    буфер не сбрасывается (по-настоящему пустая строка не подходит ни под
    «комментарий», ни под «код») и цепляет случайную процедуру к чужой
    шапке — например, заголовок раздела файла или документацию соседней,
    никак не связанной процедуры (около 2 396 таких
    случаев на живом корпусе)."""
    текст = (
        "// Шапка чужой процедуры\n"
        "\n"
        "Процедура БезШапки()\nКонецПроцедуры\n"
    )
    процедура = разобрать(текст)[0]
    assert процедура.шапка == ""


def test_вызовы_не_дублируются_на_строке_объявления():
    """Регресс: окно вызовов на строке объявления сканировалось
    целиком, но курсор для обычного разбора тела возвращался на конец
    ПЕРВОГО снятого идентификатора, а не на конец просканированного окна —
    обычная ветка тела проходила по уже учтённому отрезку заново и
    дублировала все вызовы, кроме первого."""
    вызовы = разобрать(
        "Процедура Пример() Рассчитать(1); Другой(2); КонецПроцедуры\n"
    )[0].вызовы
    assert вызовы.count(("", "Рассчитать", 1)) == 1
    assert вызовы.count(("", "Другой", 1)) == 1


def test_прочитать_модуль_не_путает_одиночный_cr_с_переводом_строки(tmp_path):
    """`Path.read_text()` открывает файл в текстовом режиме с универсальным
    переводом строк и молча превращает одиночный `CR` в `\n` ещё до того,
    как текст дойдёт до `нормализовать()` — правило про одиночный CR
    (покрыто `test_одиночный_cr_не_считается_переводом_строки`) на
    обычном пути чтения файла не срабатывает. `прочитать_модуль` читает
    байтами и декодирует без универсальных переводов строк."""
    путь = tmp_path / "Module.bsl"
    путь.write_bytes("// шапка\rпродолжение\nПроцедура Пример()\nКонецПроцедуры\n".encode("utf-8"))

    через_прочитать_модуль = разобрать(прочитать_модуль(путь))[0]
    через_read_text = разобрать(путь.read_text(encoding="utf-8-sig", errors="replace"))[0]

    assert через_прочитать_модуль.строка == 2
    assert через_read_text.строка != 2
