def test_элемент_появившийся_позже_не_объявляется_удалённым(tmp_path):
    """Элемент жил только в средней справке: появился в 8.3.18, в 8.3.27 его
    уже нет. Для конфигурации 8.3.5 верная причина — «ещё не появился», а не
    «уже удалён»: обновление до 8.3.18 его как раз добавит."""
    incoming = tmp_path / "incoming"
    середина = справка(incoming, "8.3.19.1417", {"МенеджерКриптографии.ПроверитьАсинх": "ПроверитьАсинх(<Данные>)"})
    _проставить_since(середина, "8.3.18")
    registry = реестр(
        tmp_path,
        [
            справка(incoming, "8.3.5.1570", {"Глобальный контекст.Найти": "Найти(<Строка>)"}),
            середина,
            справка(incoming, "8.3.27.2130", {"Глобальный контекст.Найти": "Найти(<Строка>)"}),
        ],
        "8.3.5.1570",
    )

    ответ = get_syntax(registry, "МенеджерКриптографии.ПроверитьАсинх")

    assert "8.3.18" in ответ
    assert "уже нет" not in ответ.lower()
    assert "не существует" not in ответ.lower()


