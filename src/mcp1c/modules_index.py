Прогресс = Callable[[int, int], None]


def _единый_каталог(
    корень: Path, каталог: ModuleCatalog | None
) -> ModuleCatalog:
    """Совместимый прямой вход тестов; production всегда передаёт снимок."""
    if каталог is not None:
        return каталог
    return build_catalog(корень, LocatorIdentity("direct", "direct", 0))


def файлы_оглавления(корень: Path) -> tuple[Path, ...]:
    """Точный детерминированный набор первого этапа индекса."""
    return tuple(
        sorted(
            [
                *корень.rglob("*.bsl"),
                *корень.glob("CommonModules/*.Module"),
                *корень.glob("CommonModule.*.Module"),
            ]
        )
    )


def _сообщить_прогресс(
    callback: Прогресс | None, обработано: int, всего: int
) -> None:
    """Не держит замок реестра на каждом файле большого корпуса.

    На маленькой синтетике сообщается каждый элемент — тест видит настоящий
    N. На живом корпусе достаточно каждого 32-го и последнего: это не меняет
    смысл счётчика, но убирает десятки тысяч межпоточных обновлений.
    """
    if callback is None:
        return
    if всего <= 100 or обработано in (0, всего) or обработано % 32 == 0:
        callback(обработано, всего)


@dataclass(slots=True)
class Запись:
    """Одна процедура оглавления — собирается по запросу из массивов.

    `функция: bool`, а не `вид: str` — тех же двух значений ("процедура" /
    "функция") строкой хотелось избежать намеренно: строка приглашает
    сравнивать её текстом (`з.вид == "Функция"`, регистр не тот — тихая
    ошибка) или, того хуже, выводить вид из имени процедуры вместо этого
    поля. `bool` такого соблазна не оставляет и совпадает по духу с
    остальными флагами записи (`экспорт`, `частичный`). Для аннотации
    расширения одного булева признака недостаточно: `вид_перекрытия` хранит
    одно из четырёх канонических русских значений либо пустую строку.
    """

    модуль: str
    имя: str
    экспорт: bool
    строка: int
    конец: int
    перекрыта: bool
    вид_перекрытия: str
    частичный: bool
    функция: bool
    # Позиция выводится из уже сохранённых параллельных массивов и не меняет
    # формат кэша. Нужна для стабильного сопоставления двух одноимённых
    # объявлений на одной физической строке с одноразовым разбором файла.
    позиция: int = -1


@dataclass(frozen=True, slots=True)
class СводкаОглавления:
    """Агрегаты корпуса без создания ``Запись`` на каждую процедуру."""

    процедур: int
    скомпилированных: int
    собственных: int
    перекрытия: dict[str, int]
    перекрытые_модули: frozenset[str]


class Оглавление:
    """Процедуры корпуса: параллельные массивы, имена интернированы.

    Сигнатура не хранится: она лежит на диске в строке объявления, чтение
    обходится в 0,1 мс на модуль. Хранение стоило бы +66 МБ на конфигурацию.
    """

    __slots__ = (
        "модули", "имена", "_модуль", "_строка", "_конец", "_флаги",
        "_по_имени", "_по_модулю", "_скомпилированные",
    )

    ЭКСПОРТ = 1
    ПЕРЕКРЫТА = 2
    ЧАСТИЧНЫЙ = 4
    ФУНКЦИЯ = 8
    _ПЕРЕКРЫТИЕ_СДВИГ = 4
    _ПЕРЕКРЫТИЯ = {
        "Вместо": 1,
        "Around": 1,
        "После": 2,
        "After": 2,
        "Перед": 3,
        "Before": 3,
        "ИзменениеИКонтроль": 4,
        "ChangeAndValidate": 4,
    }
    _ВИДЫ_ПЕРЕКРЫТИЯ = {
        1: "Вместо",
        2: "После",
        3: "Перед",
        4: "ИзменениеИКонтроль",
    }

    def __init__(
        self,
        модули: list[str],
        имена: list[str],
        _модуль: array,
        _строка: array,
        _конец: array,
        _флаги: array,
        _по_имени: dict[str, array],
        _по_модулю: dict[str, array],
        _скомпилированные: frozenset[str] = frozenset(),
    ) -> None:
        # Приватный конструктор: собирает готовые массивы, ничего не
        # вычисляет. Публичный вход — `построить` (с диска) и `прочитать`
        # (из ранее записанного файла).
        self.модули = модули
        self.имена = имена
        self._модуль = _модуль
        self._строка = _строка
        self._конец = _конец
        self._флаги = _флаги
        self._по_имени = _по_имени
        self._по_модулю = _по_модулю
        self._скомпилированные = _скомпилированные

    @staticmethod
    def _индексы(
        имена: list[str], _модуль: array, модули: list[str]
    ) -> tuple[dict[str, array], dict[str, array]]:
        """Обратные индексы «имя -> позиции» и «модуль -> позиции».

        Строится и после сборки с диска, и после подъёма из файла — на диске
        эти индексы не лежат: они целиком выводятся из `имена`/`_модуль`, а
        хранить производное вторым слоем значило бы удваивать файл ради того,
        что и так пересчитывается за доли секунды одним проходом.
        """
        по_имени: dict[str, array] = {}
        по_модулю: dict[str, array] = {}
        for i, имя in enumerate(имена):
            по_имени.setdefault(имя.lower(), array("i")).append(i)
            по_модулю.setdefault(модули[_модуль[i]], array("i")).append(i)
        return по_имени, по_модулю

    @classmethod
    def построить(
        cls,
        корень: Path,
        *,
        каталог: ModuleCatalog | None = None,
        прогресс: Прогресс | None = None,
    ) -> "Оглавление":
        """Проход по выгрузке: адрес модуля из пути, процедуры — из текста.

        Порядок файлов детерминированный (`sorted`) ради воспроизводимости
        замеров и стабильного порядка индексов между прогонами — само
        оглавление от порядка не зависит.

        `адрес_модуля` не оборачивается в `try`: незнакомый каталог или файл
        выгрузки — честный отказ (см. докстроку `module_address`), а не
        объект, молча пропущенный из оглавления.
        """
        модули: list[str] = []
        индекс_модуля: dict[str, int] = {}
        имена: list[str] = []
        _модуль = array("i")
        _строка = array("i")
        _конец = array("i")
        _флаги = array("i")

        снимок = _единый_каталог(корень, каталог)
        модули_каталога = tuple(
            entry for entry in снимок.entries.values() if entry.locator is not None
        )
        исходные_модули: set[str] = set()
        скомпилированные: set[str] = set()
        _сообщить_прогресс(прогресс, 0, len(модули_каталога))
        for обработано, entry in enumerate(модули_каталога, 1):
            адрес = entry.address
            locator = entry.locator
            assert locator is not None
            if locator.kind == "compiled":
                if адрес not in исходные_модули:
                    скомпилированные.add(адрес)
            else:
                исходные_модули.add(адрес)
                скомпилированные.discard(адрес)
            индекс = индекс_модуля.get(адрес)
            if индекс is None:
                индекс = len(модули)
                модули.append(адрес)
                индекс_модуля[адрес] = индекс

            if locator.kind == "compiled":
                _сообщить_прогресс(
                    прогресс, обработано, len(модули_каталога)
                )
                continue

            for процедура in разобрать(read_bsl(корень, адрес, locator)):
                # Интернируем на записи, не на чтении: одно и то же имя
                # («ПриСозданииНаСервере» — 3 003 раза на живом корпусе)
                # иначе заводило бы отдельный строковый объект на каждое
                # вхождение вместо одного общего.
                имена.append(sys.intern(процедура.имя))
                _модуль.append(индекс)
                _строка.append(процедура.строка)
                _конец.append(процедура.конец)
                флаги = 0
                if процедура.экспорт:
                    флаги |= cls.ЭКСПОРТ
                if процедура.перекрытие:
                    флаги |= cls.ПЕРЕКРЫТА
                    флаги |= (
                        cls._ПЕРЕКРЫТИЯ[процедура.перекрытие[0]]
                        << cls._ПЕРЕКРЫТИЕ_СДВИГ
                    )
                if процедура.частичный:
                    флаги |= cls.ЧАСТИЧНЫЙ
                if процедура.вид == "функция":
                    флаги |= cls.ФУНКЦИЯ
                _флаги.append(флаги)
            _сообщить_прогресс(прогресс, обработано, len(модули_каталога))

        по_имени, по_модулю = cls._индексы(имена, _модуль, модули)
        return cls(
            модули, имена, _модуль, _строка, _конец, _флаги,
            по_имени, по_модулю, frozenset(скомпилированные),
        )

    def _состояние(self) -> dict:
        """Параллельные массивы в виде, годном для `marshal`, — общее тело
        для `записать` (файл напрямую) и `сохранить_индексы` (через кэш
        проекта, со штампом и сжатием).

        Обратные индексы (`по_имени`, `по_модулю`) не входят — они
        производные от `имена`/`_модуль` и пересчитываются на подъёме.
        Массивы идут байтами (`tobytes()`), не списками: `marshal` умеет
        сохранять `array` только как обычную последовательность чисел, а
        это для миллиона элементов дороже и на запись, и на чтение.
        """
        return {
            "модули": self.модули,
            "имена": self.имена,
            "модуль": self._модуль.tobytes(),
            "строка": self._строка.tobytes(),
            "конец": self._конец.tobytes(),
            "флаги": self._флаги.tobytes(),
            "скомпилированные": sorted(self._скомпилированные),
        }

    def записать(self, путь: Path) -> None:
        """Сохраняет параллельные массивы на диск через голый `marshal`,
        без штампа и без сжатия — круг «построить -> записать -> прочитать»
        для тестов и разовой проверки на месте. Постоянное хранение кэша
        проекта — `сохранить_индексы`/`поднять_индексы`, через `index_cache`."""
        путь.write_bytes(marshal.dumps(self._состояние()))

    @classmethod
    def _из_состояния(cls, данные: dict) -> "Оглавление":
        """Собирает оглавление из словаря `_состояние` — общее тело для
        `прочитать` и `поднять_индексы`.

        Массивы поднимаются `frombytes()` напрямую в пустой `array('i')`,
        без промежуточного `list` — см. докстроку модуля про 97 МБ вместо 62.
        """
        _модуль = array("i")
        _модуль.frombytes(данные["модуль"])
        _строка = array("i")
        _строка.frombytes(данные["строка"])
        _конец = array("i")
        _конец.frombytes(данные["конец"])
        _флаги = array("i")
        _флаги.frombytes(данные["флаги"])

        модули = данные["модули"]
        имена = данные["имена"]
        if (
            not isinstance(модули, list)
            or not isinstance(имена, list)
            or any(not isinstance(item, str) or not item for item in модули)
            or any(not isinstance(item, str) or not item for item in имена)
            or len(set(модули)) != len(модули)
            or len({_key.casefold() for _key in модули}) != len(модули)
        ):
            raise ValueError("некорректная таблица модулей оглавления")
        записей = len(имена)
        if any(
            len(values) != записей
            for values in (_модуль, _строка, _конец, _флаги)
        ):
            raise ValueError("параллельные массивы оглавления расходятся")
        if any(index < 0 or index >= len(модули) for index in _модуль):
            raise ValueError("индекс модуля оглавления вне таблицы")
        if any(line < 1 for line in _строка) or any(
            end < line for line, end in zip(_строка, _конец)
        ):
            raise ValueError("границы процедуры оглавления некорректны")
        допустимые_младшие = (
            cls.ЭКСПОРТ | cls.ПЕРЕКРЫТА | cls.ЧАСТИЧНЫЙ | cls.ФУНКЦИЯ
        )
        допустимая_маска = допустимые_младшие | (0b111 << cls._ПЕРЕКРЫТИЕ_СДВИГ)
        for флаг in _флаги:
            код_перекрытия = флаг >> cls._ПЕРЕКРЫТИЕ_СДВИГ & 0b111
            if (
                флаг < 0
                or флаг & ~допустимая_маска
                or код_перекрытия not in {0, *cls._ВИДЫ_ПЕРЕКРЫТИЯ}
                or bool(флаг & cls.ПЕРЕКРЫТА) != bool(код_перекрытия)
            ):
                raise ValueError("флаги процедуры оглавления некорректны")
        скомпилированные = данные.get("скомпилированные", ())
        if (
            not isinstance(скомпилированные, (list, tuple))
            or any(not isinstance(item, str) for item in скомпилированные)
            or not set(скомпилированные).issubset(модули)
        ):
            raise ValueError("таблица скомпилированных модулей некорректна")
        по_имени, по_модулю = cls._индексы(имена, _модуль, модули)
        return cls(
            модули, имена, _модуль, _строка, _конец, _флаги,
            по_имени, по_модулю,
            frozenset(скомпилированные),
        )

    @classmethod
    def прочитать(cls, путь: Path) -> "Оглавление":
        """Поднимает оглавление из файла `записать`."""
        return cls._из_состояния(marshal.loads(путь.read_bytes()))

    def _запись(self, i: int) -> Запись:
        флаги = self._флаги[i]
        return Запись(
            модуль=self.модули[self._модуль[i]],
            имя=self.имена[i],
            экспорт=bool(флаги & self.ЭКСПОРТ),
            строка=self._строка[i],
            конец=self._конец[i],
            перекрыта=bool(флаги & self.ПЕРЕКРЫТА),
            вид_перекрытия=self._ВИДЫ_ПЕРЕКРЫТИЯ.get(
                флаги >> self._ПЕРЕКРЫТИЕ_СДВИГ & 0b111, ""
            ),
            частичный=bool(флаги & self.ЧАСТИЧНЫЙ),
            функция=bool(флаги & self.ФУНКЦИЯ),
            позиция=i,
        )

    def все(self) -> list[Запись]:
        """Все процедуры корпуса — для полного прохода (сборка других индексов)."""
        return [self._запись(i) for i in range(len(self.имена))]

    def сводка(self) -> СводкаОглавления:
        """Счётчики перекрытий напрямую по плоским массивам.

        Сводка расширения нужна на первом шаге работы, но полный корпус может
        содержать сотни тысяч процедур. Здесь создаются только четыре
        счётчика и множество затронутых модулей, а не список ``Запись``.
        """
        перекрытия = {
            "Вместо": 0,
            "После": 0,
            "Перед": 0,
            "ИзменениеИКонтроль": 0,
        }
        перекрытые_модули: set[str] = set()
        собственных = 0
        for i, флаги in enumerate(self._флаги):
            код = флаги >> self._ПЕРЕКРЫТИЕ_СДВИГ & 0b111
            вид = self._ВИДЫ_ПЕРЕКРЫТИЯ.get(код)
            if вид is None:
                собственных += 1
                continue
            перекрытия[вид] += 1
            перекрытые_модули.add(self.модули[self._модуль[i]])
        return СводкаОглавления(
            процедур=len(self.имена),
            скомпилированных=len(self._скомпилированные),
            собственных=собственных,
            перекрытия=перекрытия,
            перекрытые_модули=frozenset(перекрытые_модули),
        )

    def покрытие_процедур(self) -> tuple[int, int, frozenset[str]]:
        """Всего, частичных и модули с оборванным разбором без объектов строк."""
        частичных = 0
        модули: set[str] = set()
        for i, флаги in enumerate(self._флаги):
            if флаги & self.ЧАСТИЧНЫЙ:
                частичных += 1
                модули.add(self.модули[self._модуль[i]])
        return len(self.имена), частичных, frozenset(модули)

    def скомпилирован(self, адрес: str) -> bool:
        """У модуля есть только платформенный образ, исходного текста нет."""
        return адрес in self._скомпилированные

    def по_имени(self, имя: str) -> list[Запись]:
        """Все процедуры с этим именем во всех модулях, без учёта регистра.

        Может вернуть несколько записей — ключ оглавления «модуль + имя»,
        не одно имя (докстрока модуля).
        """
        return [self._запись(i) for i in self._по_имени.get(имя.lower(), ())]

    def модуля(self, адрес: str) -> list[Запись]:
        """Все процедуры модуля, включая неэкспортные."""
        return [self._запись(i) for i in self._по_модулю.get(адрес, ())]

    def известно(self, имя: str) -> bool:
        """Объявлена ли хоть одна процедура с этим именем где-либо в корпусе.

        Дешёвый сторож для `Вызовы.построить`:
        на живом корпусе кандидатов в вызовы около миллиона, и строить на
        каждом `Запись`-объекты через `по_имени` только ради проверки
        «есть или нет» значило бы платить за то, что тут же выбрасывается.
        Словарь `_по_имени` для этого и существует.
        """
        return имя.lower() in self._по_имени


@dataclass(slots=True)
class Место:
    """Одно место вызова — модуль-вызыватель, строка и, если удалось
    разрешить, адрес модуля-цели."""

    модуль: str
    строка: int
    цель: str | None


@dataclass(slots=True)
class ВыборМест:
    """Ограниченный срез обратных вызовов с точными общими счётчиками."""

    подтверждённые: list[Место]
    подтверждённых_всего: int
    неразрешённые: list[Место]
    неразрешённых_всего: int
    пропущено_в_модулях: int


class Вызовы:
    """Индекс вызовов корпуса: «кто вызывает эту процедуру», с разрешением
    цели до модуля там, где это возможно (design doc, раздел 4).

    **Ключ по одному имени врёт.** `ПриСозданииНаСервере` объявлена в
    3 003 модулях живой конфигурации — агент, спросивший «кто вызывает мою
    процедуру» и получивший ответ по имени, получит два десятка чужих
    мест и либо решит, что правка задевает пол-конфигурации, либо, что
    хуже, не увидит настоящего вызывающего среди них и сделает вывод
    «никто не вызывает, менять безопасно». Поэтому ребро несёт третье
    поле — индекс модуля-цели или −1, а не только имя.

    Разрешается только то, в чём мы уверены (`_разрешить`):
    квалифицированный вызов `Х.Метод(`, где `Х` — имя общего модуля
    корпуса, и неквалифицированный вызов, чьё имя объявлено в самом
    модуле-вызывателе. Остальное остаётся −1 и честно называется в ответе
    и отдельно называется в публичном ответе — подставлять «похоже, это оно» здесь так же
    неуместно, как и в `module_address`.

    **Фильтр «имя объявлено где-то в корпусе».** Вызов платформенного
    метода (`ЗначениеЗаполнено`, `Сообщить`) целью быть не может — ни один
    модуль корпуса такое имя не объявляет — и такое ребро не индексируется
    вовсе, а не заводится неразрешённым: без фильтра рёбер на 63% больше
    (1 009 479 против 619 030 на живой выгрузке), и все они бесполезны.

    **Хранение — `имя цели -> array('i')` плоских троек** «модуль-вызыватель,
    строка, модуль-цель или −1» на ключ, без объекта на ребро. Группировка
    по имени уже есть на этапе сборки — `места(имя)` для этого и вызывается
    — так что отдельного параллельного массива с именем на каждое ребро
    (619 030 интернированных ссылок) заводить незачем: имя один раз лежит
    ключом словаря, а не миллион раз копией указателя. Замер живой
    выгрузки: 619 030 рёбер, 52% разрешено, 51 МБ при подъёме.
    """

    __slots__ = ("модули", "_по_имени", "рёбер", "разрешённых")

    def __init__(
        self,
        модули: list[str],
        _по_имени: dict[str, array],
        рёбер: int,
        разрешённых: int,
    ) -> None:
        # Приватный конструктор, как у Оглавление: собирает готовые данные,
        # ничего не вычисляет. Публичный вход — `построить` и `прочитать`.
        self.модули = модули
        self._по_имени = _по_имени
        self.рёбер = рёбер
        self.разрешённых = разрешённых

    @staticmethod
    def _общие_модули(оглавление: "Оглавление") -> dict[str, int]:
        """Имя общего модуля (без вида) -> его индекс в списке модулей корпуса.

        Разрешаются только квалифицированные вызовы к ОБЩИМ модулям: у
        остальных видов квалификатор перед вызовом — это имя переменной
        объекта (`Объект.Общая()`), а не имя типа, и совпадение с адресом
        модуля там ничего не доказывает — ровно та подстановка, от которой
        уходит разрешение до модуля.
        """
        return {
            адрес.split(".", 1)[1].lower(): i
            for i, адрес in enumerate(оглавление.модули)
            if адрес.startswith("ОбщийМодуль.")
            and not оглавление.скомпилирован(адрес)
        }

    @staticmethod
    def _разрешить(
        квалификатор: str, имя: str, модуль: int,
        общие: dict[str, int], свои: set[str],
    ) -> int:
        """Индекс модуля-цели или −1.

        Разрешаем только то, в чём уверены: остальное честно помечается в
        ответе. Ключ по одному имени врал бы — `ПриСозданииНаСервере`
        объявлена в 3 003 модулях живой конфигурации.

        `@staticmethod`, а не метод экземпляра: вызывается из `построить` до того, как
        экземпляр `Вызовы` собран — `self` тут неоткуда взять, а тело и
        так не трогает состояние объекта.
        """
        if квалификатор:
            return общие.get(квалификатор.lower(), -1)
        return модуль if имя in свои else -1

    @classmethod
    def построить(
        cls,
        корень: Path,
        оглавление: "Оглавление",
        *,
        каталог: ModuleCatalog | None = None,
        прогресс: Прогресс | None = None,
    ) -> "Вызовы":
        """Второй проход по выгрузке: места вызова из `Процедура.вызовы`,
        которых оглавление не хранит (оно помнит только границы объявлений).

        `оглавление` принимается готовым, а не строится заново: `известно`
        (фильтр по корпусу) и список объявленных в модуле имён (для «своих»
        неквалифицированных вызовов) — это уже посчитанный проходом оглавления
        ответ, и второй полный обход исходников ради тех же чисел был бы
        пустой тратой времени сборки.
        """
        адрес_к_индексу = {адрес: i for i, адрес in enumerate(оглавление.модули)}
        общие = cls._общие_модули(оглавление)

        _по_имени: dict[str, array] = {}
        рёбер = 0
        разрешённых = 0

        снимок = _единый_каталог(корень, каталог)
        модули_каталога = tuple(
            entry
            for entry in снимок.entries.values()
            if entry.locator is not None
            and entry.locator.kind != "compiled"
            and entry.address in адрес_к_индексу
        )
        _сообщить_прогресс(прогресс, 0, len(модули_каталога))
        for обработано, entry in enumerate(модули_каталога, 1):
            адрес = entry.address
            индекс_модуля = адрес_к_индексу[адрес]
            # Имена, объявленные в ЭТОМ модуле — для неквалифицированных
            # вызовов (`_разрешить`). Не только имя самой вызывающей
            # процедуры: любая процедура модуля годится целью, так что
            # набор строится по всему модулю разом, один раз на файл.
            свои = {
                оглавление.имена[i].lower()
                for i in оглавление._по_модулю.get(адрес, ())
            }

            assert entry.locator is not None
            for процедура in разобрать(
                read_bsl(корень, адрес, entry.locator)
            ):
                for квалификатор, имя, строка in процедура.вызовы:
                    # Платформенный метод корпусом не объявлен нигде — не
                    # индексируем вовсе (докстрока класса, 63%).
                    if not оглавление.известно(имя):
                        continue
                    ключ = имя.lower()
                    цель = cls._разрешить(
                        квалификатор, ключ, индекс_модуля, общие, свои
                    )
                    массив = _по_имени.get(ключ)
                    if массив is None:
                        массив = array("i")
                        _по_имени[ключ] = массив
                    массив.append(индекс_модуля)
                    массив.append(строка)
                    массив.append(цель)
                    рёбер += 1
                    if цель != -1:
                        разрешённых += 1
            _сообщить_прогресс(прогресс, обработано, len(модули_каталога))

        return cls(оглавление.модули, _по_имени, рёбер, разрешённых)

    def _состояние(self) -> dict:
        """Рёбра в виде, годном для `marshal` — общее тело для `записать`
        и `сохранить_индексы`. Массивы идут байтами (`tobytes()`), не
        списками чисел, дороже на запись и на чтение вдвое-втрое."""
        return {
            "модули": self.модули,
            "по_имени": {имя: массив.tobytes() for имя, массив in self._по_имени.items()},
        }

    def записать(self, путь: Path) -> None:
        """Сохраняет рёбра на диск через голый `marshal`, без штампа и без
        сжатия — круг «построить -> записать -> прочитать» для тестов.
        Постоянное хранение кэша проекта — `сохранить_индексы`/
        `поднять_индексы`, через `index_cache`."""
        путь.write_bytes(marshal.dumps(self._состояние()))

    @classmethod
    def _из_состояния(cls, данные: dict) -> "Вызовы":
        """Собирает индекс вызовов из словаря `_состояние` — общее тело для
        `прочитать` и `поднять_индексы`.

        Оглавление сюда не нужно: адреса модулей и уже разрешённые цели
        лежат в самих данных, второй проход по исходникам не требуется.
        Массивы поднимаются `frombytes()` напрямую в пустой `array('i')`,
        без промежуточного `list` — см. докстроку модуля.
        """
        _по_имени: dict[str, array] = {}
        рёбер = 0
        разрешённых = 0
        модули = данные["модули"]
        по_имени = данные["по_имени"]
        if (
            not isinstance(модули, list)
            or any(not isinstance(item, str) or not item for item in модули)
            or len(set(модули)) != len(модули)
            or not isinstance(по_имени, dict)
            or any(
                not isinstance(key, str) or not key or key != key.lower()
                for key in по_имени
            )
            or len({key.casefold() for key in по_имени}) != len(по_имени)
        ):
            raise ValueError("таблица модулей вызовов некорректна")
        for имя, байты in по_имени.items():
            if not isinstance(имя, str) or not имя or not isinstance(байты, bytes):
                raise ValueError("постинг вызовов имеет неверный тип")
            массив = array("i")
            массив.frombytes(байты)
            if len(массив) % 3:
                raise ValueError("постинг вызовов не разбивается на тройки")
            for i in range(0, len(массив), 3):
                модуль, строка, цель = массив[i : i + 3]
                if (
                    модуль < 0
                    or модуль >= len(модули)
                    or строка < 1
                    or цель < -1
                    or цель >= len(модули)
                ):
                    raise ValueError("постинг вызовов ссылается вне таблицы")
            _по_имени[имя] = массив
            for i in range(2, len(массив), 3):
                рёбер += 1
                if массив[i] != -1:
                    разрешённых += 1

        return cls(модули, _по_имени, рёбер, разрешённых)

    @classmethod
    def прочитать(cls, путь: Path) -> "Вызовы":
        """Поднимает индекс вызовов из файла `записать`."""
        return cls._из_состояния(marshal.loads(путь.read_bytes()))

    def _место(self, модуль: int, строка: int, цель: int) -> Место:
        return Место(
            модуль=self.модули[модуль],
            строка=строка,
            цель=self.модули[цель] if цель != -1 else None,
        )

    def места(self, имя: str) -> list[Место]:
        """Все места вызова процедуры с этим именем, без учёта регистра.

        `цель` заполнена только там, где источник надёжен (докстрока
        класса и `_разрешить`); иначе — `None`, а не имя, угаданное по
        совпадению.
        """
        массив = self._по_имени.get(имя.lower())
        if массив is None:
            return []
        return [
            self._место(массив[i], массив[i + 1], массив[i + 2])
            for i in range(0, len(массив), 3)
        ]

    def выбрать(self, имя: str, цель: str, *, limit: int) -> ВыборМест:
        """Один проход по рёбрам без материализации полного списка мест.

        Для ответа нужны точные счётчики, но показывается не больше ``limit``
        подтверждённых и столько же неразрешённых кандидатов. Поэтому в ходе
        прохода сохраняются только лучшие по стабильному порядку элементы;
        объекты ``Место`` создаются уже для итогового ограниченного среза.
        """
        массив = self._по_имени.get(имя.lower())
        if массив is None:
            return ВыборМест([], 0, [], 0, 0)

        предел = max(0, limit)
        target_indexes = {
            i for i, модуль in enumerate(self.модули)
            if модуль.casefold() == цель.casefold()
        }
        подтверждённые: list[tuple[tuple, int, int, int]] = []
        неразрешённые: list[tuple[tuple, int, int, int]] = []
        по_модулям: dict[int, int] = {}
        confirmed_total = 0
        unresolved_total = 0

        for последовательность, i in enumerate(range(0, len(массив), 3)):
            модуль, строка, target = массив[i], массив[i + 1], массив[i + 2]
            ключ = (
                self.модули[модуль].casefold(),
                self.модули[модуль],
                строка,
                последовательность,
            )
            if target in target_indexes:
                confirmed_total += 1
                по_модулям[модуль] = по_модулям.get(модуль, 0) + 1
                if предел:
                    insort(подтверждённые, (ключ, модуль, строка, target))
                    if len(подтверждённые) > предел:
                        подтверждённые.pop()
            elif target == -1:
                unresolved_total += 1
                if предел:
                    insort(неразрешённые, (ключ, модуль, строка, target))
                    if len(неразрешённые) > предел:
                        неразрешённые.pop()

        выбранные_по_модулям: dict[int, int] = {}
        for _, модуль, _, _ in подтверждённые:
            выбранные_по_модулям[модуль] = выбранные_по_модулям.get(модуль, 0) + 1
        omitted_modules = sum(
            1
            for модуль, count in по_модулям.items()
            if count > выбранные_по_модулям.get(модуль, 0)
        )
        return ВыборМест(
            подтверждённые=[
                self._место(модуль, строка, target)
                for _, модуль, строка, target in подтверждённые
            ],
            подтверждённых_всего=confirmed_total,
            неразрешённые=[
                self._место(модуль, строка, target)
                for _, модуль, строка, target in неразрешённые
            ],
            неразрешённых_всего=unresolved_total,
            пропущено_в_модулях=omitted_modules,
        )


# Технические узлы `Form.xml`, которые не считаются элементами формы:
# `Events` — отдельный слой (обработчики, не элементы палитры), а
# `ExtendedTooltip`/`ContextMenu` платформа заводит автоматически на каждый
# интерактивный элемент — это не то, что разработчик сам добавил в форму.
# Замерено на живой выгрузке: без исключения этих трёх узлов дерево несёт
# 244 313 «элементов» вместо 89 528 — почти три четверти были бы чужой
# автогенерацией, а не составом формы.
_НЕ_ЭЛЕМЕНТЫ_ФОРМЫ = frozenset({"Events", "ExtendedTooltip", "ContextMenu"})


def _тег(узел: ET.Element) -> str:
    """Локальное имя тега без пространства имён.

    Настоящий `Form.xml` объявляет полный набор `xmlns` (`xcf/logform` и
    ещё девять служебных), и каждый тег на самом деле выглядит как
    `{http://v8.1c.ru/8.3/xcf/logform}Form`. Синтетические фикстуры тестов
    пространство имён не несут вовсе. Сравнение по тому, что после
    последней `}`, — единственный способ разбирать оба случая одним кодом,
    не заводя раздельных путей для «настоящего» XML и тестового.
    """
    return узел.tag.rsplit("}", 1)[-1]


def _прямой_ребёнок(узел: ET.Element, тег: str) -> ET.Element | None:
    """Первый прямой потомок с данным локальным именем тега, без поиска
    вглубь: `Attributes` и `ChildItems` — оба прямые дети корня `Form`,
    искать их через `.iter()` значило бы сканировать всё дерево ради
    одного узла у самого корня."""
    for ребёнок in узел:
        if _тег(ребёнок) == тег:
            return ребёнок
    return None


def _реквизиты_формы(корень: ET.Element) -> list[str]:
    """Имена реквизитов — прямые дети `<Attributes>`.

    Колонки табличных частей лежат глубже (`Attribute/Columns/Column`) и
    несут другой тег (`Column`, не `Attribute`) — в реквизиты формы не
    попадают: это состав табличной части, а не самой формы. Замерено на
    живой выгрузке: 25 651 реквизит именно на этом правиле.
    """
    узел = _прямой_ребёнок(корень, "Attributes")
    if узел is None:
        return []
    return [
        ребёнок.get("name") for ребёнок in узел
        if _тег(ребёнок) == "Attribute" and ребёнок.get("name") is not None
    ]


def _собрать_элементы(узел: ET.Element, накопитель: list[str]) -> None:
    for ребёнок in узел:
        тег = _тег(ребёнок)
        if тег in _НЕ_ЭЛЕМЕНТЫ_ФОРМЫ:
            continue
        имя = ребёнок.get("name")
        if имя is not None:
            накопитель.append(имя)
        _собрать_элементы(ребёнок, накопитель)


def _элементы_формы(корень: ET.Element) -> list[str]:
    """Имена элементов — всё дерево `<ChildItems>`, включая вложенные
    группы и страницы, но без спуска в технические обвязки
    (`_НЕ_ЭЛЕМЕНТЫ_ФОРМЫ`). Группа сама остаётся элементом — исключены
    только автогенерируемые платформой спутники, не пользовательские
    контейнеры."""
    узел = _прямой_ребёнок(корень, "ChildItems")
    накопитель: list[str] = []
    if узел is not None:
        _собрать_элементы(узел, накопитель)
    return накопитель


def _события_формы(
    корень: ET.Element,
) -> list[tuple[str, str, str | None]]:
    """Процедура, событие и ближайший настоящий элемент-владелец.

    Верхнеуровневый ``Events`` принадлежит самой форме, поэтому владелец там
    ``None``. Внутри ``ChildItems`` владелец меняется только на узле с
    пользовательским ``name``; служебные обёртки и ``Events`` его наследуют.
    Так один обработчик ``OnClick`` на кнопке не превращается в безымянное
    событие формы и не смешивается с таким же событием другого элемента.
    """
    пары: list[tuple[str, str, str | None]] = []

    def события(узел: ET.Element, владелец: str | None) -> None:
        for событие in узел:
            if _тег(событие) != "Event":
                continue
            имя_процедуры = (событие.text or "").strip()
            имя_события = событие.get("name")
            if имя_процедуры and имя_события:
                пары.append((имя_процедуры, имя_события, владелец))

    for ребёнок in корень:
        тег = _тег(ребёнок)
        if тег == "Events":
            события(ребёнок, None)
        elif тег == "ChildItems":
            def обойти(узел: ET.Element, владелец: str | None) -> None:
                for элемент in узел:
                    тег_элемента = _тег(элемент)
                    if тег_элемента in ("ExtendedTooltip", "ContextMenu"):
                        обойти(элемент, владелец)
                        continue
                    if тег_элемента == "Events":
                        события(элемент, владелец)
                        continue
                    следующий = элемент.get("name") or владелец
                    обойти(элемент, следующий)

            обойти(ребёнок, None)
    return пары


def _свойства_дескриптора(
    корень: ET.Element,
) -> tuple[str | None, str | None, str | None, str | None]:
    """UUID, имя, синоним и тип из XML-дескриптора формы.

    Это не позиционные догадки из ``form``: поля подписаны самой XML-схемой.
    Пространства имён у ``MDClasses`` и ``data/core`` различаются между
    обвязками, поэтому, как и для ``Form.xml``, сравниваются локальные имена.
    Первый непустой ``content`` синонима сохраняется без попытки выбрать язык:
    локаль в индексе пока не моделируется, а придумывать приоритет нельзя.
    """
    объект = корень
    if _тег(корень) == "MetaDataObject":
        объект = next(
            (
                ребёнок
                for ребёнок in корень
                if _тег(ребёнок) in {"Form", "CommonForm"}
            ),
            корень,
        )
    свойства = _прямой_ребёнок(объект, "Properties")

    def текст_прямого(имя: str) -> str | None:
        if свойства is None:
            return None
        узел = _прямой_ребёнок(свойства, имя)
        текст = "" if узел is None else (узел.text or "").strip()
        return текст or None

    синоним: str | None = None
    if свойства is not None:
        узел_синонима = _прямой_ребёнок(свойства, "Synonym")
        if узел_синонима is not None:
            синоним = next(
                (
                    (узел.text or "").strip()
                    for узел in узел_синонима.iter()
                    if _тег(узел) == "content" and (узел.text or "").strip()
                ),
                None,
            )
    идентификатор = next(
        (
            значение.strip()
            for имя, значение in объект.attrib.items()
            if имя.rsplit("}", 1)[-1].lower() == "uuid" and значение.strip()
        ),
        None,
    )
    return (
        идентификатор,
        текст_прямого("Name"),
        синоним,
        текст_прямого("FormType"),
    )


