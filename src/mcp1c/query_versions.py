SINCE_8_3_22 = ("UUID",)

# Релиз 8.3.25. Не функция, а конструкция языка: `ДОБАВИТЬ <Имя временной
# таблицы>` — дописать строки в уже существующую временную таблицу.
SINCE_8_3_25 = ("temp_ADD",)

SINCE: dict[str, str] = {
    **{имя.lower(): "8.3.13" for имя in SINCE_8_3_13},
    **{имя.lower(): "8.3.16" for имя in SINCE_8_3_16},
    **{имя.lower(): "8.3.20" for имя in SINCE_8_3_20},
    **{имя.lower(): "8.3.22" for имя in SINCE_8_3_22},
    **{имя.lower(): "8.3.25" for имя in SINCE_8_3_25},
}


def since_for(name_en: str) -> str:
    """Версия появления по английскому имени страницы. Пусто — значит «всегда».

    Пустая строка и есть правильный ответ для большинства: 98 страниц из 127
    были уже в 8.3.5, и фильтровать их не по чему.
    """
    return SINCE.get((name_en or "").strip().lower(), "")
