"""Сверка задачи 9 на живой выгрузке: четыре файла кэша, их размеры, время
полной сборки и время подъёма, поведение при порче файла и при разошедшемся
штампе.

Источник заводится напрямую (`реестр.sources[...] = Source(...)`), не через
`add_modules`: тот копирует 375 МБ кода во временный каталог и требует
привязанную конфигурацию — накладные расходы, которые самому кэшу не
принадлежат и раздули бы время замера тем, что эта задача не меряет.
Сборка структур и запись в кэш идут ровно тем же кодом, что и боевой путь —
`Оглавление.построить`/`Вызовы.построить`/`Формы.построить`/
`построить_поиск` плюс `modules_index.сохранить_индексы`/`поднять_индексы`.

Запуск:

    .venv/bin/python tools/lab/measure_modules_cache.py data/modules/<Конфигурация>
"""
import shutil
import sys
import time
from pathlib import Path

sys.path.insert(0, "src")

from mcp1c import index_cache, modules_index
from mcp1c.registry import KIND_MODULES, Registry, STATUS_READY, Source

КОРЕНЬ = Path(sys.argv[1]).resolve()
ИМЯ = КОРЕНЬ.name

СКРАТЧ = Path("/tmp/measure_modules_cache_data")
shutil.rmtree(СКРАТЧ, ignore_errors=True)

реестр = Registry(СКРАТЧ)
источник = Source(
    id=f"{ИМЯ}:modules",
    kind=KIND_MODULES,
    origin=ИМЯ,
    sha256="lab-sha256",  # штамп важен только для сверки промаха ниже
    status=STATUS_READY,
    stored_path=str(КОРЕНЬ),
)
реестр.sources[источник.id] = источник

# ---- сборка всех четырёх структур + запись в кэш -----------------------
начало = time.monotonic()
оглавление = modules_index.Оглавление.построить(КОРЕНЬ)
t_оглавление = time.monotonic() - начало

начало = time.monotonic()
вызовы = modules_index.Вызовы.построить(КОРЕНЬ, оглавление)
t_вызовы = time.monotonic() - начало

начало = time.monotonic()
формы = modules_index.Формы.построить(КОРЕНЬ)
t_формы = time.monotonic() - начало

начало = time.monotonic()
поиск = modules_index.построить_поиск(оглавление, КОРЕНЬ)
t_поиск = time.monotonic() - начало

индексы = modules_index.Индексы(оглавление=оглавление, вызовы=вызовы, формы=формы, поиск=поиск)

начало = time.monotonic()
modules_index.сохранить_индексы(реестр, источник.id, индексы)
t_запись = time.monotonic() - начало

сборка_и_запись = t_оглавление + t_вызовы + t_формы + t_поиск + t_запись

файлы = sorted(реестр.cache_dir.glob(f"{index_cache.safe_name(источник.id)}.*"))
итого_байт = 0
print(f"источник: {источник.id}")
print(f"оглавление : {t_оглавление:5.1f} с")
print(f"вызовы     : {t_вызовы:5.1f} с")
print(f"формы      : {t_формы:5.1f} с")
print(f"поиск      : {t_поиск:5.1f} с")
print(f"запись     : {t_запись:5.1f} с")
print(f"итого      : {сборка_и_запись:5.1f} с")
print()
print("файлы кэша:")
for путь in файлы:
    размер = путь.stat().st_size
    итого_байт += размер
    print(f"  {путь.name:45s} {размер / 1024 / 1024:7.2f} МБ")
print(f"  {'итого':45s} {итого_байт / 1024 / 1024:7.2f} МБ")

# ---- подъём из годного кэша -------------------------------------------
начало = time.monotonic()
поднятое = modules_index.поднять_индексы(реестр, источник.id)
подъём = time.monotonic() - начало
assert поднятое is not None, "кэш только что записан, обязан подняться"
print()
print(f"подъём из кэша: {подъём * 1000:.1f} мс")
print(f"  оглавление: {len(поднятое.оглавление.все())} процедур")
print(f"  вызовы: {поднятое.вызовы.рёбер} рёбер, {поднятое.вызовы.разрешённых} разрешено")
print(f"  формы: {len(поднятое.формы.модули)} форм, {поднятое.формы.битых} битых")
print(f"  поиск: {len(поднятое.поиск.docs)} документов")

# ---- испорченный файл кэша ---------------------------------------------
испорченный = реестр._cache_path(источник.id, "modules-toc")
исходные_байты = испорченный.read_bytes()
испорченный.write_bytes(b"\x00" * 32 + исходные_байты[32:])
попытка = modules_index.поднять_индексы(реестр, источник.id)
print()
print(f"испорчен modules-toc (заголовок затёрт нулями): "
      f"поднять_индексы -> {'None (пересборка)' if попытка is None else 'ОШИБКА: вернул данные!'}")
испорченный.write_bytes(исходные_байты)  # вернуть на место для следующей проверки

# ---- разошедшийся штамп (sha256 источника «изменился») -----------------
подлинный_sha256 = реестр.sources[источник.id].sha256
реестр.sources[источник.id].sha256 = "другой-хеш-как-будто-код-переразобран"
попытка = modules_index.поднять_индексы(реестр, источник.id)
print(f"разошёлся sha256 источника: "
      f"поднять_индексы -> {'None (пересборка)' if попытка is None else 'ОШИБКА: вернул данные!'}")
реестр.sources[источник.id].sha256 = подлинный_sha256

# Тот же контроль: настоящий подъём после возврата обоих файлов на место
# всё ещё работает — порча и штамп не оставили реестр в плохом состоянии.
контроль = modules_index.поднять_индексы(реестр, источник.id)
print(f"контроль после восстановления: {'кэш годен' if контроль is not None else 'ОШИБКА: кэш не поднимается'}")

shutil.rmtree(СКРАТЧ, ignore_errors=True)
