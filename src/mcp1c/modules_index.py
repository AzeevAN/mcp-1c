"""Оглавление процедур корпуса: сборка с диска, хранение, подъём.

Первая настоящая структура провайдера `modules` (design doc, раздел 4): на
ней держатся поиск процедур, «кто вызывает» и выдача тела. Строится проходом
по выгрузке — `bsl_lex.разобрать` даёт границы и `Экспорт`, `module_address.
адрес_модуля` переводит путь файла в адрес на языке метаданных.

**Хранение — параллельные массивы, а не список объектов на процедуру.**
Замерено на живой конфигурации (137 116 процедур): кортежи с текстом
сигнатуры — 128 МБ, параллельные массивы без сигнатуры — 62 МБ. Разница не
в форме массива, а в том, что каждая процедура кортежами заводит отдельный
Python-объект (кортеж + строки внутри), а `array('i')` хранит числа плотно,
без объектной обвязки на каждый элемент.

**Сигнатура принципиально не хранится.** Она лежит на диске в строке
объявления (поле `строка`), и чтение оттуда стоит 0,1 мс на модуль — держать
её в памяти постоянно значило бы платить +66 МБ за то, что достаётся
мгновенно по первому запросу.

**Ключ процедуры — пара «модуль + имя», а не одно имя.** `ПриСозданииНаСервере`
объявлена в 3 003 модулях живой конфигурации; `Запись`, отданная по одному
только имени, была бы неполной и выглядела бы как полный ответ.

**Вид (процедура или функция) — бит в тех же флагах, не отдельный массив.**
Design doc (раздел 4) перечисляет `вид[i]` в одном ряду со `строка`/`конец`/
`флаги` — в интерфейсе этой задачи поле сначала не завели, это пробел брифа,
закрытый по ревью. Отдельный `array('i')` стоил бы ещё +0,5 МБ на живом
корпусе ради одного бита на запись; вместо этого — пятый бит в `_флаги`
(`ФУНКЦИЯ`), цена которого ноль: тот же массив, тот же файл на диске. Нужен
не для полноты — у функции есть возвращаемое значение, у процедуры нет, и
агент, составляющий вызов, обязан различать это до чтения сигнатуры с диска;
не отдавать вид значило бы вынуждать потребителя гадать по имени процедуры
(«ПолучитьСумму» — наверное, функция?), а такая догадка не гарантирована
ничем и на живом корпусе будет ошибаться.

Подъём с диска (`прочитать`) обязан идти через `array.frombytes()` без
промежуточных списков: первая версия строила `list(marshal.loads(...))` и
только потом `array('i', список)` — на этом пути измерение показало 97 МБ
вместо 62. Причина — мусор аллокатора: список из миллиона `int` держит
миллион отдельных объектов, пусть и временно, и аллокатор память под них не
возвращает ОС сразу же после того, как список отброшен.
"""
from __future__ import annotations

import marshal
import sys
from array import array
from dataclasses import dataclass
from pathlib import Path

from .bsl_lex import прочитать_модуль, разобрать
from .module_address import адрес_модуля


@dataclass(slots=True)
class Запись:
    """Одна процедура оглавления — собирается по запросу из массивов.

    `функция: bool`, а не `вид: str` — тех же двух значений ("процедура" /
    "функция") строкой хотелось избежать намеренно: строка приглашает
    сравнивать её текстом (`з.вид == "Функция"`, регистр не тот — тихая
    ошибка) или, того хуже, выводить вид из имени процедуры вместо этого
    поля. `bool` такого соблазна не оставляет и совпадает по духу с
    остальными флагами записи (`экспорт`, `перекрыта`, `частичный`).
    """

    модуль: str
    имя: str
    экспорт: bool
    строка: int
    конец: int
    перекрыта: bool
    частичный: bool
    функция: bool


class Оглавление:
    """Процедуры корпуса: параллельные массивы, имена интернированы.

    Сигнатура не хранится: она лежит на диске в строке объявления, чтение
    обходится в 0,1 мс на модуль. Хранение стоило бы +66 МБ на конфигурацию.
    """

    __slots__ = ("модули", "имена", "_модуль", "_строка", "_конец", "_флаги",
                 "_по_имени", "_по_модулю")

    ЭКСПОРТ = 1
    ПЕРЕКРЫТА = 2
    ЧАСТИЧНЫЙ = 4
    ФУНКЦИЯ = 8

    def __init__(
        self,
        модули: list[str],
        имена: list[str],
        _модуль: array,
        _строка: array,
        _конец: array,
        _флаги: array,
        _по_имени: dict[str, array],
        _по_модулю: dict[str, array],
    ) -> None:
        # Приватный конструктор: собирает готовые массивы, ничего не
        # вычисляет. Публичный вход — `построить` (с диска) и `прочитать`
        # (из ранее записанного файла).
        self.модули = модули
        self.имена = имена
        self._модуль = _модуль
        self._строка = _строка
        self._конец = _конец
        self._флаги = _флаги
        self._по_имени = _по_имени
        self._по_модулю = _по_модулю

    @staticmethod
    def _индексы(
        имена: list[str], _модуль: array, модули: list[str]
    ) -> tuple[dict[str, array], dict[str, array]]:
        """Обратные индексы «имя -> позиции» и «модуль -> позиции».

        Строится и после сборки с диска, и после подъёма из файла — на диске
        эти индексы не лежат: они целиком выводятся из `имена`/`_модуль`, а
        хранить производное вторым слоем значило бы удваивать файл ради того,
        что и так пересчитывается за доли секунды одним проходом.
        """
        по_имени: dict[str, array] = {}
        по_модулю: dict[str, array] = {}
        for i, имя in enumerate(имена):
            по_имени.setdefault(имя.lower(), array("i")).append(i)
            по_модулю.setdefault(модули[_модуль[i]], array("i")).append(i)
        return по_имени, по_модулю

    @classmethod
    def построить(cls, корень: Path) -> "Оглавление":
        """Проход по выгрузке: адрес модуля из пути, процедуры — из текста.

        Порядок файлов детерминированный (`sorted`) ради воспроизводимости
        замеров и стабильного порядка индексов между прогонами — само
        оглавление от порядка не зависит.

        `адрес_модуля` не оборачивается в `try`: незнакомый каталог или файл
        выгрузки — честный отказ (см. докстроку `module_address`), а не
        объект, молча пропущенный из оглавления.
        """
        модули: list[str] = []
        индекс_модуля: dict[str, int] = {}
        имена: list[str] = []
        _модуль = array("i")
        _строка = array("i")
        _конец = array("i")
        _флаги = array("i")

        for файл in sorted(корень.rglob("*.bsl")):
            относительный = файл.relative_to(корень).as_posix()
            адрес = адрес_модуля(относительный)
            индекс = индекс_модуля.get(адрес)
            if индекс is None:
                индекс = len(модули)
                модули.append(адрес)
                индекс_модуля[адрес] = индекс

            for процедура in разобрать(прочитать_модуль(файл)):
                # Интернируем на записи, не на чтении: одно и то же имя
                # («ПриСозданииНаСервере» — 3 003 раза на живом корпусе)
                # иначе заводило бы отдельный строковый объект на каждое
                # вхождение вместо одного общего.
                имена.append(sys.intern(процедура.имя))
                _модуль.append(индекс)
                _строка.append(процедура.строка)
                _конец.append(процедура.конец)
                флаги = 0
                if процедура.экспорт:
                    флаги |= cls.ЭКСПОРТ
                if процедура.перекрытие:
                    флаги |= cls.ПЕРЕКРЫТА
                if процедура.частичный:
                    флаги |= cls.ЧАСТИЧНЫЙ
                if процедура.вид == "функция":
                    флаги |= cls.ФУНКЦИЯ
                _флаги.append(флаги)

        по_имени, по_модулю = cls._индексы(имена, _модуль, модули)
        return cls(модули, имена, _модуль, _строка, _конец, _флаги, по_имени, по_модулю)

    def записать(self, путь: Path) -> None:
        """Сохраняет параллельные массивы на диск через `marshal`.

        Обратные индексы (`по_имени`, `по_модулю`) не пишутся — они
        производные от `имена`/`_модуль` и пересчитываются на подъёме.
        Массивы идут байтами (`tobytes()`), не списками: `marshal` умеет
        сохранять `array` только как обычную последовательность чисел, а
        это для миллиона элементов дороже и на запись, и на чтение.
        """
        данные = {
            "модули": self.модули,
            "имена": self.имена,
            "модуль": self._модуль.tobytes(),
            "строка": self._строка.tobytes(),
            "конец": self._конец.tobytes(),
            "флаги": self._флаги.tobytes(),
        }
        путь.write_bytes(marshal.dumps(данные))

    @classmethod
    def прочитать(cls, путь: Path) -> "Оглавление":
        """Поднимает оглавление из файла `записать`.

        Массивы поднимаются `frombytes()` напрямую в пустой `array('i')`,
        без промежуточного `list` — см. докстрою модуля про 97 МБ вместо 62.
        """
        данные = marshal.loads(путь.read_bytes())

        _модуль = array("i")
        _модуль.frombytes(данные["модуль"])
        _строка = array("i")
        _строка.frombytes(данные["строка"])
        _конец = array("i")
        _конец.frombytes(данные["конец"])
        _флаги = array("i")
        _флаги.frombytes(данные["флаги"])

        модули = данные["модули"]
        имена = данные["имена"]
        по_имени, по_модулю = cls._индексы(имена, _модуль, модули)
        return cls(модули, имена, _модуль, _строка, _конец, _флаги, по_имени, по_модулю)

    def _запись(self, i: int) -> Запись:
        флаги = self._флаги[i]
        return Запись(
            модуль=self.модули[self._модуль[i]],
            имя=self.имена[i],
            экспорт=bool(флаги & self.ЭКСПОРТ),
            строка=self._строка[i],
            конец=self._конец[i],
            перекрыта=bool(флаги & self.ПЕРЕКРЫТА),
            частичный=bool(флаги & self.ЧАСТИЧНЫЙ),
            функция=bool(флаги & self.ФУНКЦИЯ),
        )

    def все(self) -> list[Запись]:
        """Все процедуры корпуса — для полного прохода (сборка других индексов)."""
        return [self._запись(i) for i in range(len(self.имена))]

    def по_имени(self, имя: str) -> list[Запись]:
        """Все процедуры с этим именем во всех модулях, без учёта регистра.

        Может вернуть несколько записей — ключ оглавления «модуль + имя»,
        не одно имя (докстрока модуля).
        """
        return [self._запись(i) for i in self._по_имени.get(имя.lower(), ())]

    def модуля(self, адрес: str) -> list[Запись]:
        """Все процедуры модуля, включая неэкспортные."""
        return [self._запись(i) for i in self._по_модулю.get(адрес, ())]

    def известно(self, имя: str) -> bool:
        """Объявлена ли хоть одна процедура с этим именем где-либо в корпусе.

        Дешёвый сторож для индекса вызовов (задача 6, `Вызовы.построить`):
        на живом корпусе кандидатов в вызовы около миллиона, и строить на
        каждом `Запись`-объекты через `по_имени` только ради проверки
        «есть или нет» значило бы платить за то, что тут же выбрасывается.
        Словарь `_по_имени` для этого и существует.
        """
        return имя.lower() in self._по_имени


@dataclass(slots=True)
class Место:
    """Одно место вызова — модуль-вызыватель, строка и, если удалось
    разрешить, адрес модуля-цели."""

    модуль: str
    строка: int
    цель: str | None


class Вызовы:
    """Индекс вызовов корпуса: «кто вызывает эту процедуру», с разрешением
    цели до модуля там, где это возможно (design doc, раздел 4).

    **Ключ по одному имени врёт.** `ПриСозданииНаСервере` объявлена в
    3 003 модулях живой конфигурации — агент, спросивший «кто вызывает мою
    процедуру» и получивший ответ по имени, получит два десятка чужих
    мест и либо решит, что правка задевает пол-конфигурации, либо, что
    хуже, не увидит настоящего вызывающего среди них и сделает вывод
    «никто не вызывает, менять безопасно». Поэтому ребро несёт третье
    поле — индекс модуля-цели или −1, а не только имя.

    Разрешается только то, в чём мы уверены (`_разрешить`):
    квалифицированный вызов `Х.Метод(`, где `Х` — имя общего модуля
    корпуса, и неквалифицированный вызов, чьё имя объявлено в самом
    модуле-вызывателе. Остальное остаётся −1 и честно называется в ответе
    (это забота задачи 14) — подставлять «похоже, это оно» здесь так же
    неуместно, как и в `module_address`.

    **Фильтр «имя объявлено где-то в корпусе».** Вызов платформенного
    метода (`ЗначениеЗаполнено`, `Сообщить`) целью быть не может — ни один
    модуль корпуса такое имя не объявляет — и такое ребро не индексируется
    вовсе, а не заводится неразрешённым: без фильтра рёбер на 63% больше
    (1 009 479 против 619 030 на живой выгрузке), и все они бесполезны.

    **Хранение — `имя цели -> array('i')` плоских троек** «модуль-вызыватель,
    строка, модуль-цель или −1» на ключ, без объекта на ребро. Группировка
    по имени уже есть на этапе сборки — `места(имя)` для этого и вызывается
    — так что отдельного параллельного массива с именем на каждое ребро
    (619 030 интернированных ссылок) заводить незачем: имя один раз лежит
    ключом словаря, а не миллион раз копией указателя. Замер живой
    выгрузки: 619 030 рёбер, 52% разрешено, 51 МБ при подъёме.
    """

    __slots__ = ("модули", "_по_имени", "рёбер", "разрешённых")

    def __init__(
        self,
        модули: list[str],
        _по_имени: dict[str, array],
        рёбер: int,
        разрешённых: int,
    ) -> None:
        # Приватный конструктор, как у Оглавление: собирает готовые данные,
        # ничего не вычисляет. Публичный вход — `построить` и `прочитать`.
        self.модули = модули
        self._по_имени = _по_имени
        self.рёбер = рёбер
        self.разрешённых = разрешённых

    @staticmethod
    def _общие_модули(модули: list[str]) -> dict[str, int]:
        """Имя общего модуля (без вида) -> его индекс в списке модулей корпуса.

        Разрешаются только квалифицированные вызовы к ОБЩИМ модулям: у
        остальных видов квалификатор перед вызовом — это имя переменной
        объекта (`Объект.Общая()`), а не имя типа, и совпадение с адресом
        модуля там ничего не доказывает — ровно та подстановка, от которой
        уходит разрешение до модуля.
        """
        return {
            адрес.split(".", 1)[1].lower(): i
            for i, адрес in enumerate(модули)
            if адрес.startswith("ОбщийМодуль.")
        }

    @staticmethod
    def _разрешить(
        квалификатор: str, имя: str, модуль: int,
        общие: dict[str, int], свои: set[str],
    ) -> int:
        """Индекс модуля-цели или −1.

        Разрешаем только то, в чём уверены: остальное честно помечается в
        ответе. Ключ по одному имени врал бы — `ПриСозданииНаСервере`
        объявлена в 3 003 модулях живой конфигурации.

        `@staticmethod`, а не метод экземпляра (в отличие от чернового
        вида в брифе задачи): вызывается из `построить` до того, как
        экземпляр `Вызовы` собран — `self` тут неоткуда взять, а тело и
        так не трогает состояние объекта.
        """
        if квалификатор:
            return общие.get(квалификатор.lower(), -1)
        return модуль if имя in свои else -1

    @classmethod
    def построить(cls, корень: Path, оглавление: "Оглавление") -> "Вызовы":
        """Второй проход по выгрузке: места вызова из `Процедура.вызовы`,
        которых оглавление не хранит (оно помнит только границы объявлений).

        `оглавление` принимается готовым, а не строится заново: `известно`
        (фильтр по корпусу) и список объявленных в модуле имён (для «своих»
        неквалифицированных вызовов) — это уже посчитанный проходом задачи 5
        ответ, и второй полный обход исходников ради тех же чисел был бы
        пустой тратой времени сборки.
        """
        адрес_к_индексу = {адрес: i for i, адрес in enumerate(оглавление.модули)}
        общие = cls._общие_модули(оглавление.модули)

        _по_имени: dict[str, array] = {}
        рёбер = 0
        разрешённых = 0

        for файл in sorted(корень.rglob("*.bsl")):
            относительный = файл.relative_to(корень).as_posix()
            адрес = адрес_модуля(относительный)
            индекс_модуля = адрес_к_индексу[адрес]
            # Имена, объявленные в ЭТОМ модуле — для неквалифицированных
            # вызовов (`_разрешить`). Не только имя самой вызывающей
            # процедуры: любая процедура модуля годится целью, так что
            # набор строится по всему модулю разом, один раз на файл.
            свои = {
                оглавление.имена[i].lower()
                for i in оглавление._по_модулю.get(адрес, ())
            }

            for процедура in разобрать(прочитать_модуль(файл)):
                for квалификатор, имя, строка in процедура.вызовы:
                    # Платформенный метод корпусом не объявлен нигде — не
                    # индексируем вовсе (докстрока класса, 63%).
                    if not оглавление.известно(имя):
                        continue
                    ключ = имя.lower()
                    цель = cls._разрешить(
                        квалификатор, ключ, индекс_модуля, общие, свои
                    )
                    массив = _по_имени.get(ключ)
                    if массив is None:
                        массив = array("i")
                        _по_имени[ключ] = массив
                    массив.append(индекс_модуля)
                    массив.append(строка)
                    массив.append(цель)
                    рёбер += 1
                    if цель != -1:
                        разрешённых += 1

        return cls(оглавление.модули, _по_имени, рёбер, разрешённых)

    def записать(self, путь: Path) -> None:
        """Сохраняет рёбра на диск через `marshal` — тот же приём, что у
        `Оглавление.записать`: массивы идут байтами (`tobytes()`), не
        списками чисел, дороже на запись и на чтение вдвое-втрое.
        """
        данные = {
            "модули": self.модули,
            "по_имени": {имя: массив.tobytes() for имя, массив in self._по_имени.items()},
        }
        путь.write_bytes(marshal.dumps(данные))

    @classmethod
    def прочитать(cls, путь: Path) -> "Вызовы":
        """Поднимает индекс вызовов из файла `записать`.

        Оглавление сюда не нужно: адреса модулей и уже разрешённые цели
        лежат в самом файле, второй проход по исходникам на подъёме не
        требуется. Массивы поднимаются `frombytes()` напрямую в пустой
        `array('i')`, без промежуточного `list` — см. докстроку модуля.
        """
        данные = marshal.loads(путь.read_bytes())

        _по_имени: dict[str, array] = {}
        рёбер = 0
        разрешённых = 0
        for имя, байты in данные["по_имени"].items():
            массив = array("i")
            массив.frombytes(байты)
            _по_имени[имя] = массив
            for i in range(2, len(массив), 3):
                рёбер += 1
                if массив[i] != -1:
                    разрешённых += 1

        return cls(данные["модули"], _по_имени, рёбер, разрешённых)

    def _место(self, модуль: int, строка: int, цель: int) -> Место:
        return Место(
            модуль=self.модули[модуль],
            строка=строка,
            цель=self.модули[цель] if цель != -1 else None,
        )

    def места(self, имя: str) -> list[Место]:
        """Все места вызова процедуры с этим именем, без учёта регистра.

        `цель` заполнена только там, где источник надёжен (докстрока
        класса и `_разрешить`); иначе — `None`, а не имя, угаданное по
        совпадению.
        """
        массив = self._по_имени.get(имя.lower())
        if массив is None:
            return []
        return [
            self._место(массив[i], массив[i + 1], массив[i + 2])
            for i in range(0, len(массив), 3)
        ]
