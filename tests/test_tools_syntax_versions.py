def test_отказ_называет_справку_версии_конфигурации(tmp_path):
    """«Такого элемента нет» подписывалось чужой версией справки.

    Отказ брал номер у объединённого источника — самой свежей справки. На
    конфигурации 8.3.5 при загруженных 8.3.5 и 8.3.27 выходило «в справке
    платформы 8.3.27 нет элемента X, доступного в версии 8.3.5»: названа
    справка, по которой ответ не строился. Тот же класс, что и строка списка
    конфигураций.
    """
    incoming = tmp_path / "incoming"
    registry = реестр(
        tmp_path,
        [
            справка(incoming, "8.3.5.1570", {"Глобальный контекст.Найти": "Найти(<Строка>)"}),
            справка(incoming, "8.3.27.2130", {"Глобальный контекст.СтрНайти": "СтрНайти(<Строка>)"}),
        ],
        "8.3.5.1570",
    )

    ответ = get_syntax(registry, "ЗаписьJSON.ЗаписатьНачалоОбъекта")

    assert "8.3.5.1570" in ответ
    assert "8.3.27" not in ответ
