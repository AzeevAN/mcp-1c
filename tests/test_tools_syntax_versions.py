"""Что инструменты отвечают, когда справок несколько.

Три состояния, и они разные: элемент не менялся — отвечаем без оговорок;
менялся, а версия конфигурации попала между справками — отдаём оба состояния;
элемента в этой версии нет — говорим прямо. Молчание не остаётся нигде.
"""

from __future__ import annotations

from mcp1c.registry import Registry
from mcp1c.store import save_syntax
from mcp1c.syntax_model import SyntaxIndex, SyntaxItem, SyntaxVariant
from mcp1c.tools import get_syntax, search_syntax

from conftest import build_configuration, write_export


def справка(directory, platform: str, элементы: dict[str, str], *, доступность=None):
    """Разобранная справка версии: имя -> сигнатура (пустая для свойства)."""
    directory.mkdir(parents=True, exist_ok=True)
    index = SyntaxIndex(platforms=[platform], source=f"test-{platform}")
    for полное, сигнатура in элементы.items():
        владелец, _, имя = полное.rpartition(".")
        item = SyntaxItem(
            id=f"objects/{владелец}/methods/{имя}",
            kind="method" if сигнатура else "property",
            name_ru=имя,
            parent_ru=владелец,
            description=f"Описание {имя}",
            availability=list(доступность or []),
        )
        if сигнатура:
            item.variants = [SyntaxVariant(signature=сигнатура)]
        index.add(item)
    return save_syntax(index, directory / f"{platform}.json.gz")


def реестр(tmp_path, справки: list, платформа_конфигурации: str) -> Registry:
    registry = Registry(tmp_path / "data")
    for путь in справки:
        registry.add_syntax(путь)
    config = build_configuration()
    config.platform = платформа_конфигурации
    registry.add_configuration(write_export(tmp_path / "incoming", config))
    return registry


def test_карточка_отдаёт_сигнатуру_версии_конфигурации(tmp_path):
    incoming = tmp_path / "incoming"
    registry = реестр(
        tmp_path,
        [
            справка(incoming, "8.3.5.1570", {"ЗаписьXML.ОткрытьФайл": "ОткрытьФайл(<ИмяФайлаXML>, <ТипКодировки>)"}),
            справка(incoming, "8.3.27.2130", {"ЗаписьXML.ОткрытьФайл": "ОткрытьФайл(<ИмяФайлаXML>, <ТипКодировки>, <ДобавлятьBOM>)"}),
        ],
        "8.3.5.1570",
    )

    ответ = get_syntax(registry, "ЗаписьXML.ОткрытьФайл")

    assert "ОткрытьФайл(<ИмяФайлаXML>, <ТипКодировки>)" in ответ
    assert "ДобавлятьBOM" not in ответ


