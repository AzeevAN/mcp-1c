"""Ранжирование поиска: что именно и в каком порядке возвращается.

Сеть безопасности под оптимизацию `search()`. Проверяется не «похоже», а
точный порядок, потому что цена ускорения — незаметно съехавшая выдача:
поиск при этом работает и выглядит правдоподобно.
"""

from __future__ import annotations

from mcp1c.search import Doc, SearchIndex


def _index(**kwargs) -> SearchIndex:
    docs = [
        Doc(
            id="Справочник.Номенклатура",
            kind="Справочник",
            payload="номенклатура",
            exact_keys=["Справочник.Номенклатура"],
            boost=1.0,
            fields={"name": "Номенклатура", "synonym": "Номенклатура", "kind": "Справочник"},
        ),
        Doc(
            id="Документ.РеализацияТоваровУслуг",
            kind="Документ",
            payload="реализация",
            exact_keys=["Документ.РеализацияТоваровУслуг"],
            boost=1.0,
            fields={
                "name": "РеализацияТоваровУслуг",
                "synonym": "Реализация товаров и услуг",
                "kind": "Документ",
            },
        ),
        Doc(
            id="Обработка.ЗагрузкаНоменклатуры",
            kind="Обработка",
            payload="загрузка",
            exact_keys=["Обработка.ЗагрузкаНоменклатуры"],
            boost=0.3,
            fields={
                "name": "ЗагрузкаНоменклатуры",
                "synonym": "Загрузка номенклатуры",
                "kind": "Обработка",
            },
        ),
        Doc(
            id="Отчет.ОстаткиНоменклатуры",
            kind="Отчет",
            payload="остатки",
            boost=0.3,
            fields={"name": "ОстаткиНоменклатуры", "synonym": "Остатки номенклатуры"},
        ),
    ]
    return SearchIndex(docs, **kwargs)


def test_порядок_выдачи_по_нескольким_словам():
    hits = _index().search("загрузка номенклатуры")

    assert [h.doc.id for h in hits] == [
        "Обработка.ЗагрузкаНоменклатуры",
        "Справочник.Номенклатура",
        "Отчет.ОстаткиНоменклатуры",
    ]


def test_частичное_совпадение_объясняется_без_пустой_причины():
    hits = _index().search("загрузка номенклатуры")

    assert [hit.reason for hit in hits] == [
        "точное совпадение",
        "совпала часть слов запроса",
        "совпала часть слов запроса",
    ]
    assert all(hit.reason for hit in hits)


def test_все_слова_запроса_отмечаются_в_причине():
    """Причина ставится, когда покрыт весь запрос и не сработало сильнее.

    Запрос «загрузка номенклатуры» сюда не годится: он совпадает с синонимом
    целиком, а это более сильный сигнал и другая причина.
    """
    hits = _index().search("реализация услуг")

    assert hits[0].doc.id == "Документ.РеализацияТоваровУслуг"
    assert hits[0].reason == "все слова запроса"

    # Совпадение строки целиком — сигнал сильнее, и причина другая.
    assert _index().search("остатки номенклатуры")[0].reason == "точное совпадение"


def test_точное_совпадение_целой_строки_вне_конкуренции():
    hits = _index().search("Справочник.Номенклатура")

    assert hits[0].doc.id == "Справочник.Номенклатура"
    assert hits[0].reason == "точное совпадение"


def test_псевдоним_бьёт_текстовое_совпадение():
    index = _index(aliases={"загрузка номенклатуры": ["Справочник.Номенклатура"]})

    hits = index.search("загрузка номенклатуры")

    assert hits[0].doc.id == "Справочник.Номенклатура"
    assert hits[0].reason == "псевдоним из словаря"


def test_псевдоним_работает_без_единого_совпавшего_слова():
    """Локальный слой словаря заведён под чужую терминологию внедрения.

    У жаргона и внутренних сокращений пересечения с именами объектов нет —
    иначе псевдоним был бы не нужен. Требовать лексического совпадения значит
    отключать псевдоним ровно там, где он единственный способ попасть в цель.
    """
    index = _index(aliases={"шахна": ["Справочник.Номенклатура"]})

    hits = index.search("шахна")

    assert [h.doc.id for h in hits] == ["Справочник.Номенклатура"]
    assert hits[0].reason == "псевдоним из словаря"


def test_все_цели_псевдонима_идут_впереди_текстовых_совпадений():
    index = _index(aliases={"номенклатура": ["Отчет.ОстаткиНоменклатуры"]})

    hits = index.search("номенклатура")

    assert hits[0].doc.id == "Отчет.ОстаткиНоменклатуры"
    assert hits[0].reason == "псевдоним из словаря"
    assert "Справочник.Номенклатура" in [h.doc.id for h in hits[1:]]


def test_порядок_в_словаре_решает_при_прочих_равных():
    """Среди целей псевдонима обычное ранжирование продолжает работать.

    Вес по виду объекта и нормирование по длине имени сильнее порядка в
    словаре: он добавляет один балл и решает только при равенстве остального.
    Так и задумано — псевдоним поднимает цели наверх, но не отменяет знание о
    том, где живут данные.
    """
    fields = {"name": "Контрагенты", "synonym": "Контрагенты"}
    index = SearchIndex(
        [
            Doc(id="Справочник.Первый", kind="Справочник", fields=dict(fields), boost=1.0),
            Doc(id="Справочник.Второй", kind="Справочник", fields=dict(fields), boost=1.0),
        ],
        aliases={"шахна": ["Справочник.Второй", "Справочник.Первый"]},
    )

    hits = index.search("шахна")

    assert [h.doc.id for h in hits] == ["Справочник.Второй", "Справочник.Первый"]


def test_несуществующий_объект_в_псевдониме_не_выдумывается():
    index = _index(aliases={"шахна": ["Справочник.ЧегоНетВКонфигурации"]})

    assert index.search("шахна") == []


def test_ничья_разрешается_по_идентификатору():
    """Два одинаковых документа обязаны идти в предсказуемом порядке.

    Иначе выдача пляшет от запуска к запуску, и стенд замеров врёт.
    """
    fields = {"name": "Контрагенты", "synonym": "Контрагенты"}
    index = SearchIndex(
        [
            Doc(id="Справочник.Б", kind="Справочник", fields=dict(fields), boost=1.0),
            Doc(id="Справочник.А", kind="Справочник", fields=dict(fields), boost=1.0),
            Doc(id="Справочник.В", kind="Справочник", fields=dict(fields), boost=1.0),
        ]
    )

    hits = index.search("контрагенты")

    assert [h.doc.id for h in hits] == ["Справочник.А", "Справочник.Б", "Справочник.В"]
    assert len({round(h.score, 9) for h in hits}) == 1, "оценки должны быть равны"


def test_ограничение_числа_ответов():
    hits = _index().search("номенклатура", limit=2)

    assert len(hits) == 2
    assert [h.doc.id for h in hits] == [
        h.doc.id for h in _index().search("номенклатура")[:2]
    ]


def test_фильтр_по_виду_объекта():
    hits = _index().search("номенклатура", kinds=["Отчет"])

    assert [h.doc.id for h in hits] == ["Отчет.ОстаткиНоменклатуры"]


def test_предикат_отсекает_документы():
    hits = _index().search("номенклатура", predicate=lambda doc: doc.kind != "Справочник")

    assert "Справочник.Номенклатура" not in [h.doc.id for h in hits]


def test_синоним_засчитывается_исходному_слову_запроса():
    """Покрытие считается по словам запроса, а не по подстановкам.

    Иначе документ, поймавший три синонима одного слова, выглядел бы
    покрывшим три слова запроса.
    """
    index = _index(synonyms={"товары": frozenset({"номенклатура"})})

    hits = index.search("товары")

    assert hits[0].doc.id == "Справочник.Номенклатура"
    assert hits[0].reason == "все слова запроса"


def test_поля_документа_освобождаются_после_заморозки():
    """Поиск читает постинги, а не поля документа.

    После заморозки индекса `fields` и `exact_keys` больше не нужны, а весят
    заметно: на справке это описания по 400 символов на 25 тысяч документов.
    """
    index = _index()
    assert index.docs["Справочник.Номенклатура"].fields

    index.search("номенклатура")

    assert not index.docs["Справочник.Номенклатура"].fields
    assert not index.docs["Справочник.Номенклатура"].exact_keys


def test_освобождение_полей_не_ломает_выдачу():
    index = _index()
    before = [(h.doc.id, h.score) for h in index.search("загрузка номенклатуры")]

    after = [(h.doc.id, h.score) for h in index.search("загрузка номенклатуры")]

    assert after == before


def test_документ_добавленный_после_поиска_находится():
    """Индекс достраивается уже после первого запроса.

    Так работает `reg-add` на живом сервере, и внутренние структуры обязаны
    пересобираться, а не остаться от прошлого состояния.
    """
    index = _index()
    index.search("контрагенты")

    index.add(
        Doc(
            id="Справочник.Контрагенты",
            kind="Справочник",
            payload="контрагенты",
            exact_keys=["Справочник.Контрагенты"],
            boost=1.0,
            fields={"name": "Контрагенты", "synonym": "Контрагенты"},
        )
    )

    assert [h.doc.id for h in index.search("контрагенты")] == ["Справочник.Контрагенты"]
    # Документы, добавленные до заморозки, обязаны остаться на месте.
    assert [h.doc.id for h in index.search("реализация услуг")] == [
        "Документ.РеализацияТоваровУслуг"
    ]


