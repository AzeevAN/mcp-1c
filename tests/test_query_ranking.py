"""Ранжирование языка запросов против платформы — три меры из задачи query-ranking.

Часть 1: описание статьи языка запросов индексируется целиком, а не по
потолку в 400 символов, который считался для короткого описания метода
платформы (`search.py`, `index_syntax`).

Часть 2: явный оборот вроде «в запросе» мягко поднимает элементы языка
запросов при ранжировании (`search.py`, `SearchIndex.search`), не выключая
победу платформенного элемента при уверенном отрыве.
"""

from __future__ import annotations

import pytest

from mcp1c.search import Doc, SearchIndex, index_syntax
from mcp1c.syntax_model import KIND_QUERY_ARTICLE, SyntaxIndex, SyntaxItem

# --------------------------------------------------------------- часть 1: потолок описания


def _syntax_with_tail_word(kind: str, tail_word: str) -> SyntaxIndex:
    """Справка из одного элемента: слово-маркер только в хвосте, за 400 символом."""
    index = SyntaxIndex(platforms=[] if kind == KIND_QUERY_ARTICLE else ["8.3.99.1"],
                         source="query-ranking-test", language="ru")
    вступление = "Вступление про запросы и таблицы. " * 20  # 35*20=700 симв.
    описание = вступление + tail_word
    assert описание.index(tail_word) > 400  # без этого тест ничего не проверяет
    index.add(
        SyntaxItem(
            id="test/long",
            kind=kind,
            name_ru="Длинный элемент",
            name_en="long",
            description=описание,
        )
    )
    return index


def test_описание_статьи_языка_запросов_индексируется_целиком():
    """Раньше в индекс шли первые 400 символов описания — у статей это
    2-5% текста (страницы весят 8-24,8 КБ), потому что для них описание и
    есть содержимое, а не краткая аннотация. Слово из хвоста статьи обязано
    находиться."""
    built = index_syntax(_syntax_with_tail_word(KIND_QUERY_ARTICLE, "разыменование"))

    hits = built.search("разыменование")

    assert [h.doc.id for h in hits] == ["test/long"]


def test_описание_метода_платформы_остаётся_обрезанным_до_400():
    """Потолок снят только для видов языка запросов. У методов платформы
    описание короткое и потолок не бил — менять для них поведение молча
    нельзя, иначе индекс раздуется без измеренной пользы."""
    built = index_syntax(_syntax_with_tail_word("method", "хвостовоеслово"))

    hits = built.search("хвостовоеслово")

    assert hits == []


# --------------------------------------------------------------- часть 2: подъём по обороту


def _platform_vs_query_docs(
    name: str,
    platform_id: str,
    query_id: str,
    platform_boost: float,
    query_boost: float = 1.0,
) -> list[Doc]:
    """Платформенный и языковой элемент с одинаковым именем и разным `boost`.

    `boost` — управляемая ручка, чтобы задать нужный разрыв счёта без борьбы
    с токенизацией: одинаковые поля дают одинаковый базовый счёт, и весь
    разрыв между документами определяется только этим множителем.
    """
    return [
        Doc(id=platform_id, kind="property", boost=platform_boost, fields={"name": name}),
        Doc(id=query_id, kind=KIND_QUERY_ARTICLE, boost=query_boost, fields={"name": name}),
    ]


# Сценарий из `tests/queries/query-language.json`: свойство платформы
# `QuerySchemaUnionType.ОбъединитьВсе` называется почти так же, как статья
# «ОБЪЕДИНИТЬ [ВСЕ]», и обходит её по счёту точных слов (2 место вместо 1).
def _union_docs(platform_boost: float, query_boost: float = 1.0) -> list[Doc]:
    return _platform_vs_query_docs(
        "ОбъединитьВсе",
        "objects/property.ОбъединитьВсе",
        "query/UNIONSection",
        platform_boost,
        query_boost,
    )


@pytest.mark.parametrize(
    "отрыв, победитель",
    [
        # Чуть меньше множителя — подъём отыгрывает: 41,1071 против 40,7645.
        (1.19, "query/UNIONSection"),
        # Чуть больше — уже нет: 41,4496 против 41,1071.
        (1.21, "objects/property.ОбъединитьВсе"),
    ],
)
def test_подъём_отыгрывает_отрыв_ровно_до_множителя(отрыв, победитель):
    """Где именно проходит граница подъёма — а не «где-то в этой области».

    Тест снят с двух прежних, проверявших одно и то же: `«ОбъединитьВсе»` и
    `«объединить все»` после `split_identifier` дают одинаковые токены, то
    есть это был один и тот же запрос дважды.

    Ровно на 1,2 счёт сходится вничью до последнего бита (41,107076 против
    41,107076), и победителя выбирает порядок сортировки, а не правило.
    Проверяются поэтому обе стороны границы, а не она сама: тест на ничью
    закреплял бы за правило то, что правилом не является.
    """
    index = SearchIndex(_union_docs(platform_boost=отрыв))

    hits = index.search("объединить все в запросе")

    assert hits[0].doc.id == победитель


@pytest.mark.parametrize(
    "оборот",
    ["в запросе", "в тексте запроса", "в выборке", "языка запросов"],
)
def test_оборот_домена_поднимает_статью_языка_запросов(оборот):
    """Разрыв 1,15/1,0 меньше подъёма 1,2 — статья выходит вперёд.

    Одновременно доказывает, что подъём не задевает платформенный элемент:
    задень он оба вида одинаково, отношение 1,15/1,0 сохранилось бы, и
    статья не смогла бы обойти свойство.
    """
    index = SearchIndex(_union_docs(platform_boost=1.15))

    hits = index.search(f"объединить все {оборот}")

    assert hits[0].doc.id == "query/UNIONSection"


def test_оборот_не_отыгрывает_уверенный_отрыв_платформенного_элемента():
    """При разрыве больше 20% мягкий подъём 1,2 не должен переставлять
    победителя — иначе «как задать параметр в запросе» перестал бы находить
    платформенный `Запрос.УстановитьПараметр` там, где человек спрашивал
    именно про него."""
    docs = _platform_vs_query_docs(
        "Параметр",
        "objects/method.УстановитьПараметр",
        "query/consts_and_parameters.html",
        platform_boost=1.3,
    )
    index = SearchIndex(docs)

    hits = index.search("параметр в запросе")

    assert hits[0].doc.id == "objects/method.УстановитьПараметр"


def test_без_оборота_подъёма_нет_и_при_маленьком_отрыве():
    """Базовый промах и контроль разом.

    Без оборота из словаря даже небольшой отрыв (1,15/1,0) не отыгрывается:
    подъём применяется только при явном обороте. Это же и есть исходное
    состояние промаха, ради которого подъём заводился.
    """
    index = SearchIndex(_union_docs(platform_boost=1.15))

    hits = index.search("объединить все")

    assert hits[0].doc.id == "objects/property.ОбъединитьВсе"
