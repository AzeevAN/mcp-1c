def _build() -> dict[str, frozenset[str]]:
    table: dict[str, set[str]] = {}
    for group in SYNONYM_GROUPS:
        for word in group:
            table.setdefault(word, set()).update(w for w in group if w != word)
    return {word: frozenset(values) for word, values in table.items()}


SYNONYMS: dict[str, frozenset[str]] = _build()


def expand(token: str) -> frozenset[str]:
    """Слова, которыми может быть названо то же самое."""
    return SYNONYMS.get(token, frozenset())


